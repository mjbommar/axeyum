#!/usr/bin/env python3
"""A held-out row that REDUCES is not blind, whatever anyone proved about it.

Draw 7 preregistered `fermat-numbers` held-out at 2026-08-30 07:09:52. Twenty-one
minutes earlier, at 06:48:10, `Nat.fermatNumber` was admitted. Three of the ten
rows are

    Nat.fermatNumber 0 = 3      Nat.fermatNumber 1 = 5      Nat.fermatNumber 2 = 17

and each of those closes by `Eq.refl` the moment the `Definition` exists,
because both sides are ground and the kernel decides them by reduction. Nobody
had to prove anything. R9 -- which screens the MATHLIB SOURCE NAMES
`Nat.fermatNumber_zero` and siblings, none of which is declared here -- reported
a clean 0 of 10 and was right about the question it asks.

**The evaluation test is not the cause, and this matters for what to do about
it.** ADR-0653 exempted the mandatory `Definition` evaluation test on the
ground that "a test is not a declaration". True, and beside the point: the
`Definition` is the declaration, and deleting
`fermat_number_evaluates_correctly` would not have made those three rows blind
again. So the remedy cannot be "write the test later" or "evaluate somewhere
else" -- CLAUDE.md requires that test precisely because the trusted gate cannot
tell you a definition is wrong. The remedy is to stop DRAWING rows that the
construction already settles. ADR-0695.

What this checks: for every held-out row in both nursery manifests, whether its
Mathlib proposition is a CLOSED EVALUATION -- a binder-free equation whose only
vocabulary is numerals and constants already declared in this kernel. Such a row
is decided by reduction and is not blind, so it is a violation.

FAIL-CLOSED, and on more than the usual axes:

  * a missing/unreadable manifest, an empty held-out population, or a missing
    environment snapshot is an error, not a pass;
  * **the classifier is self-tested on every run** against a pinned fixture
    table that includes the three real Fermat statements as positives and their
    binder-carrying siblings as negatives. Today's population contains ZERO
    closed-evaluation rows (they were amended out), so without that table this
    gate would print `violations=0` whether or not it still worked -- which is
    the failure this repository cares most about. If the classifier stops
    discriminating, the gate fails on its own fixtures before it looks at a
    single real row.

A constant counts as declared if the committed environment snapshot names it,
OR if the kernel crate's source carries a plausible `snake_case` field for it.
The second is not redundant: the snapshot is regenerated by hand and goes stale
FAIL-OPEN for exactly this screen (a construction declared minutes ago reads as
absent, so its rows read as blind), which is how the Fermat window opened. The
source fallback over-approximates, and that direction is safe here: over-calling
a constant "declared" can only make this gate refuse a draw, never admit one.
"""

from __future__ import annotations

import json
import pathlib
import re
import sys
from typing import Any

ROOT = pathlib.Path(__file__).resolve().parents[1]
NURSERY = ROOT / "artifacts/autogenesis/nursery-v1.json"
EXTENSION = ROOT / "artifacts/autogenesis/nursery-v2-extension.json"
FACTS = ROOT / "artifacts/facts"
SNAPSHOT = ROOT / "artifacts/autogenesis/kernel-environment-snapshot-v1.json"
KERNEL_SRC = ROOT / "crates/axeyum-lean-kernel/src"

# Anything that introduces a variable, a hypothesis or a set-builder means the
# proposition is not ground, so reduction alone cannot decide it. `:` is in the
# list because every binder in this surface syntax carries one, and a ground
# equation never does.
BINDER = re.compile(r"[∀∃→↔¬,{}\[\]:∑∏]")
# A dotted or bare identifier. Unicode letters are excluded deliberately: `ℕ`
# and friends only appear inside binders, which are already rejected.
IDENT = re.compile(r"[A-Za-z_][A-Za-z0-9_']*(?:\.[A-Za-z_][A-Za-z0-9_']*)*")
NUMERAL = re.compile(r"\A[0-9]+\Z")

# Every token a ground arithmetic equation may contain besides identifiers and
# numerals. A statement using anything else is not classified, which is the
# conservative direction: this gate refuses to guess.
ALLOWED_PUNCT = set(" ()=+-*/^%≤≥≠⋅")


class ClosedEvaluationError(Exception):
    pass


# ---------------------------------------------------------------------------
# the classifier


def is_closed_evaluation(statement: str) -> bool:
    """Is this Mathlib proposition a binder-free equation over ground terms?

    Not "is it true" and not "does the kernel decide it" -- only whether its
    SHAPE admits decision by reduction. Whether the vocabulary is actually
    declared here is a separate question, asked by the caller, because the two
    fail in opposite directions and conflating them hides which one moved.
    """
    text = statement.strip()
    if not text or BINDER.search(text):
        return False
    if "=" not in text:
        return False
    residue = IDENT.sub(" ", text)
    residue = re.sub(r"[0-9]+", " ", residue)
    if any(ch not in ALLOWED_PUNCT for ch in residue):
        return False
    # At least one side must be a bare numeral, and at least one identifier must
    # appear. `1 = 1` is not a nursery row and `Foo = Bar` is not an evaluation.
    sides = [s.strip() for s in text.split("=")]
    if len(sides) != 2:
        return False
    if not any(NUMERAL.match(s) for s in sides):
        return False
    return bool(IDENT.search(text))


def constants(statement: str) -> set[str]:
    return {m.group(0) for m in IDENT.finditer(statement)}


# ---------------------------------------------------------------------------
# the classifier's own fixtures, checked on every run


CLASSIFIER_FIXTURES: list[tuple[str, bool, str]] = [
    # The three rows that were actually spent. Verbatim `formal.statement`
    # values from artifacts/facts, read 2026-08-30.
    ("Nat.fermatNumber 0 = 3", True, "the row draw 7 spent"),
    ("Nat.fermatNumber 1 = 5", True, "the row draw 7 spent"),
    ("Nat.fermatNumber 2 = 17", True, "the row draw 7 spent"),
    # Their siblings in the SAME family, which are genuinely blind. If the
    # classifier ever flagged these, it would be condemning a family for having
    # a construction at all.
    ("Monotone Nat.fermatNumber", False, "binder-free but not an equation"),
    ("StrictMono Nat.fermatNumber", False, "binder-free but not an equation"),
    ("∀ (n : ℕ), n.fermatNumber ≠ 1", False, "quantified"),
    ("∀ (n : ℕ), Odd n.fermatNumber", False, "quantified"),
    # Shapes from other families that must not be swept in.
    ("∀ {n : ℕ}, Even n ↔ n % 2 = 0", False, "quantified biconditional"),
    ("Nat.sqrt 0 = 0", True, "same shape, different family -- the rule is general"),
    ("Nat.gcd m n = Nat.gcd n m", False, "free variables, no numeral side"),
]


def self_test() -> list[str]:
    """Run the classifier against its own fixtures. Empty list means healthy."""
    failures = []
    for statement, expected, why in CLASSIFIER_FIXTURES:
        actual = is_closed_evaluation(statement)
        if actual != expected:
            failures.append(
                f"classifier-fixture|{statement!r}|expected={expected}|"
                f"got={actual}|{why}"
            )
    if not any(e for _, e, _ in CLASSIFIER_FIXTURES):
        failures.append("classifier-fixture|the fixture table has no POSITIVE case")
    if all(e for _, e, _ in CLASSIFIER_FIXTURES):
        failures.append("classifier-fixture|the fixture table has no NEGATIVE case")
    return failures


# ---------------------------------------------------------------------------
# the environment


def snake(name: str) -> str:
    tail = name.rsplit(".", 1)[-1]
    return re.sub(r"(?<!^)(?=[A-Z])", "_", tail).lower()


def declared_names() -> tuple[set[str], int]:
    if not SNAPSHOT.is_file():
        raise ClosedEvaluationError(
            f"the kernel environment snapshot is missing at {SNAPSHOT}; without "
            f"it nothing can say whether a row's vocabulary is declared here")
    try:
        snap = json.loads(SNAPSHOT.read_text())
    except json.JSONDecodeError as error:
        raise ClosedEvaluationError(f"snapshot unreadable: {error}") from error
    names = snap.get("declarations")
    if not isinstance(names, list) or not names:
        raise ClosedEvaluationError("the snapshot declares no names")
    return set(names), len(names)


def source_declares(constant: str) -> bool:
    """Fallback for a constant the snapshot is too old to know about."""
    needle = snake(constant)
    if len(needle) < 3:
        return False
    for path in KERNEL_SRC.rglob("*.rs"):
        try:
            if needle in path.read_text():
                return True
        except OSError:
            continue
    return False


# ---------------------------------------------------------------------------


def held_out_rows() -> list[dict[str, Any]]:
    rows: list[dict[str, Any]] = []
    for path in (NURSERY, EXTENSION):
        if not path.is_file():
            raise ClosedEvaluationError(f"nursery manifest is missing: {path}")
        try:
            manifest = json.loads(path.read_text())
        except json.JSONDecodeError as error:
            raise ClosedEvaluationError(
                f"nursery manifest is unreadable: {path.name}: {error}") from error
        entries = manifest.get("entries")
        if not isinstance(entries, list):
            raise ClosedEvaluationError(f"{path.name} has no entries")
        found = [e for e in entries
                 if isinstance(e, dict) and e.get("partition") == "held-out"]
        if not found:
            raise ClosedEvaluationError(
                f"{path.name} contributes no held-out rows; this gate would "
                f"pass vacuously for that manifest's population")
        rows += found
    return rows


def statement_of(entry: dict[str, Any]) -> str:
    """The row's Mathlib proposition, from the manifest or from its fact file.

    v1 entries carry no `statement`, so the fact ledger is the authority there.
    A row with neither is an error: an unclassifiable row read as "not a closed
    evaluation" is the fail-open direction.
    """
    if entry.get("statement"):
        return str(entry["statement"])
    path = FACTS / (entry["fact_id"].replace("F:", "F-") + ".json")
    if not path.is_file():
        raise ClosedEvaluationError(
            f"{entry['fact_id']} has neither a manifest statement nor a fact file")
    fact = json.loads(path.read_text())
    statement = (fact.get("formal") or {}).get("statement")
    if not statement:
        raise ClosedEvaluationError(
            f"{entry['fact_id']} carries no formal.statement to classify")
    return str(statement)


def main() -> int:
    failures = self_test()
    if failures:
        print("HOLDOUT_CLOSED_EVALUATION|verdict=CLASSIFIER-BROKEN", file=sys.stderr)
        for item in failures:
            print(f"  {item}", file=sys.stderr)
        print(
            "the classifier does not reproduce its own pinned fixtures, so a "
            "clean run over the real population would mean nothing",
            file=sys.stderr,
        )
        return 1

    try:
        rows = held_out_rows()
        declared, snapshot_size = declared_names()
    except ClosedEvaluationError as error:
        print(f"HOLDOUT_CLOSED_EVALUATION_ERROR|{error}", file=sys.stderr)
        return 1

    violations: list[str] = []
    closed_shaped = 0
    try:
        for entry in rows:
            statement = statement_of(entry)
            if not is_closed_evaluation(statement):
                continue
            closed_shaped += 1
            names = constants(statement)
            undeclared = sorted(
                n for n in names
                if n not in declared and not source_declares(n))
            if undeclared:
                continue
            violations.append(
                f"closed-evaluation|{entry['fact_id']}|{entry.get('family', '?')}|"
                f"{statement}|decided by reduction over {sorted(names)}")
    except ClosedEvaluationError as error:
        print(f"HOLDOUT_CLOSED_EVALUATION_ERROR|{error}", file=sys.stderr)
        return 1

    verdict = "FAIL" if violations else "PASS"
    print(
        f"HOLDOUT_CLOSED_EVALUATION|held_out={len(rows)}|"
        f"closed_shaped={closed_shaped}|violations={len(violations)}|"
        f"snapshot_declarations={snapshot_size}|"
        f"fixtures={len(CLASSIFIER_FIXTURES)}|verdict={verdict}"
    )
    for item in violations:
        print(f"  {item}", file=sys.stderr)
    if violations:
        print(
            "each row above is decided by reduction over constants this kernel "
            "already declares, so it is not blind. The repair is an ADR-0542 "
            "amendment in artifacts/autogenesis/"
            "mathlib-nursery-split-policy-v1.json, never a deletion, and the "
            "draw-time fix is ADR-0695: do not draw a family whose first rows "
            "the unblocking construction already settles.",
            file=sys.stderr,
        )
    return 1 if violations else 0


if __name__ == "__main__":
    raise SystemExit(main())
