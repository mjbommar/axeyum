//! Generate `lean/axeyum-creal` — the Lake package that publishes this
//! repository's constructed-real development as **Lean source a third party can
//! `import`**.
//!
//! # Why a generator and not a hand-written package
//!
//! The `creal` development is 3,600-odd declarations this kernel admitted
//! through `Kernel::add_declaration`. Hand-writing any of it in Lean would put a
//! second, unchecked copy of the mathematics in the tree: the published `.lean`
//! would then be a *claim about* the kernel rather than a *projection of* it,
//! and the two could drift silently. So every byte of the package — the module
//! sources, the axiom audit, the manifest, even the `lean-toolchain` — is
//! written by this program from the live kernel, and `--check` fails if what is
//! committed is not what this program would write today.
//!
//! # What Next Ten item 3 asked for, and what the wire route could not do
//!
//! The replay census (ADR-1661) already hands pinned Lean's *kernel* the
//! `lean4export` NDJSON stream and grades every declaration by name. It reports
//! 3,542 of `creal`'s 3,617 accepted: 49 are `Theorem`s whose type is not a
//! proposition (`Lean.Environment.addDeclCore` refuses those as theorems) and 26
//! are ordinary `Prop`-valued theorems whose dependency closure reaches one of
//! the 49, so the *stream* cannot carry them either.
//!
//! Lean **source** has a way out that the wire format does not: a `Type`-valued
//! proof is a perfectly good `def`. So the 49 are emitted as `def`s carrying a
//! doc comment that names the reason, the 26 stop being blocked, and the source
//! route publishes strictly more of the development than the wire route can.
//! The census's own numbers are the floor this package is measured against.
//!
//! # The rendering rules, stated once
//!
//! | kernel declaration | Lean command | why |
//! |---|---|---|
//! | `Definition` | `def` | same thing |
//! | `Theorem`, type in `Prop` | see `--proof-spelling` | a proof |
//! | `Theorem`, type NOT in `Prop` | `def` + doc comment | Lean refuses a `theorem` whose type is not a proposition; the modulus is data (`creal/uniform_convergence.rs`) |
//! | `Opaque` | `opaque` | never re-spelled: it has no value to unfold |
//! | `Axiom` | `axiom` | there are none in `creal`, and the manifest says so |
//! | `Inductive` | `inductive` | Lean regenerates the constructors and the recursor |
//! | `Constructor`, `Recursor` | *(none)* | regenerated by Lean from the `inductive` |
//! | anything else | **exclusion** | listed by name and reason in `EXCLUSIONS.json`; never `sorry`, never an axiom, never silently dropped |
//!
//! Nothing here reads a list of names: `Prop`-ness is decided by asking the
//! kernel to infer the type's sort, exactly as `tests/support/replay_census.rs`
//! does, and the coverage classification is computed against
//! `kernel.environment()`, which is the whole population.
//!
//! # Usage
//!
//! ```text
//! cargo run --release -p axeyum-lean-kernel --example render_creal_library -- \
//!     --out lean/axeyum-creal --facts artifacts/facts --toolchain lean-toolchain
//! cargo run --release -p axeyum-lean-kernel --example render_creal_library -- \
//!     --out lean/axeyum-creal --facts artifacts/facts --toolchain lean-toolchain --check
//! ```
//!
//! `--check` regenerates into memory and diffs against what is on disk, so
//! drift between the kernel and the committed package is a gate failure and not
//! a discovery someone makes later. See ADR-1675.

