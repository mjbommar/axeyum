fn axioms_module(sample: &[String]) -> String {
    let mut out = String::new();
    out.push_str(
        "\
-- GENERATED by `crates/axeyum-lean-kernel/examples/render_creal_library.rs`.
-- Do not edit.
--
-- THE AXIOM AUDIT. One `#print axioms` per result the fact ledger credits to
-- the constructed reals -- the sample is derived from every fact whose
-- `formal.kernel_theorem` names a declaration in the built environment, never
-- hand-listed, and the generator fails if that derivation stops covering the
-- headline results (IVT, EVT, FTC both directions, MVT, Rolle, `e`, `pi`).
--
-- Every line this module prints must read `does not depend on any axioms`.
-- `scripts/check-lean-creal-library.sh` enforces that, enforces a floor on how
-- many lines there are, and requires the positive control in
-- `Tests/AxiomControl.lean` to print the opposite -- so a `#print axioms` that
-- had stopped traversing could not pass.
--
-- `#guard_msgs` is NOT used here and cannot be: it lives in `Lean.Elab`, which
-- is unreachable from a `prelude` module, and `prelude` is forced by the
-- development's own `Eq`/`And`/`Or`. Measured on the pin, 2026-09-05: a
-- `#guard_msgs` in a `prelude` module is a parse error (`expected token`),
-- while `#print axioms` works because it is a builtin command elaborator.
prelude
",
    );
    let _ = writeln!(out, "import {CARRIER_MODULE}");
    out.push('\n');
    for name in sample {
        let _ = writeln!(out, "#print axioms {name}");
    }
    out
}

fn control_module() -> String {
    format!(
        "\
-- GENERATED by `crates/axeyum-lean-kernel/examples/render_creal_library.rs`.
-- Do not edit.
--
-- THE POSITIVE CONTROL for the axiom audit, and the reason this is a separate
-- Lake target: it declares an `axiom`, and nothing a user imports may.
--
-- `Axeyum.Creal.Axioms` asserts that every audited result reports `does not
-- depend on any axioms`. On its own that assertion is consistent with
-- `#print axioms` having silently stopped traversing into imported proofs -- in
-- which case an audit resting on a `sorryAx` would still look clean. This
-- module makes that failure mode visible: `axeyumCrealAudit_control` rests on a
-- declared axiom THROUGH an imported theorem, so `#print axioms` must name that
-- axiom. The gate requires that line, and fails without it.
prelude
import {CARRIER_MODULE}

axiom axeyumCrealAudit_controlAxiom : CReal.Equiv CReal.zero CReal.zero

theorem axeyumCrealAudit_control : CReal.Equiv CReal.zero CReal.zero :=
  CReal.Equiv.trans CReal.zero CReal.zero CReal.zero
    axeyumCrealAudit_controlAxiom (CReal.Equiv.refl CReal.zero)

#print axioms axeyumCrealAudit_control
"
    )
}

fn exclusions_json(excluded: &[(String, String)], spelling: ProofSpelling) -> String {
    let mut out = String::new();
    out.push_str("{\n");
    let _ = writeln!(
        out,
        "  \"generated_by\": \"crates/axeyum-lean-kernel/examples/render_creal_library.rs\","
    );
    let _ = writeln!(out, "  \"proof_spelling\": \"{}\",", spelling.as_str());
    let _ = writeln!(
        out,
        "  \"note\": \"A declaration the Axeyum kernel admitted that the published package does not carry as a Lean command. Never emitted as `sorry` and never as an axiom: it is listed here or it is in the package.\","
    );
    let _ = writeln!(out, "  \"count\": {},", excluded.len());
    out.push_str("  \"exclusions\": [");
    for (index, (name, reason)) in excluded.iter().enumerate() {
        if index > 0 {
            out.push(',');
        }
        let _ = write!(
            out,
            "\n    {{ \"name\": {}, \"reason\": {} }}",
            json_string(name),
            json_string(reason)
        );
    }
    if excluded.is_empty() {
        out.push_str("]\n}\n");
    } else {
        out.push_str("\n  ]\n}\n");
    }
    out
}

