fn eqv(d: &mut IntDev<'_>, c: Rec, a: ExprId, b: ExprId) -> ExprId {
    d.apply(c.equiv, &[a, b])
}
fn radd(d: &mut IntDev<'_>, c: Rec, a: ExprId, b: ExprId) -> ExprId {
    d.apply(c.add, &[a, b])
}
fn rmul(d: &mut IntDev<'_>, c: Rec, a: ExprId, b: ExprId) -> ExprId {
    d.apply(c.mul, &[a, b])
}
fn rneg(d: &mut IntDev<'_>, c: Rec, a: ExprId) -> ExprId {
    d.apply(c.neg, &[a])
}
fn rle(d: &mut IntDev<'_>, c: Rec, a: ExprId, b: ExprId) -> ExprId {
    d.apply(c.le, &[a, b])
}
fn refl(d: &mut IntDev<'_>, c: Rec, a: ExprId) -> ExprId {
    d.apply(c.erefl, &[a])
}
fn symm(d: &mut IntDev<'_>, c: Rec, a: ExprId, b: ExprId, h: ExprId) -> ExprId {
    d.apply(c.esymm, &[a, b, h])
}
fn trans(
    d: &mut IntDev<'_>,
    c: Rec,
    a: ExprId,
    b: ExprId,
    e: ExprId,
    h1: ExprId,
    h2: ExprId,
) -> ExprId {
    d.apply(c.etrans, &[a, b, e, h1, h2])
}
#[allow(clippy::too_many_arguments)]
fn acongr(
    d: &mut IntDev<'_>,
    c: Rec,
    a: ExprId,
    a2: ExprId,
    b: ExprId,
    b2: ExprId,
    h1: ExprId,
    h2: ExprId,
) -> ExprId {
    d.apply(c.add_congr, &[a, a2, b, b2, h1, h2])
}
#[allow(clippy::too_many_arguments)]
fn mcongr(
    d: &mut IntDev<'_>,
    c: Rec,
    a: ExprId,
    a2: ExprId,
    b: ExprId,
    b2: ExprId,
    h1: ExprId,
    h2: ExprId,
) -> ExprId {
    d.apply(c.mul_congr, &[a, a2, b, b2, h1, h2])
}
fn ncongr(d: &mut IntDev<'_>, c: Rec, a: ExprId, b: ExprId, h: ExprId) -> ExprId {
    d.apply(c.neg_congr, &[a, b, h])
}

/// `equivTrans`-fold a chain of steps, mirroring `NatOps::chain` for the
/// record's setoid equality: `steps[i] = (next_rhs, proof_of(cur ≃ next))`.
fn chain(d: &mut IntDev<'_>, c: Rec, start: ExprId, steps: &[(ExprId, ExprId)]) -> ExprId {
    let mut cur = start;
    let mut acc: Option<ExprId> = None;
    for &(next, step) in steps {
        acc = Some(match acc {
            None => step,
            Some(prev) => trans(d, c, start, cur, next, prev, step),
        });
        cur = next;
    }
    acc.expect("chain needs at least one step")
}

/// The record's own type, `AlgS.OrderedRing`.
fn rec_ty(d: &mut IntDev<'_>, rn: &RecordNames) -> ExprId {
    d.kernel().const_(rn.ind, vec![])
}

