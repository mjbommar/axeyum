/// Declare the generic Bernoulli layer.
///
/// # Errors
///
/// Returns the trusted gate's rejection — an `Err` means the kernel
/// **refused** a proof, not that a script gave up.
pub(crate) fn declare_binomial_s_all(
    d: &mut IntDev<'_>,
    p: &RatPrelude,
) -> Result<(), KernelError> {
    let st = p.int.nat.structures_s;
    let rn = st.ordered_ring;
    let extra = p.int.nat.structures_s_extra;
    let prob = p.probability_s;
    let names = p.binomial_s;

    declare_mul_neg(d, &rn, &names, prob.to_ring_s, extra.mul_neg_one)?;
    declare_zero_add(d, &rn, &names)?;
    declare_bernoulli_var(d, &rn, &names)?;
    declare_bernoulli_mass(d, &rn, &names)?;
    declare_bernoulli_mass_nonneg(d, &rn, &names, prob.sub_nonneg_of_le)?;
    declare_bernoulli_is_distribution(d, &rn, &names, prob.is_distribution, prob.sum_range)?;
    declare_bernoulli_expectation(d, &rn, &names, prob.expectation, prob.zero_mul)?;
    declare_bernoulli_variance(
        d,
        &rn,
        &names,
        prob.variance,
        prob.expectation,
        prob.neg_mul,
        extra.neg_neg,
        prob.to_ring_s,
    )?;
    Ok(())
}
