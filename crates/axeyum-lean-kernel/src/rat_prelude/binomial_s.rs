/// `AlgS.OrderedRing.bernoulliVar R`, the partial application at `R`.
fn bvar(d: &mut IntDev<'_>, names: &BinomialSNames, r: ExprId) -> ExprId {
    d.const_app(names.bernoulli_var, &[r])
}

/// `AlgS.OrderedRing.bernoulliMass R q`, the partial application at `R`, `q`.
fn bmass(d: &mut IntDev<'_>, names: &BinomialSNames, r: ExprId, q: ExprId) -> ExprId {
    d.const_app(names.bernoulli_mass, &[r, q])
}

/// `AlgS.OrderedRing.bernoulliVar : ∀ (R : AlgS.OrderedRing), Nat →
/// R.carrier := fun R k => Nat.rec R.zero (fun _ _ => R.one) k`.
///
/// The success indicator on the two-outcome range: `bernoulliVar R 0 ≡
/// R.zero` and `bernoulliVar R 1 ≡ R.one`, both by ι alone, which is what
/// makes every statement below reduce without an equation lemma.
fn declare_bernoulli_var(
    d: &mut IntDev<'_>,
    rn: &RecordNames,
    names: &BinomialSNames,
) -> Result<(), KernelError> {
    let nat = d.nat_ty();
    let anon = d.anon_name();
    let l1 = d.level_one();

    let r_fv = d.fresh_fvar();
    let r = d.kernel().fvar(r_fv);
    let c = proj(d, rn, r);

    let motive = d
        .kernel()
        .lam(anon, nat, c.carrier, crate::BinderInfo::Default);
    let minor_succ = {
        let j_fv = d.fresh_fvar();
        let ih_fv = d.fresh_fvar();
        let inner = d.lam_fv(ih_fv, c.carrier, c.one);
        d.lam_fv(j_fv, nat, inner)
    };
    let k_fv = d.fresh_fvar();
    let kv = d.kernel().fvar(k_fv);
    let rec_name = d.prelude().rec;
    let rec = d.kernel().const_(rec_name, vec![l1]);
    let body = d.apply(rec, &[motive, c.zero, minor_succ, kv]);

    let value = {
        let with_k = d.lam_fv(k_fv, nat, body);
        let ord_ty = rec_ty(d, rn);
        d.lam_fv(r_fv, ord_ty, with_k)
    };
    let ty = {
        let over_k = d.arrow(nat, c.carrier);
        let ord_ty = rec_ty(d, rn);
        d.pi_fv(r_fv, ord_ty, over_k)
    };
    d.kernel().add_declaration(Declaration::Definition {
        name: names.bernoulli_var,
        uparams: vec![],
        ty,
        value,
        hint: ReducibilityHint::Regular(1),
    })
}

/// `AlgS.OrderedRing.bernoulliMass : ∀ (R : AlgS.OrderedRing), R.carrier →
/// Nat → R.carrier := fun R q k => Nat.rec (R.add R.one (R.neg q)) (fun _ _
/// => q) k`.
///
/// The mass function of the two-outcome model: `bernoulliMass R q 0 ≡ 1 − q`
/// (failure) and `bernoulliMass R q 1 ≡ q` (success). Written `add one (neg
/// q)` rather than through `AlgS.sub` so it is the same shape
/// `sub_nonneg_of_le` (ADR-1616) already produces — the nonnegativity proof
/// is then that theorem applied, with no rewriting at all.
fn declare_bernoulli_mass(
    d: &mut IntDev<'_>,
    rn: &RecordNames,
    names: &BinomialSNames,
) -> Result<(), KernelError> {
    let nat = d.nat_ty();
    let anon = d.anon_name();
    let l1 = d.level_one();

    let r_fv = d.fresh_fvar();
    let r = d.kernel().fvar(r_fv);
    let c = proj(d, rn, r);
    let q_fv = d.fresh_fvar();
    let q = d.kernel().fvar(q_fv);

    let nq = rneg(d, c, q);
    let one_minus_q = radd(d, c, c.one, nq);

    let motive = d
        .kernel()
        .lam(anon, nat, c.carrier, crate::BinderInfo::Default);
    let minor_succ = {
        let j_fv = d.fresh_fvar();
        let ih_fv = d.fresh_fvar();
        let inner = d.lam_fv(ih_fv, c.carrier, q);
        d.lam_fv(j_fv, nat, inner)
    };
    let k_fv = d.fresh_fvar();
    let kv = d.kernel().fvar(k_fv);
    let rec_name = d.prelude().rec;
    let rec = d.kernel().const_(rec_name, vec![l1]);
    let body = d.apply(rec, &[motive, one_minus_q, minor_succ, kv]);

    let value = {
        let with_k = d.lam_fv(k_fv, nat, body);
        let with_q = d.lam_fv(q_fv, c.carrier, with_k);
        let ord_ty = rec_ty(d, rn);
        d.lam_fv(r_fv, ord_ty, with_q)
    };
    let ty = {
        let over_k = d.arrow(nat, c.carrier);
        let over_q = d.arrow(c.carrier, over_k);
        let ord_ty = rec_ty(d, rn);
        d.pi_fv(r_fv, ord_ty, over_q)
    };
    d.kernel().add_declaration(Declaration::Definition {
        name: names.bernoulli_mass,
        uparams: vec![],
        ty,
        value,
        hint: ReducibilityHint::Regular(1),
    })
}

/// `AlgS.OrderedRing.bernoulliMass_nonneg : ∀ R q, le zero q → le q one → ∀
/// k, le zero (bernoulliMass R q k)` — for EVERY `k`, not only `k < 2`.
///
/// `Nat.rec` on `k`: the base case is `sub_nonneg_of_le R q one` (ADR-1616)
/// applied to `q ≤ 1`, whose conclusion `le zero (add one (neg q))` is
/// literally the ι-reduct of `bernoulliMass R q 0`; every successor case is
/// the `0 ≤ q` hypothesis unchanged. Stating it unbounded is what lets
/// [`declare_bernoulli_is_distribution`] discharge `∀ i, i < 2 → …` with
/// `fun i _ => …` and never invert a `Nat.lt`.
fn declare_bernoulli_mass_nonneg(
    d: &mut IntDev<'_>,
    rn: &RecordNames,
    names: &BinomialSNames,
    sub_nonneg_of_le: NameId,
) -> Result<(), KernelError> {
    let nat = d.nat_ty();
    let r_fv = d.fresh_fvar();
    let r = d.kernel().fvar(r_fv);
    let c = proj(d, rn, r);
    let q_fv = d.fresh_fvar();
    let q = d.kernel().fvar(q_fv);

    let h0_ty = rle(d, c, c.zero, q);
    let h0_fv = d.fresh_fvar();
    let h0 = d.kernel().fvar(h0_fv);
    let h1_ty = rle(d, c, q, c.one);
    let h1_fv = d.fresh_fvar();
    let h1 = d.kernel().fvar(h1_fv);

    let mass = bmass(d, names, r, q);
    let k_fv = d.fresh_fvar();
    let kv = d.kernel().fvar(k_fv);

    let motive = |d: &mut IntDev<'_>, x: ExprId| -> ExprId {
        let mx = d.apply(mass, &[x]);
        rle(d, c, c.zero, mx)
    };
    let core = d.induct(
        &motive,
        &|d| d.const_app(sub_nonneg_of_le, &[r, q, c.one, h1]),
        &|_d, _j, _ih| h0,
        kv,
    );

    let concl = motive(d, kv);
    let ord_ty = rec_ty(d, rn);
    let ty = {
        let over_k = d.pi_fv(k_fv, nat, concl);
        let over_h1 = d.arrow(h1_ty, over_k);
        let over_h0 = d.arrow(h0_ty, over_h1);
        let over_q = d.pi_fv(q_fv, c.carrier, over_h0);
        d.pi_fv(r_fv, ord_ty, over_q)
    };
    let value = {
        let over_k = d.lam_fv(k_fv, nat, core);
        let over_h1 = d.lam_fv(h1_fv, h1_ty, over_k);
        let over_h0 = d.lam_fv(h0_fv, h0_ty, over_h1);
        let over_q = d.lam_fv(q_fv, c.carrier, over_h0);
        d.lam_fv(r_fv, ord_ty, over_q)
    };
    d.declare_theorem(names.bernoulli_mass_nonneg, ty, value)
}

/// `AlgS.OrderedRing.bernoulli_isDistribution : ∀ R q, le zero q → le q one →
/// IsDistribution R (bernoulliMass R q) 2`.
///
/// **The first `IsDistribution` in the repository discharged from a
/// construction rather than assumed.** Its two halves are
/// [`declare_bernoulli_mass_nonneg`] (weakened to `i < 2` by ignoring the
/// bound) and `sumRange R (bernoulliMass R q) 2 ≃ 1`, which ι-reduces to
/// `(0 + (1 + −q)) + q ≃ 1` and is then four record laws: `zero_add`,
/// `addAssoc`, `addComm`/`negAdd`, `addZero`.
fn declare_bernoulli_is_distribution(
    d: &mut IntDev<'_>,
    rn: &RecordNames,
    names: &BinomialSNames,
    is_distribution: NameId,
    sum_range: NameId,
) -> Result<(), KernelError> {
    let nat = d.nat_ty();
    let r_fv = d.fresh_fvar();
    let r = d.kernel().fvar(r_fv);
    let c = proj(d, rn, r);
    let q_fv = d.fresh_fvar();
    let q = d.kernel().fvar(q_fv);

    let h0_ty = rle(d, c, c.zero, q);
    let h0_fv = d.fresh_fvar();
    let h0 = d.kernel().fvar(h0_fv);
    let h1_ty = rle(d, c, q, c.one);
    let h1_fv = d.fresh_fvar();
    let h1 = d.kernel().fvar(h1_fv);

    let two = d.num(2);
    let mass = bmass(d, names, r, q);

    // Left half: forall i, Nat.lt i 2 -> le zero (mass i).
    let nonneg_part = {
        let i_fv = d.fresh_fvar();
        let i = d.kernel().fvar(i_fv);
        let hyp = d.lt(i, two);
        let mi = d.apply(mass, &[i]);
        let nonneg = rle(d, c, c.zero, mi);
        let body = d.arrow(hyp, nonneg);
        d.pi_fv(i_fv, nat, body)
    };
    let nonneg_proof = {
        let i_fv = d.fresh_fvar();
        let i = d.kernel().fvar(i_fv);
        let hyp = d.lt(i, two);
        let hi_fv = d.fresh_fvar();
        let at_i = d.const_app(names.bernoulli_mass_nonneg, &[r, q, h0, h1, i]);
        let with_hi = d.lam_fv(hi_fv, hyp, at_i);
        d.lam_fv(i_fv, nat, with_hi)
    };

    // Right half: sumRange R mass 2 ~ one, i.e. (0 + (1 + -q)) + q ~ 1.
    let nq = rneg(d, c, q);
    let u = radd(d, c, c.one, nq);
    let zu = radd(d, c, c.zero, u);
    let zu_q = radd(d, c, zu, q);
    let u_q = radd(d, c, u, q);
    let nq_q = radd(d, c, nq, q);
    let q_nq = radd(d, c, q, nq);
    let one_nq_q = radd(d, c, c.one, nq_q);
    let one_zero = radd(d, c, c.one, c.zero);

    let refl_q = refl(d, c, q);
    let s1 = {
        let za = d.const_app(names.zero_add, &[r, u]);
        acongr(d, c, zu, u, q, q, za, refl_q)
    };
    let s2 = d.apply(c.add_assoc, &[c.one, nq, q]);
    let s3 = {
        let comm = d.apply(c.add_comm, &[nq, q]);
        let na = d.apply(c.neg_add, &[q]);
        let inner = trans(d, c, nq_q, q_nq, c.zero, comm, na);
        let refl_one = refl(d, c, c.one);
        acongr(d, c, c.one, c.one, nq_q, c.zero, refl_one, inner)
    };
    let s4 = d.apply(c.add_zero, &[c.one]);
    let sum_proof = chain(
        d,
        c,
        zu_q,
        &[(u_q, s1), (one_nq_q, s2), (one_zero, s3), (c.one, s4)],
    );
    let sum_part = {
        let sum = d.const_app(sum_range, &[r, mass, two]);
        eqv(d, c, sum, c.one)
    };

    let and_intro = d.int().logic.and_intro;
    let core = d.const_app(and_intro, &[nonneg_part, sum_part, nonneg_proof, sum_proof]);

    let stmt = d.const_app(is_distribution, &[r, mass, two]);
    let ord_ty = rec_ty(d, rn);
    let ty = {
        let over_h1 = d.arrow(h1_ty, stmt);
        let over_h0 = d.arrow(h0_ty, over_h1);
        let over_q = d.pi_fv(q_fv, c.carrier, over_h0);
        d.pi_fv(r_fv, ord_ty, over_q)
    };
    let value = {
        let over_h1 = d.lam_fv(h1_fv, h1_ty, core);
        let over_h0 = d.lam_fv(h0_fv, h0_ty, over_h1);
        let over_q = d.lam_fv(q_fv, c.carrier, over_h0);
        d.lam_fv(r_fv, ord_ty, over_q)
    };
    d.declare_theorem(names.bernoulli_is_distribution, ty, value)
}

/// `AlgS.OrderedRing.bernoulli_expectation : ∀ R q, equiv (expectation R
/// (bernoulliVar R) (bernoulliMass R q) 2) q` — **the parameter IS the
/// mean**, with no hypothesis on `q` at all.
///
/// `expectation` at `n = 2` ι-reduces to `(0 + (0 · (1 − q))) + (1 · q)`;
/// `zero_mul` (ADR-1616) kills the failure term, `mulOneL` and
/// [`declare_zero_add`] strip the success term. Note that `0 ≤ q ≤ 1` is
/// nowhere needed: the identity is algebraic, and only
/// [`declare_bernoulli_is_distribution`] cares whether the weights are a
/// distribution.
fn declare_bernoulli_expectation(
    d: &mut IntDev<'_>,
    rn: &RecordNames,
    names: &BinomialSNames,
    expectation: NameId,
    zero_mul: NameId,
) -> Result<(), KernelError> {
    let r_fv = d.fresh_fvar();
    let r = d.kernel().fvar(r_fv);
    let c = proj(d, rn, r);
    let q_fv = d.fresh_fvar();
    let q = d.kernel().fvar(q_fv);

    let two = d.num(2);
    let var = bvar(d, names, r);
    let mass = bmass(d, names, r, q);

    let nq = rneg(d, c, q);
    let u = radd(d, c, c.one, nq);
    let zero_u = rmul(d, c, c.zero, u);
    let one_q = rmul(d, c, c.one, q);
    let head = radd(d, c, c.zero, zero_u);
    let lhs = radd(d, c, head, one_q);
    let zero_plus_q = radd(d, c, c.zero, q);

    // head ~ zero : zero_add then zero_mul.
    let head_zero = {
        let za = d.const_app(names.zero_add, &[r, zero_u]);
        let zm = d.const_app(zero_mul, &[r, u]);
        trans(d, c, head, zero_u, c.zero, za, zm)
    };
    let mol = d.apply(c.mul_one_l, &[q]);
    let s1 = acongr(d, c, head, c.zero, one_q, q, head_zero, mol);
    let s2 = d.const_app(names.zero_add, &[r, q]);
    let core = chain(d, c, lhs, &[(zero_plus_q, s1), (q, s2)]);

    let expectation_term = d.const_app(expectation, &[r, var, mass, two]);
    let stmt = eqv(d, c, expectation_term, q);
    let ord_ty = rec_ty(d, rn);
    let ty = {
        let over_q = d.pi_fv(q_fv, c.carrier, stmt);
        d.pi_fv(r_fv, ord_ty, over_q)
    };
    let value = {
        let over_q = d.lam_fv(q_fv, c.carrier, core);
        d.lam_fv(r_fv, ord_ty, over_q)
    };
    d.declare_theorem(names.bernoulli_expectation, ty, value)
}

/// `AlgS.OrderedRing.bernoulli_variance : ∀ R q, equiv (variance R
/// (bernoulliVar R) (bernoulliMass R q) 2) (mul q (add one (neg q)))` —
/// `Var[X] = q·(1 − q)`.
///
/// **This is the theorem that says what the record can and cannot do.**
/// `variance` is the CENTRED form `E[(X − μ)²]` with `μ` the expectation
/// term itself, so the proof is in three movements:
///
/// 1. rewrite `μ` to `q` inside both summands, by `negCongr`/`addCongr`/
///    `mulCongr` against [`declare_bernoulli_expectation`] — no
///    `sumRange_congr` is needed because at `n = 2` the sum has already
///    ι-reduced to two named terms;
/// 2. collapse the failure summand `((0 + −q)·(0 + −q))·(1 − q)` to
///    `(q·q)·(1 − q)`, which needs `zero_add`, `neg_mul` (ADR-1616),
///    [`declare_mul_neg`] and `AlgS.neg_neg`;
/// 3. prove `(q·q)·u + (u·u)·q ≃ q·u` where `u := 1 − q`.
///
/// Movement 3 is where the missing `mulComm` would normally stop the
/// argument, and it does not, because the ONE instance of commutativity the
/// identity actually needs is `u·q ≃ q·u` — and both sides expand to
/// `q + −(q·q)` by `distribR`/`distribL` with `mulOneL`/`mulOneR` and the two
/// negation-through-multiplication lemmas. With that in hand: `mulAssoc`
/// twice gives `q·(q·u) + u·(q·u)`, `distribR` factors it to `(q + u)·(q·u)`,
/// `q + u ≃ 1` by `addAssoc`/`addComm`/`negAdd`/`addZero`, and `mulOneL`
/// finishes. No trichotomy, no field inverse, no commutative ring.
#[allow(clippy::too_many_lines)]
fn declare_bernoulli_variance(
    d: &mut IntDev<'_>,
    rn: &RecordNames,
    names: &BinomialSNames,
    variance: NameId,
    expectation: NameId,
    neg_mul: NameId,
    algs_neg_neg: NameId,
    to_ring_s: NameId,
) -> Result<(), KernelError> {
    let r_fv = d.fresh_fvar();
    let r = d.kernel().fvar(r_fv);
    let c = proj(d, rn, r);
    let ring_r = d.const_app(to_ring_s, &[r]);
    let q_fv = d.fresh_fvar();
    let q = d.kernel().fvar(q_fv);

    let two = d.num(2);
    let var = bvar(d, names, r);
    let mass = bmass(d, names, r, q);
    let mu = d.const_app(expectation, &[r, var, mass, two]);
    let hmu = d.const_app(names.bernoulli_expectation, &[r, q]);

    let nq = rneg(d, c, q);
    let u = radd(d, c, c.one, nq);
    let nmu = rneg(d, c, mu);

    // --- movement 1: mu ~> q inside both centred factors -------------------
    let d0 = radd(d, c, c.zero, nmu);
    let d0p = radd(d, c, c.zero, nq);
    let d1 = radd(d, c, c.one, nmu);
    let d1p = u;

    let hnm = ncongr(d, c, mu, q, hmu);
    let refl_zero = refl(d, c, c.zero);
    let refl_one = refl(d, c, c.one);
    let hd0 = acongr(d, c, c.zero, c.zero, nmu, nq, refl_zero, hnm);
    let hd1 = acongr(d, c, c.one, c.one, nmu, nq, refl_one, hnm);

    let sq0 = rmul(d, c, d0, d0);
    let sq0p = rmul(d, c, d0p, d0p);
    let sq1 = rmul(d, c, d1, d1);
    let sq1p = rmul(d, c, d1p, d1p);
    let t0 = rmul(d, c, sq0, u);
    let t0p = rmul(d, c, sq0p, u);
    let t1 = rmul(d, c, sq1, q);
    let t1p = rmul(d, c, sq1p, q);

    let refl_u = refl(d, c, u);
    let refl_q = refl(d, c, q);
    let hsq0 = mcongr(d, c, d0, d0p, d0, d0p, hd0, hd0);
    let hsq1 = mcongr(d, c, d1, d1p, d1, d1p, hd1, hd1);
    let ht0 = mcongr(d, c, sq0, sq0p, u, u, hsq0, refl_u);
    let ht1 = mcongr(d, c, sq1, sq1p, q, q, hsq1, refl_q);

    let head = radd(d, c, c.zero, t0);
    let headp = radd(d, c, c.zero, t0p);
    let lhs = radd(d, c, head, t1);
    let lhs1 = radd(d, c, headp, t1p);
    let hhead = acongr(d, c, c.zero, c.zero, t0, t0p, refl_zero, ht0);
    let step1 = acongr(d, c, head, headp, t1, t1p, hhead, ht1);

    // --- movement 2: (0 + -q)^2 * u  ~>  (q*q) * u -------------------------
    let qq = rmul(d, c, q, q);
    let nqq = rneg(d, c, qq);
    let q_nq = rmul(d, c, q, nq);
    let nq_nq = rmul(d, c, nq, nq);
    let n_q_nq = rneg(d, c, q_nq);
    let n_nqq = rneg(d, c, nqq);
    let t0pp = rmul(d, c, qq, u);
    let headpp = radd(d, c, c.zero, t0pp);
    let lhs2 = radd(d, c, headpp, t1p);

    let hz = d.const_app(names.zero_add, &[r, nq]);
    let hsq0p = mcongr(d, c, d0p, nq, d0p, nq, hz, hz);
    // (-q)*(-q) ~ -(q*(-q)) ~ -(-(q*q)) ~ q*q
    let e1 = d.const_app(neg_mul, &[r, q, nq]);
    let e2 = d.const_app(names.mul_neg, &[r, q, q]);
    let e3 = ncongr(d, c, q_nq, nqq, e2);
    let e4 = d.const_app(algs_neg_neg, &[ring_r, qq]);
    let hneg_sq = chain(d, c, nq_nq, &[(n_q_nq, e1), (n_nqq, e3), (qq, e4)]);
    let hsq0_full = trans(d, c, sq0p, nq_nq, qq, hsq0p, hneg_sq);
    let step2 = {
        let inner = mcongr(d, c, sq0p, qq, u, u, hsq0_full, refl_u);
        let refl_t1p = refl(d, c, t1p);
        let hh = acongr(d, c, c.zero, c.zero, t0p, t0pp, refl_zero, inner);
        acongr(d, c, headp, headpp, t1p, t1p, hh, refl_t1p)
    };

    // strip the leading `zero +`
    let lhs3 = radd(d, c, t0pp, t1p);
    let step3 = {
        let za = d.const_app(names.zero_add, &[r, t0pp]);
        let refl_t1p = refl(d, c, t1p);
        acongr(d, c, headpp, t0pp, t1p, t1p, za, refl_t1p)
    };

    // --- movement 3: (q*q)*u + (u*u)*q ~ q*u -------------------------------
    let qu = rmul(d, c, q, u);
    let uq = rmul(d, c, u, q);
    let q_plus_nqq = radd(d, c, q, nqq);

    // hcomm : u*q ~ q*u, both sides expanding to q + -(q*q).
    let hcomm = {
        // u*q = (1 + -q)*q ~ 1*q + (-q)*q ~ q + -(q*q)
        let one_q = rmul(d, c, c.one, q);
        let nq_q = rmul(d, c, nq, q);
        let l1 = d.apply(c.distrib_r, &[c.one, nq, q]);
        let sum_l = radd(d, c, one_q, nq_q);
        let mol = d.apply(c.mul_one_l, &[q]);
        let nm = d.const_app(neg_mul, &[r, q, q]);
        let l2 = acongr(d, c, one_q, q, nq_q, nqq, mol, nm);
        let left = trans(d, c, uq, sum_l, q_plus_nqq, l1, l2);

        // q*u = q*(1 + -q) ~ q*1 + q*(-q) ~ q + -(q*q)
        let q_one = rmul(d, c, q, c.one);
        let r1 = d.apply(c.distrib_l, &[q, c.one, nq]);
        let sum_r = radd(d, c, q_one, q_nq);
        let mor = d.apply(c.mul_one_r, &[q]);
        let mn = d.const_app(names.mul_neg, &[r, q, q]);
        let r2 = acongr(d, c, q_one, q, q_nq, nqq, mor, mn);
        let right = trans(d, c, qu, sum_r, q_plus_nqq, r1, r2);
        let right_s = symm(d, c, qu, q_plus_nqq, right);
        trans(d, c, uq, q_plus_nqq, qu, left, right_s)
    };

    let q_qu = rmul(d, c, q, qu);
    let u_uq = rmul(d, c, u, uq);
    let u_qu = rmul(d, c, u, qu);
    let q_plus_u = radd(d, c, q, u);
    let qu_uq = rmul(d, c, q_plus_u, qu);
    let one_qu = rmul(d, c, c.one, qu);
    let lhs4 = radd(d, c, q_qu, u_qu);

    let a1 = d.apply(c.mul_assoc, &[q, q, u]); // (q*q)*u ~ q*(q*u)
    let a2 = d.apply(c.mul_assoc, &[u, u, q]); // (u*u)*q ~ u*(u*q)
    let a3 = mcongr(d, c, u, u, uq, qu, refl_u, hcomm); // u*(u*q) ~ u*(q*u)
    let a23 = trans(d, c, t1p, u_uq, u_qu, a2, a3);
    let step4 = acongr(d, c, t0pp, q_qu, t1p, u_qu, a1, a23);

    let step5 = {
        let dr = d.apply(c.distrib_r, &[q, u, qu]); // (q+u)*(q*u) ~ q*(q*u) + u*(q*u)
        symm(d, c, qu_uq, lhs4, dr)
    };

    // q + u ~ one
    let hqu1 = {
        let q_one = radd(d, c, q, c.one);
        let one_q = radd(d, c, c.one, q);
        let q_one_nq = radd(d, c, q_one, nq);
        let one_q_nq = radd(d, c, one_q, nq);
        let q_nq_add = radd(d, c, q, nq);
        let one_inner = radd(d, c, c.one, q_nq_add);
        let one_zero = radd(d, c, c.one, c.zero);

        let s1 = {
            let assoc = d.apply(c.add_assoc, &[q, c.one, nq]);
            symm(d, c, q_one_nq, q_plus_u, assoc)
        };
        let s2 = {
            let comm = d.apply(c.add_comm, &[q, c.one]);
            let refl_nq = refl(d, c, nq);
            acongr(d, c, q_one, one_q, nq, nq, comm, refl_nq)
        };
        let s3 = d.apply(c.add_assoc, &[c.one, q, nq]);
        let s4 = {
            let na = d.apply(c.neg_add, &[q]);
            acongr(d, c, c.one, c.one, q_nq_add, c.zero, refl_one, na)
        };
        let s5 = d.apply(c.add_zero, &[c.one]);
        chain(
            d,
            c,
            q_plus_u,
            &[
                (q_one_nq, s1),
                (one_q_nq, s2),
                (one_inner, s3),
                (one_zero, s4),
                (c.one, s5),
            ],
        )
    };
    let refl_qu = refl(d, c, qu);
    let step6 = mcongr(d, c, q_plus_u, c.one, qu, qu, hqu1, refl_qu);
    let step7 = d.apply(c.mul_one_l, &[qu]);

    let core = chain(
        d,
        c,
        lhs,
        &[
            (lhs1, step1),
            (lhs2, step2),
            (lhs3, step3),
            (lhs4, step4),
            (qu_uq, step5),
            (one_qu, step6),
            (qu, step7),
        ],
    );

    let variance_term = d.const_app(variance, &[r, var, mass, two]);
    let stmt = eqv(d, c, variance_term, qu);
    let ord_ty = rec_ty(d, rn);
    let ty = {
        let over_q = d.pi_fv(q_fv, c.carrier, stmt);
        d.pi_fv(r_fv, ord_ty, over_q)
    };
    let value = {
        let over_q = d.lam_fv(q_fv, c.carrier, core);
        d.lam_fv(r_fv, ord_ty, over_q)
    };
    d.declare_theorem(names.bernoulli_variance, ty, value)
}

