/// `AlgS.OrderedRing.mul_neg : ∀ R a b, equiv (mul a (neg b)) (neg (mul a
/// b))` — the RIGHT-handed twin of `AlgS.OrderedRing.neg_mul` (ADR-1616).
///
/// Without `mulComm` the two are genuinely different statements, and only
/// the left one was proved. This one goes through `AlgS.mul_neg_one`
/// (ADR-1590, over `AlgS.Ring`, reached by `toRingS`) rather than through a
/// second `add_left_cancel` argument: `a·(−b) ≃ a·(b·(−1)) ≃ (a·b)·(−1) ≃
/// −(a·b)`, three steps, of which the middle one is just `mulAssoc`.
fn declare_mul_neg(
    d: &mut IntDev<'_>,
    rn: &RecordNames,
    names: &BinomialSNames,
    to_ring_s: NameId,
    mul_neg_one: NameId,
) -> Result<(), KernelError> {
    let r_fv = d.fresh_fvar();
    let r = d.kernel().fvar(r_fv);
    let c = proj(d, rn, r);
    let ring_r = d.const_app(to_ring_s, &[r]);

    let a_fv = d.fresh_fvar();
    let a = d.kernel().fvar(a_fv);
    let b_fv = d.fresh_fvar();
    let b = d.kernel().fvar(b_fv);

    let nb = rneg(d, c, b);
    let none = rneg(d, c, c.one);
    let ab = rmul(d, c, a, b);
    let n_ab = rneg(d, c, ab);
    let a_nb = rmul(d, c, a, nb);
    let b_none = rmul(d, c, b, none);
    let a_b_none = rmul(d, c, a, b_none);
    let ab_none = rmul(d, c, ab, none);

    // s1 : equiv (neg b) (mul b (neg one))
    let mno_b = d.const_app(mul_neg_one, &[ring_r, b]);
    let s1 = symm(d, c, b_none, nb, mno_b);
    // s2 : equiv (mul a (neg b)) (mul a (mul b (neg one)))
    let refl_a = refl(d, c, a);
    let s2 = mcongr(d, c, a, a, nb, b_none, refl_a, s1);
    // s3 : equiv (mul a (mul b (neg one))) (mul (mul a b) (neg one))
    let assoc = d.apply(c.mul_assoc, &[a, b, none]);
    let s3 = symm(d, c, ab_none, a_b_none, assoc);
    // s4 : equiv (mul (mul a b) (neg one)) (neg (mul a b))
    let s4 = d.const_app(mul_neg_one, &[ring_r, ab]);

    let core = chain(d, c, a_nb, &[(a_b_none, s2), (ab_none, s3), (n_ab, s4)]);

    let stmt = eqv(d, c, a_nb, n_ab);
    let ord_ty = rec_ty(d, rn);
    let ty = {
        let over_b = d.pi_fv(b_fv, c.carrier, stmt);
        let over_a = d.pi_fv(a_fv, c.carrier, over_b);
        d.pi_fv(r_fv, ord_ty, over_a)
    };
    let value = {
        let over_b = d.lam_fv(b_fv, c.carrier, core);
        let over_a = d.lam_fv(a_fv, c.carrier, over_b);
        d.lam_fv(r_fv, ord_ty, over_a)
    };
    d.declare_theorem(names.mul_neg, ty, value)
}

/// `AlgS.OrderedRing.zero_add : ∀ R a, equiv (add zero a) a`.
///
/// The record's additive unit law `addZero` is right-handed; every sum this
/// file reduces out of `sumRange` starts with a literal `zero` on the LEFT,
/// so the left law is needed once per summand. `addComm` then `addZero`.
fn declare_zero_add(
    d: &mut IntDev<'_>,
    rn: &RecordNames,
    names: &BinomialSNames,
) -> Result<(), KernelError> {
    let r_fv = d.fresh_fvar();
    let r = d.kernel().fvar(r_fv);
    let c = proj(d, rn, r);
    let a_fv = d.fresh_fvar();
    let a = d.kernel().fvar(a_fv);

    let za = radd(d, c, c.zero, a);
    let az = radd(d, c, a, c.zero);
    let s1 = d.apply(c.add_comm, &[c.zero, a]);
    let s2 = d.apply(c.add_zero, &[a]);
    let core = trans(d, c, za, az, a, s1, s2);

    let stmt = eqv(d, c, za, a);
    let ord_ty = rec_ty(d, rn);
    let ty = {
        let over_a = d.pi_fv(a_fv, c.carrier, stmt);
        d.pi_fv(r_fv, ord_ty, over_a)
    };
    let value = {
        let over_a = d.lam_fv(a_fv, c.carrier, core);
        d.lam_fv(r_fv, ord_ty, over_a)
    };
    d.declare_theorem(names.zero_add, ty, value)
}

