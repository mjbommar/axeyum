//! ADR-1631 (roadmap W3-12): the Bernoulli distribution as a **constructed**
//! two-point model on the generic finite-probability carrier, its mean and
//! its variance.
//!
//! `rat_prelude/probability_s.rs` (ADR-1616) states the finite probability
//! layer once over `(R : AlgS.OrderedRing)`: `sumRange`, `IsDistribution`,
//! `expectation`, `variance`, `covariance`, `Independent`. Everything there
//! is stated for an ARBITRARY weight function `p` and an arbitrary variable
//! `X`. Nothing in the shelf is a *named distribution*: no `p` is ever built,
//! so no `IsDistribution` is ever discharged from a construction rather than
//! assumed.
//!
//! This module builds the first one. On the two-outcome index range `{0, 1}`:
//!
//! * `bernoulliVar R : Nat → R.carrier` is the indicator `0 ↦ 0`,
//!   `succ _ ↦ 1`;
//! * `bernoulliMass R q : Nat → R.carrier` is the mass `0 ↦ 1 − q`,
//!   `succ _ ↦ q`.
//!
//! Both are `Nat.rec` over the record's own `zero`/`one`/`add`/`neg`, so at
//! `R := AlgS.Rat.orderedRingS` they δι-reduce to `ℚ` terms and the three
//! theorems below become `ℚ` theorems by instantiation, not by analogy.
//!
//! **What the record costs here.** `AlgS.OrderedRing` carries no `mulComm`
//! (ADR-1592 §2). The variance identity `E[(X−q)²] ≃ q·(1−q)` is
//! nevertheless provable without it, because the subring generated by a
//! single element is commutative — but that fact has to be *supplied*, and
//! it is supplied as exactly one lemma: [`declare_bernoulli_variance`]'s
//! `hcomm : (1−q)·q ≃ q·(1−q)`, proved by expanding both sides to
//! `q + −(q·q)` with `distribL`/`distribR`. Once `q·(1−q)` and `(1−q)·q` are
//! interchangeable the whole computation collapses in four steps:
//! `q·(q·u) + u·(q·u) ≃ (q + u)·(q·u) ≃ 1·(q·u) ≃ q·u`, since `q + u ≃ 1`.
//! That is the entire content of "the Bernoulli variance is `p(1−p)`" once
//! the shelf is doing the work.
//!
//! Two generic ring lemmas the spine did not carry are declared first:
//! [`declare_mul_neg`] (`a·(−b) ≃ −(a·b)` — the spine has only the LEFT
//! side, `AlgS.OrderedRing.neg_mul`) and [`declare_zero_add`] (`0 + a ≃ a` —
//! the record's additive unit law is right-handed).
//!
//! Every theorem in this file is proved from the record's fields and the
//! already-declared `AlgS.*` ring calculus: no axiom, no classical
//! principle, no carrier-specific step.

