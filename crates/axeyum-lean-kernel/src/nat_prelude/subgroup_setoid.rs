/// `forall a b, G.equiv a b -> S a -> S b` — **the setoid-only obligation**.
fn respects_stmt(k: &mut Kernel, c: &GCtx, s: ExprId) -> ExprId {
    let a = k.fvar(A_FV);
    let b = k.fvar(B_FV);
    let hyp1 = c.eqv(k, a, b);
    let hyp2 = k.app(s, a);
    let concl = k.app(s, b);
    let t = pi_over(k, H2_FV, hyp2, concl);
    let t = pi_over(k, H1_FV, hyp1, t);
    let t = pi_over(k, B_FV, c.carrier, t);
    pi_over(k, A_FV, c.carrier, t)
}

/// `S G.e`.
fn mem_e_stmt(k: &mut Kernel, c: &GCtx, s: ExprId) -> ExprId {
    k.app(s, c.e)
}

/// `forall a b, S a -> S b -> S (G.op a b)`.
fn closed_op_stmt(k: &mut Kernel, c: &GCtx, s: ExprId) -> ExprId {
    let a = k.fvar(A_FV);
    let b = k.fvar(B_FV);
    let hyp1 = k.app(s, a);
    let hyp2 = k.app(s, b);
    let ab = app2(k, c.op, a, b);
    let concl = k.app(s, ab);
    let t = pi_over(k, H2_FV, hyp2, concl);
    let t = pi_over(k, H1_FV, hyp1, t);
    let t = pi_over(k, B_FV, c.carrier, t);
    pi_over(k, A_FV, c.carrier, t)
}

/// `forall a, S a -> S (G.inv a)`.
fn closed_inv_stmt(k: &mut Kernel, c: &GCtx, s: ExprId) -> ExprId {
    let a = k.fvar(A_FV);
    let hyp = k.app(s, a);
    let ia = k.app(c.inv, a);
    let concl = k.app(s, ia);
    let t = pi_over(k, H1_FV, hyp, concl);
    pi_over(k, A_FV, c.carrier, t)
}

fn four_stmts(k: &mut Kernel, c: &GCtx, s: ExprId) -> [ExprId; 4] {
    [
        respects_stmt(k, c, s),
        mem_e_stmt(k, c, s),
        closed_op_stmt(k, c, s),
        closed_inv_stmt(k, c, s),
    ]
}

/// `And p0 (And p1 (And p2 p3))`.
fn nest_and(k: &mut Kernel, lg: &LogicPrelude, props: &[ExprId; 4]) -> ExprId {
    let and_c = k.const_(lg.and, vec![]);
    let mut acc = props[3];
    for p in props[..3].iter().rev() {
        acc = app2(k, and_c, *p, acc);
    }
    acc
}

/// The `And.intro` chain matching [`nest_and`].
fn intro_and(
    k: &mut Kernel,
    lg: &LogicPrelude,
    props: &[ExprId; 4],
    proofs: &[ExprId; 4],
) -> ExprId {
    let and_c = k.const_(lg.and, vec![]);
    let mut tail_prop = props[3];
    let mut tail_val = proofs[3];
    for i in (0..3).rev() {
        let and_intro = k.const_(lg.and_intro, vec![]);
        tail_val = t_app(k, and_intro, &[props[i], tail_prop, proofs[i], tail_val]);
        tail_prop = app2(k, and_c, props[i], tail_prop);
    }
    tail_val
}

/// Project conjunct `which` (0..3) out of a proof of [`nest_and`].
fn project_and(
    k: &mut Kernel,
    lg: &LogicPrelude,
    props: &[ExprId; 4],
    h: ExprId,
    which: usize,
) -> ExprId {
    let and_c = k.const_(lg.and, vec![]);
    // `tails[i]` is what remains after `i` `And.right`s.
    let mut tails = vec![props[3]];
    for p in props[..3].iter().rev() {
        let last = *tails.last().expect("non-empty");
        tails.push(app2(k, and_c, *p, last));
    }
    tails.reverse();

    let mut cur = h;
    for (i, prop) in props.iter().enumerate().take(which) {
        let and_right = k.const_(lg.and_right, vec![]);
        cur = t_app(k, and_right, &[*prop, tails[i + 1], cur]);
    }
    if which == 3 {
        cur
    } else {
        let and_left = k.const_(lg.and_left, vec![]);
        t_app(k, and_left, &[props[which], tails[which + 1], cur])
    }
}

