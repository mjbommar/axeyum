#[derive(Debug, Clone, Copy, PartialEq, Eq)]
#[allow(clippy::struct_field_names)]
pub struct SubgroupDeps {
    pub hom_ker: NameId,
    pub hom_map_one: NameId,
    pub hom_map_inv: NameId,
}

/// Declare the whole `AlgS.Subgroup.*` namespace.
///
/// # Errors
///
/// Returns the trusted gate's rejection — an `Err` means
/// [`Kernel::add_declaration`] **refused** a proof term.
pub(crate) fn declare_subgroup_setoid(
    k: &mut Kernel,
    lg: &LogicPrelude,
    group: &RecordNames,
    deps: SubgroupDeps,
    algs_p: NameId,
) -> Result<SubgroupNames, KernelError> {
    let ns = k.name_str(algs_p, "Subgroup");

    let is_sub = declare_is_sub(k, lg, group, ns)?;
    let le = declare_le(k, group, ns)?;
    let inter = declare_inter(k, lg, group, ns)?;
    let top = declare_top(k, lg, group, ns)?;
    let bot = declare_bot(k, group, ns)?;

    let respects = declare_accessor(k, lg, group, is_sub, 0, "respects", ns)?;
    let mem_e = declare_accessor(k, lg, group, is_sub, 1, "mem_e", ns)?;
    let closed_op = declare_accessor(k, lg, group, is_sub, 2, "closedOp", ns)?;
    let closed_inv = declare_accessor(k, lg, group, is_sub, 3, "closedInv", ns)?;
    let acc = AccNames {
        respects,
        mem_e,
        closed_op,
        closed_inv,
    };

    let le_refl = declare_le_refl(k, group, le, ns)?;
    let le_trans = declare_le_trans(k, group, le, ns)?;
    let inter_le_left = declare_inter_le(k, lg, group, le, inter, true, ns)?;
    let inter_le_right = declare_inter_le(k, lg, group, le, inter, false, ns)?;
    let le_inter = declare_le_inter(k, lg, group, le, inter, ns)?;
    let inter_is_sub = declare_inter_is_sub(k, lg, group, is_sub, inter, acc, ns)?;
    let top_is_sub = declare_top_is_sub(k, lg, group, is_sub, top, ns)?;
    let bot_is_sub = declare_bot_is_sub(k, lg, group, is_sub, bot, ns)?;
    let le_top = declare_le_top(k, lg, group, le, top, ns)?;
    let bot_le = declare_bot_le(k, lg, group, is_sub, le, bot, respects, mem_e, ns)?;
    let ker_is_sub = declare_ker_is_sub(
        k,
        lg,
        group,
        is_sub,
        deps.hom_ker,
        deps.hom_map_one,
        deps.hom_map_inv,
        ns,
    )?;

    Ok(SubgroupNames {
        is_sub,
        le,
        inter,
        top,
        bot,
        respects,
        mem_e,
        closed_op,
        closed_inv,
        le_refl,
        le_trans,
        inter_le_left,
        inter_le_right,
        le_inter,
        inter_is_sub,
        top_is_sub,
        bot_is_sub,
        le_top,
        bot_le,
        ker_is_sub,
    })
}

