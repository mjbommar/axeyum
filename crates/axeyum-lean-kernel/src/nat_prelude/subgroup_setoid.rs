/// `AlgS.Subgroup.IsSub : forall (G : AlgS.Group), (G.carrier -> Prop) -> Prop`.
fn declare_is_sub(
    k: &mut Kernel,
    lg: &LogicPrelude,
    group: &RecordNames,
    ns: NameId,
) -> Result<NameId, KernelError> {
    let c = gctx(k, group, G_FV);
    let s = k.fvar(S_FV);
    let props = four_stmts(k, &c, s);
    let body = nest_and(k, lg, &props);
    let value = lam_over(k, S_FV, c.sub_ty, body);
    let value = lam_over(k, G_FV, c.group_ty, value);

    let l0 = k.level_zero();
    let prop = k.sort(l0);
    let ty = arrow(k, c.sub_ty, prop);
    let ty = pi_over(k, G_FV, c.group_ty, ty);

    let name = k.name_str(ns, "IsSub");
    k.add_declaration(Declaration::Definition {
        name,
        uparams: vec![],
        ty,
        value,
        hint: ReducibilityHint::Regular(1),
    })?;
    Ok(name)
}

/// `AlgS.Subgroup.le G S T := forall a, S a -> T a` — the lattice order.
