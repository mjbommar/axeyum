/// `AlgS.Subgroup.bot G := fun a => G.equiv a G.e` — the trivial subgroup.
///
/// **Not the singleton `{G.e}`**: over a setoid the smallest subgroup is the
/// equivalence CLASS of the identity, because a subgroup must be closed under
/// `G.equiv` (`IsSub`'s first conjunct). `fun a => Eq a G.e` would not be a
/// subgroup of a carrier whose equality is a defined relation.
fn declare_bot(k: &mut Kernel, group: &RecordNames, ns: NameId) -> Result<NameId, KernelError> {
    let c = gctx(k, group, G_FV);
    let a = k.fvar(A_FV);
    let body = c.eqv(k, a, c.e);
    let body = lam_over(k, A_FV, c.carrier, body);
    let value = lam_over(k, G_FV, c.group_ty, body);
    let ty = pi_over(k, G_FV, c.group_ty, c.sub_ty);

    let name = k.name_str(ns, "bot");
    k.add_declaration(Declaration::Definition {
        name,
        uparams: vec![],
        ty,
        value,
        hint: ReducibilityHint::Regular(1),
    })?;
    Ok(name)
}

