fn declare_accessor(
    k: &mut Kernel,
    lg: &LogicPrelude,
    group: &RecordNames,
    is_sub: NameId,
    which: usize,
    suffix: &str,
    ns: NameId,
) -> Result<NameId, KernelError> {
    let c = gctx(k, group, G_FV);
    let s = k.fvar(S_FV);
    let props = four_stmts(k, &c, s);
    let hyp_ty = {
        let t = k.const_(is_sub, vec![]);
        app2(k, t, c.g, s)
    };
    let h = k.fvar(HS_FV);
    let proof = project_and(k, lg, &props, h, which);

    let value = lam_over(k, HS_FV, hyp_ty, proof);
    let value = lam_over(k, S_FV, c.sub_ty, value);
    let value = lam_over(k, G_FV, c.group_ty, value);

    let ty = pi_over(k, HS_FV, hyp_ty, props[which]);
    let ty = pi_over(k, S_FV, c.sub_ty, ty);
    let ty = pi_over(k, G_FV, c.group_ty, ty);

    let name = k.name_str(ns, suffix);
    k.add_declaration(Declaration::Theorem {
        name,
        uparams: vec![],
        ty,
        value,
    })?;
    Ok(name)
}

