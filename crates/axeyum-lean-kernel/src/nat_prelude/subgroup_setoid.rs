//! `AlgS.Subgroup.*` — the residue of roadmap W1-11: subgroups of an
//! **abstract** `AlgS.Group`, and the meet-semilattice they form, built by the
//! setoid route (ADR-1595, ADR-1609). W1-11's homomorphism/kernel/image half
//! landed with `AlgS.Hom.*`; this is the subobject half, and it closes back
//! onto that one with `AlgS.Subgroup.ker_isSub`.
//!
//! # A subgroup is a predicate, and the setoid adds exactly one obligation
//!
//! This kernel has no `Subtype` and no `Sigma` (both verified ABSENT,
//! ADR-1595), so a subgroup cannot be a carrier. It is a **predicate**
//! `S : G.carrier -> Prop` together with closure conditions — the same shape
//! `AlgS.Hom.ker` and `AlgS.Hom.image` already use.
//!
//! `AlgS.Subgroup.IsSub` has **four** conjuncts where the `Eq`-flavored
//! version would have three:
//!
//! | conjunct | free under `Eq`? |
//! |---|---|
//! | `forall a b, G.equiv a b -> S a -> S b` | **YES** — `Eq.subst` gives it |
//! | `S G.e` | no |
//! | `forall a b, S a -> S b -> S (G.op a b)` | no |
//! | `forall a, S a -> S (G.inv a)` | no |
//!
//! So the measured setoid cost of the whole subobject layer is **one field**,
//! and it is not decoration: `AlgS.Subgroup.bot_le` cannot be proved without
//! it, because the trivial subgroup over a setoid is the equivalence CLASS of
//! `G.e` (`fun a => G.equiv a G.e`), not the singleton — and showing it sits
//! inside every subgroup is exactly a transport along `G.equiv`.
//!
//! # The lattice
//!
//! Order is implication (`le S T := forall a, S a -> T a`), meet is
//! intersection, `top` is `fun _ => True`, `bot` is the class of the
//! identity. `inter_le_left`/`inter_le_right`/`le_inter` are the
//! greatest-lower-bound property, so this is a bounded meet-semilattice with
//! `IsSub` closed under all three constructions. The JOIN is not here: the
//! subgroup generated by a union needs a word/closure construction, which
//! needs an inductive family over `G.carrier` — sized in ADR-1609.

