/// `AlgS.Subgroup.le_trans : forall G S T U, le G S T -> le G T U -> le G S U`.
fn declare_le_trans(
    k: &mut Kernel,
    group: &RecordNames,
    le: NameId,
    ns: NameId,
) -> Result<NameId, KernelError> {
    let c = gctx(k, group, G_FV);
    let s = k.fvar(S_FV);
    let t = k.fvar(T_FV);
    let u = k.fvar(U_FV);
    let le_st = {
        let l = k.const_(le, vec![]);
        t_app(k, l, &[c.g, s, t])
    };
    let le_tu = {
        let l = k.const_(le, vec![]);
        t_app(k, l, &[c.g, t, u])
    };
    let le_su = {
        let l = k.const_(le, vec![]);
        t_app(k, l, &[c.g, s, u])
    };
    let h1 = k.fvar(HS_FV);
    let h2 = k.fvar(HT_FV);
    let a = k.fvar(A_FV);
    let sa = k.app(s, a);
    let ha = k.fvar(H1_FV);
    let step1 = {
        let f = k.app(h1, a);
        k.app(f, ha)
    };
    let step2 = {
        let f = k.app(h2, a);
        k.app(f, step1)
    };
    let body = lam_over(k, H1_FV, sa, step2);
    let body = lam_over(k, A_FV, c.carrier, body);
    let value = lam_over(k, HT_FV, le_tu, body);
    let value = lam_over(k, HS_FV, le_st, value);
    let value = lam_over(k, U_FV, c.sub_ty, value);
    let value = lam_over(k, T_FV, c.sub_ty, value);
    let value = lam_over(k, S_FV, c.sub_ty, value);
    let value = lam_over(k, G_FV, c.group_ty, value);

    let ty = pi_over(k, HT_FV, le_tu, le_su);
    let ty = pi_over(k, HS_FV, le_st, ty);
    let ty = pi_over(k, U_FV, c.sub_ty, ty);
    let ty = pi_over(k, T_FV, c.sub_ty, ty);
    let ty = pi_over(k, S_FV, c.sub_ty, ty);
    let ty = pi_over(k, G_FV, c.group_ty, ty);

    let name = k.name_str(ns, "le_trans");
    k.add_declaration(Declaration::Theorem {
        name,
        uparams: vec![],
        ty,
        value,
    })?;
    Ok(name)
}

/// `AlgS.Subgroup.inter_le_left` / `..._right`: the meet is below both sides.
fn declare_inter_le(
    k: &mut Kernel,
    lg: &LogicPrelude,
    group: &RecordNames,
    le: NameId,
    inter: NameId,
    left: bool,
    ns: NameId,
) -> Result<NameId, KernelError> {
    let c = gctx(k, group, G_FV);
    let s = k.fvar(S_FV);
    let t = k.fvar(T_FV);
    let a = k.fvar(A_FV);
    let sa = k.app(s, a);
    let ta = k.app(t, a);
    let and_c = k.const_(lg.and, vec![]);
    let hyp = app2(k, and_c, sa, ta);
    let h = k.fvar(H1_FV);
    let proj = if left {
        let al = k.const_(lg.and_left, vec![]);
        t_app(k, al, &[sa, ta, h])
    } else {
        let ar = k.const_(lg.and_right, vec![]);
        t_app(k, ar, &[sa, ta, h])
    };
    let body = lam_over(k, H1_FV, hyp, proj);
    let body = lam_over(k, A_FV, c.carrier, body);
    let value = lam_over(k, T_FV, c.sub_ty, body);
    let value = lam_over(k, S_FV, c.sub_ty, value);
    let value = lam_over(k, G_FV, c.group_ty, value);

    let concl = {
        let i = k.const_(inter, vec![]);
        let st = t_app(k, i, &[c.g, s, t]);
        let l = k.const_(le, vec![]);
        let target = if left { s } else { t };
        t_app(k, l, &[c.g, st, target])
    };
    let ty = pi_over(k, T_FV, c.sub_ty, concl);
    let ty = pi_over(k, S_FV, c.sub_ty, ty);
    let ty = pi_over(k, G_FV, c.group_ty, ty);

    let suffix = if left {
        "inter_le_left"
    } else {
        "inter_le_right"
    };
    let name = k.name_str(ns, suffix);
    k.add_declaration(Declaration::Theorem {
        name,
        uparams: vec![],
        ty,
        value,
    })?;
    Ok(name)
}

/// `AlgS.Subgroup.le_inter : forall G S T U, le G U S -> le G U T ->
/// le G U (inter G S T)` — the greatest-lower-bound half.
fn declare_le_inter(
    k: &mut Kernel,
    lg: &LogicPrelude,
    group: &RecordNames,
    le: NameId,
    inter: NameId,
    ns: NameId,
) -> Result<NameId, KernelError> {
    let c = gctx(k, group, G_FV);
    let s = k.fvar(S_FV);
    let t = k.fvar(T_FV);
    let u = k.fvar(U_FV);
    let le_us = {
        let l = k.const_(le, vec![]);
        t_app(k, l, &[c.g, u, s])
    };
    let le_ut = {
        let l = k.const_(le, vec![]);
        t_app(k, l, &[c.g, u, t])
    };
    let h1 = k.fvar(HS_FV);
    let h2 = k.fvar(HT_FV);
    let a = k.fvar(A_FV);
    let ua = k.app(u, a);
    let hu = k.fvar(H1_FV);
    let sa = k.app(s, a);
    let ta = k.app(t, a);
    let p1 = {
        let f = k.app(h1, a);
        k.app(f, hu)
    };
    let p2 = {
        let f = k.app(h2, a);
        k.app(f, hu)
    };
    let and_intro = k.const_(lg.and_intro, vec![]);
    let body = t_app(k, and_intro, &[sa, ta, p1, p2]);
    let body = lam_over(k, H1_FV, ua, body);
    let body = lam_over(k, A_FV, c.carrier, body);
    let value = lam_over(k, HT_FV, le_ut, body);
    let value = lam_over(k, HS_FV, le_us, value);
    let value = lam_over(k, U_FV, c.sub_ty, value);
    let value = lam_over(k, T_FV, c.sub_ty, value);
    let value = lam_over(k, S_FV, c.sub_ty, value);
    let value = lam_over(k, G_FV, c.group_ty, value);

    let concl = {
        let i = k.const_(inter, vec![]);
        let st = t_app(k, i, &[c.g, s, t]);
        let l = k.const_(le, vec![]);
        t_app(k, l, &[c.g, u, st])
    };
    let ty = pi_over(k, HT_FV, le_ut, concl);
    let ty = pi_over(k, HS_FV, le_us, ty);
    let ty = pi_over(k, U_FV, c.sub_ty, ty);
    let ty = pi_over(k, T_FV, c.sub_ty, ty);
    let ty = pi_over(k, S_FV, c.sub_ty, ty);
    let ty = pi_over(k, G_FV, c.group_ty, ty);

    let name = k.name_str(ns, "le_inter");
    k.add_declaration(Declaration::Theorem {
        name,
        uparams: vec![],
        ty,
        value,
    })?;
    Ok(name)
}

