/// `AlgS.Subgroup.bot_le : forall G S, IsSub G S -> le G (bot G) S`.
///
/// **This is the theorem that spends the setoid's extra conjunct.** From
/// `h : G.equiv a G.e` we must produce `S a` out of `S G.e`, and the only
/// route is `IsSub`'s `respects` field applied to `G.equivSymm h`. Under `Eq`
/// this step would be `Eq.subst` and the field would not exist.
#[allow(clippy::too_many_arguments)]
fn declare_bot_le(
    k: &mut Kernel,
    lg: &LogicPrelude,
    group: &RecordNames,
    is_sub: NameId,
    le: NameId,
    bot: NameId,
    respects: NameId,
    mem_e: NameId,
    ns: NameId,
) -> Result<NameId, KernelError> {
    let c = gctx(k, group, G_FV);
    let s = k.fvar(S_FV);
    let hyp_ty = {
        let t = k.const_(is_sub, vec![]);
        app2(k, t, c.g, s)
    };
    let hs = k.fvar(HS_FV);
    let a = k.fvar(A_FV);
    let ha_ty = c.eqv(k, a, c.e);
    let ha = k.fvar(H1_FV);
    let sym = c.sy(k, a, c.e, ha); // G.equiv G.e a
    let mem = {
        let t = k.const_(mem_e, vec![]);
        t_app(k, t, &[c.g, s, hs])
    };
    let body = {
        let t = k.const_(respects, vec![]);
        let r = t_app(k, t, &[c.g, s, hs]);
        t_app(k, r, &[c.e, a, sym, mem])
    };
    let body = lam_over(k, H1_FV, ha_ty, body);
    let body = lam_over(k, A_FV, c.carrier, body);
    let value = lam_over(k, HS_FV, hyp_ty, body);
    let value = lam_over(k, S_FV, c.sub_ty, value);
    let value = lam_over(k, G_FV, c.group_ty, value);

    let concl = {
        let b = k.const_(bot, vec![]);
        let bg = k.app(b, c.g);
        let l = k.const_(le, vec![]);
        t_app(k, l, &[c.g, bg, s])
    };
    let ty = pi_over(k, HS_FV, hyp_ty, concl);
    let ty = pi_over(k, S_FV, c.sub_ty, ty);
    let ty = pi_over(k, G_FV, c.group_ty, ty);
    let _ = lg;

    let name = k.name_str(ns, "bot_le");
    k.add_declaration(Declaration::Theorem {
        name,
        uparams: vec![],
        ty,
        value,
    })?;
    Ok(name)
}

