/// `AlgS.Subgroup.bot_isSub : forall G, IsSub G (bot G)` — the identity's
/// equivalence class is a subgroup. `respects` is `equivTrans ∘ equivSymm`,
/// `closedOp` is `opCongr` then `identL`, and `closedInv` needs
/// `G.equiv (G.inv G.e) G.e`, which is `identR` symm'd against `invL`.
#[allow(clippy::too_many_lines)]
fn declare_bot_is_sub(
    k: &mut Kernel,
    lg: &LogicPrelude,
    group: &RecordNames,
    is_sub: NameId,
    bot: NameId,
    ns: NameId,
) -> Result<NameId, KernelError> {
    let c = gctx(k, group, G_FV);
    let bot_g = {
        let t = k.const_(bot, vec![]);
        k.app(t, c.g)
    };
    let props = four_stmts(k, &c, bot_g);

    // 0. respects : a ~ b -> a ~ e -> b ~ e
    let p0 = {
        let a = k.fvar(A_FV);
        let b = k.fvar(B_FV);
        let hab_ty = c.eqv(k, a, b);
        let hab = k.fvar(H1_FV);
        let hae_ty = c.eqv(k, a, c.e);
        let hae = k.fvar(H2_FV);
        let hba = c.sy(k, a, b, hab); // b ~ a
        let body = c.tr(k, b, a, c.e, hba, hae);
        let body = lam_over(k, H2_FV, hae_ty, body);
        let body = lam_over(k, H1_FV, hab_ty, body);
        let body = lam_over(k, B_FV, c.carrier, body);
        lam_over(k, A_FV, c.carrier, body)
    };
    // 1. mem_e : e ~ e
    let p1 = k.app(c.refl, c.e);
    // 2. closedOp : a ~ e -> b ~ e -> a*b ~ e
    let p2 = {
        let a = k.fvar(A_FV);
        let b = k.fvar(B_FV);
        let ha_ty = c.eqv(k, a, c.e);
        let hb_ty = c.eqv(k, b, c.e);
        let ha = k.fvar(H1_FV);
        let hb = k.fvar(H2_FV);
        let ab = app2(k, c.op, a, b);
        let ee = app2(k, c.op, c.e, c.e);
        let congr = t_app(k, c.op_congr, &[a, c.e, b, c.e, ha, hb]);
        let idl = k.app(c.ident_l, c.e); // op e e ~ e
        let body = c.tr(k, ab, ee, c.e, congr, idl);
        let body = lam_over(k, H2_FV, hb_ty, body);
        let body = lam_over(k, H1_FV, ha_ty, body);
        let body = lam_over(k, B_FV, c.carrier, body);
        lam_over(k, A_FV, c.carrier, body)
    };
    // 3. closedInv : a ~ e -> inv a ~ e
    let p3 = {
        let a = k.fvar(A_FV);
        let ha_ty = c.eqv(k, a, c.e);
        let ha = k.fvar(H1_FV);
        let ia = k.app(c.inv, a);
        let ie = k.app(c.inv, c.e);
        let congr = t_app(k, c.inv_congr, &[a, c.e, ha]); // inv a ~ inv e
        // inv e ~ e : identR (inv e) symm'd, then invL e.
        let ie_e = app2(k, c.op, ie, c.e);
        let idr = k.app(c.ident_r, ie); // op (inv e) e ~ inv e
        let idr_s = c.sy(k, ie_e, ie, idr); // inv e ~ op (inv e) e
        let invl = k.app(c.inv_l, c.e); // op (inv e) e ~ e
        let inv_e_e = c.tr(k, ie, ie_e, c.e, idr_s, invl);
        let body = c.tr(k, ia, ie, c.e, congr, inv_e_e);
        let body = lam_over(k, H1_FV, ha_ty, body);
        lam_over(k, A_FV, c.carrier, body)
    };

    let proofs = [p0, p1, p2, p3];
    let body = intro_and(k, lg, &props, &proofs);
    let value = lam_over(k, G_FV, c.group_ty, body);

    let concl = {
        let x = k.const_(is_sub, vec![]);
        app2(k, x, c.g, bot_g)
    };
    let ty = pi_over(k, G_FV, c.group_ty, concl);

    let name = k.name_str(ns, "bot_isSub");
    k.add_declaration(Declaration::Theorem {
        name,
        uparams: vec![],
        ty,
        value,
    })?;
    Ok(name)
}

/// `AlgS.Subgroup.ker_isSub : forall G H f fCongr fMul,
/// IsSub G (AlgS.Hom.ker G H f)` — **the kernel of a homomorphism is a
/// subgroup**, which is what joins this half of W1-11 to the half that landed
/// with `AlgS.Hom.firstIso`.
///
/// `respects` is `fCongr` symm'd and composed; `mem_e` is `AlgS.Hom.mapOne`
/// verbatim; `closedOp` is `fMul` then `H.opCongr` then `H.identL`;
/// `closedInv` is `AlgS.Hom.mapInv` then `H.invCongr` then
/// `H.equiv (H.inv H.e) H.e`.
#[allow(clippy::too_many_arguments, clippy::too_many_lines)]
fn declare_ker_is_sub(
    k: &mut Kernel,
    lg: &LogicPrelude,
    group: &RecordNames,
    is_sub: NameId,
    ker: NameId,
    map_one: NameId,
    map_inv: NameId,
    ns: NameId,
) -> Result<NameId, KernelError> {
    use idx::group::{
        CARRIER, E, EQUIV, EQUIV_SYMM, EQUIV_TRANS, IDENT_L, IDENT_R, INV, INV_CONGR, INV_L, OP,
        OP_CONGR,
    };
    let c = gctx(k, group, G_FV);
    let h = k.fvar(KH_FV);
    let hc = sel(k, group, CARRIER, h);
    let heq_sel = sel(k, group, EQUIV, h);
    let hsymm = sel(k, group, EQUIV_SYMM, h);
    let htrans = sel(k, group, EQUIV_TRANS, h);
    let hop = sel(k, group, OP, h);
    let hop_congr = sel(k, group, OP_CONGR, h);
    let he = sel(k, group, E, h);
    let hinv = sel(k, group, INV, h);
    let hinv_congr = sel(k, group, INV_CONGR, h);
    let hident_l = sel(k, group, IDENT_L, h);
    let hident_r = sel(k, group, IDENT_R, h);
    let hinv_l = sel(k, group, INV_L, h);

    let f = k.fvar(KF_FV);
    let f_ty = arrow(k, c.carrier, hc);
    let fc_ty = {
        let a = k.fvar(A_FV);
        let b = k.fvar(B_FV);
        let hyp = c.eqv(k, a, b);
        let fa = k.app(f, a);
        let fb = k.app(f, b);
        let concl = app2(k, heq_sel, fa, fb);
        let t = pi_over(k, H1_FV, hyp, concl);
        let t = pi_over(k, B_FV, c.carrier, t);
        pi_over(k, A_FV, c.carrier, t)
    };
    let fc = k.fvar(KFC_FV);
    let fm_ty = {
        let a = k.fvar(A_FV);
        let b = k.fvar(B_FV);
        let ab = app2(k, c.op, a, b);
        let f_ab = k.app(f, ab);
        let fa = k.app(f, a);
        let fb = k.app(f, b);
        let rhs = app2(k, hop, fa, fb);
        let concl = app2(k, heq_sel, f_ab, rhs);
        let t = pi_over(k, B_FV, c.carrier, concl);
        pi_over(k, A_FV, c.carrier, t)
    };
    let fm = k.fvar(KFM_FV);

    let ker_s = {
        let t = k.const_(ker, vec![]);
        t_app(k, t, &[c.g, h, f])
    };
    let props = four_stmts(k, &c, ker_s);

    let htr = |k: &mut Kernel, x: ExprId, y: ExprId, z: ExprId, p: ExprId, q: ExprId| {
        t_app(k, htrans, &[x, y, z, p, q])
    };

    // 0. respects : a ~ b -> f a ~ H.e -> f b ~ H.e
    let p0 = {
        let a = k.fvar(A_FV);
        let b = k.fvar(B_FV);
        let hab_ty = c.eqv(k, a, b);
        let hab = k.fvar(H1_FV);
        let fa = k.app(f, a);
        let fb = k.app(f, b);
        let ka_ty = app2(k, heq_sel, fa, he);
        let ka = k.fvar(H2_FV);
        let fab = t_app(k, fc, &[a, b, hab]); // f a ~ f b
        let fba = t_app(k, hsymm, &[fa, fb, fab]); // f b ~ f a
        let body = htr(k, fb, fa, he, fba, ka);
        let body = lam_over(k, H2_FV, ka_ty, body);
        let body = lam_over(k, H1_FV, hab_ty, body);
        let body = lam_over(k, B_FV, c.carrier, body);
        lam_over(k, A_FV, c.carrier, body)
    };
    // 1. mem_e : f G.e ~ H.e — `AlgS.Hom.mapOne` verbatim.
    let p1 = {
        let t = k.const_(map_one, vec![]);
        t_app(k, t, &[c.g, h, f, fc, fm])
    };
    // 2. closedOp
    let p2 = {
        let a = k.fvar(A_FV);
        let b = k.fvar(B_FV);
        let fa = k.app(f, a);
        let fb = k.app(f, b);
        let ka_ty = app2(k, heq_sel, fa, he);
        let kb_ty = app2(k, heq_sel, fb, he);
        let ka = k.fvar(H1_FV);
        let kb = k.fvar(H2_FV);
        let ab = app2(k, c.op, a, b);
        let f_ab = k.app(f, ab);
        let prod = app2(k, hop, fa, fb);
        let ee = app2(k, hop, he, he);
        let s1 = t_app(k, fm, &[a, b]); // f(a*b) ~ f a * f b
        let s2 = t_app(k, hop_congr, &[fa, he, fb, he, ka, kb]); // ~ e*e
        let s3 = k.app(hident_l, he); // e*e ~ e
        let step = htr(k, prod, ee, he, s2, s3);
        let body = htr(k, f_ab, prod, he, s1, step);
        let body = lam_over(k, H2_FV, kb_ty, body);
        let body = lam_over(k, H1_FV, ka_ty, body);
        let body = lam_over(k, B_FV, c.carrier, body);
        lam_over(k, A_FV, c.carrier, body)
    };
    // 3. closedInv
    let p3 = {
        let a = k.fvar(A_FV);
        let fa = k.app(f, a);
        let ka_ty = app2(k, heq_sel, fa, he);
        let ka = k.fvar(H1_FV);
        let ia = k.app(c.inv, a);
        let f_ia = k.app(f, ia);
        let inv_fa = k.app(hinv, fa);
        let inv_e = k.app(hinv, he);
        let s1 = {
            let t = k.const_(map_inv, vec![]);
            let m = t_app(k, t, &[c.g, h, f, fc, fm]);
            k.app(m, a)
        }; // f (inv a) ~ H.inv (f a)
        let s2 = t_app(k, hinv_congr, &[fa, he, ka]); // H.inv (f a) ~ H.inv H.e
        // H.inv H.e ~ H.e
        let ie_e = app2(k, hop, inv_e, he);
        let idr = k.app(hident_r, inv_e);
        let idr_s = t_app(k, hsymm, &[ie_e, inv_e, idr]);
        let invl = k.app(hinv_l, he);
        let s3 = htr(k, inv_e, ie_e, he, idr_s, invl);
        let step = htr(k, inv_fa, inv_e, he, s2, s3);
        let body = htr(k, f_ia, inv_fa, he, s1, step);
        let body = lam_over(k, H1_FV, ka_ty, body);
        lam_over(k, A_FV, c.carrier, body)
    };

    let proofs = [p0, p1, p2, p3];
    let body = intro_and(k, lg, &props, &proofs);
    let value = lam_over(k, KFM_FV, fm_ty, body);
    let value = lam_over(k, KFC_FV, fc_ty, value);
    let value = lam_over(k, KF_FV, f_ty, value);
    let value = lam_over(k, KH_FV, c.group_ty, value);
    let value = lam_over(k, G_FV, c.group_ty, value);

    let concl = {
        let x = k.const_(is_sub, vec![]);
        app2(k, x, c.g, ker_s)
    };
    let ty = pi_over(k, KFM_FV, fm_ty, concl);
    let ty = pi_over(k, KFC_FV, fc_ty, ty);
    let ty = pi_over(k, KF_FV, f_ty, ty);
    let ty = pi_over(k, KH_FV, c.group_ty, ty);
    let ty = pi_over(k, G_FV, c.group_ty, ty);

    let name = k.name_str(ns, "ker_isSub");
    k.add_declaration(Declaration::Theorem {
        name,
        uparams: vec![],
        ty,
        value,
    })?;
    Ok(name)
}

