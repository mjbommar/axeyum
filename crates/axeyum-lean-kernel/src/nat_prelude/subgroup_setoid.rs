/// Accessor names, so the closure theorems can take conjuncts apart by name.
#[derive(Debug, Clone, Copy, PartialEq, Eq)]
struct AccNames {
    respects: NameId,
    mem_e: NameId,
    closed_op: NameId,
    closed_inv: NameId,
}

/// `AlgS.Subgroup.inter_isSub : forall G S T, IsSub G S -> IsSub G T ->
/// IsSub G (inter G S T)` — the meet of two subgroups is a subgroup.
#[allow(clippy::too_many_arguments, clippy::too_many_lines)]
fn declare_inter_is_sub(
    k: &mut Kernel,
    lg: &LogicPrelude,
    group: &RecordNames,
    is_sub: NameId,
    inter: NameId,
    acc: AccNames,
    ns: NameId,
) -> Result<NameId, KernelError> {
    let c = gctx(k, group, G_FV);
    let s = k.fvar(S_FV);
    let t = k.fvar(T_FV);
    let hyp_s = {
        let x = k.const_(is_sub, vec![]);
        app2(k, x, c.g, s)
    };
    let hyp_t = {
        let x = k.const_(is_sub, vec![]);
        app2(k, x, c.g, t)
    };
    let hs = k.fvar(HS_FV);
    let ht = k.fvar(HT_FV);

    let use_acc = |k: &mut Kernel, name: NameId, sub: ExprId, h: ExprId| {
        let x = k.const_(name, vec![]);
        t_app(k, x, &[c.g, sub, h])
    };
    let and_intro_at = |k: &mut Kernel, pa: ExprId, pb: ExprId, va: ExprId, vb: ExprId| {
        let ai = k.const_(lg.and_intro, vec![]);
        t_app(k, ai, &[pa, pb, va, vb])
    };
    let and_l = |k: &mut Kernel, pa: ExprId, pb: ExprId, h: ExprId| {
        let al = k.const_(lg.and_left, vec![]);
        t_app(k, al, &[pa, pb, h])
    };
    let and_r = |k: &mut Kernel, pa: ExprId, pb: ExprId, h: ExprId| {
        let ar = k.const_(lg.and_right, vec![]);
        t_app(k, ar, &[pa, pb, h])
    };

    let inter_st = {
        let i = k.const_(inter, vec![]);
        t_app(k, i, &[c.g, s, t])
    };
    let props = four_stmts(k, &c, inter_st);

    // 0. respects
    let p_respects = {
        let a = k.fvar(A_FV);
        let b = k.fvar(B_FV);
        let hab_ty = c.eqv(k, a, b);
        let hab = k.fvar(H1_FV);
        let sa = k.app(s, a);
        let ta = k.app(t, a);
        let sb = k.app(s, b);
        let tb = k.app(t, b);
        let and_c = k.const_(lg.and, vec![]);
        let hyp = app2(k, and_c, sa, ta);
        let h = k.fvar(H2_FV);
        let hl = and_l(k, sa, ta, h);
        let hr = and_r(k, sa, ta, h);
        let rs = use_acc(k, acc.respects, s, hs);
        let rt = use_acc(k, acc.respects, t, ht);
        let vs = t_app(k, rs, &[a, b, hab, hl]);
        let vt = t_app(k, rt, &[a, b, hab, hr]);
        let body = and_intro_at(k, sb, tb, vs, vt);
        let body = lam_over(k, H2_FV, hyp, body);
        let body = lam_over(k, H1_FV, hab_ty, body);
        let body = lam_over(k, B_FV, c.carrier, body);
        lam_over(k, A_FV, c.carrier, body)
    };
    // 1. mem_e
    let p_mem_e = {
        let se = k.app(s, c.e);
        let te = k.app(t, c.e);
        let vs = use_acc(k, acc.mem_e, s, hs);
        let vt = use_acc(k, acc.mem_e, t, ht);
        and_intro_at(k, se, te, vs, vt)
    };
    // 2. closed_op
    let p_closed_op = {
        let a = k.fvar(A_FV);
        let b = k.fvar(B_FV);
        let sa = k.app(s, a);
        let ta = k.app(t, a);
        let sb = k.app(s, b);
        let tb = k.app(t, b);
        let and_c = k.const_(lg.and, vec![]);
        let hyp_a = app2(k, and_c, sa, ta);
        let and_c2 = k.const_(lg.and, vec![]);
        let hyp_b = app2(k, and_c2, sb, tb);
        let hva = k.fvar(H1_FV);
        let hvb = k.fvar(H2_FV);
        let sa_l = and_l(k, sa, ta, hva);
        let ta_r = and_r(k, sa, ta, hva);
        let sb_l = and_l(k, sb, tb, hvb);
        let tb_r = and_r(k, sb, tb, hvb);
        let cs = use_acc(k, acc.closed_op, s, hs);
        let ct = use_acc(k, acc.closed_op, t, ht);
        let vs = t_app(k, cs, &[a, b, sa_l, sb_l]);
        let vt = t_app(k, ct, &[a, b, ta_r, tb_r]);
        let ab = app2(k, c.op, a, b);
        let sab = k.app(s, ab);
        let tab = k.app(t, ab);
        let body = and_intro_at(k, sab, tab, vs, vt);
        let body = lam_over(k, H2_FV, hyp_b, body);
        let body = lam_over(k, H1_FV, hyp_a, body);
        let body = lam_over(k, B_FV, c.carrier, body);
        lam_over(k, A_FV, c.carrier, body)
    };
    // 3. closed_inv
    let p_closed_inv = {
        let a = k.fvar(A_FV);
        let sa = k.app(s, a);
        let ta = k.app(t, a);
        let and_c = k.const_(lg.and, vec![]);
        let hyp = app2(k, and_c, sa, ta);
        let h = k.fvar(H1_FV);
        let hl = and_l(k, sa, ta, h);
        let hr = and_r(k, sa, ta, h);
        let cs = use_acc(k, acc.closed_inv, s, hs);
        let ct = use_acc(k, acc.closed_inv, t, ht);
        let vs = t_app(k, cs, &[a, hl]);
        let vt = t_app(k, ct, &[a, hr]);
        let ia = k.app(c.inv, a);
        let sia = k.app(s, ia);
        let tia = k.app(t, ia);
        let body = and_intro_at(k, sia, tia, vs, vt);
        let body = lam_over(k, H1_FV, hyp, body);
        lam_over(k, A_FV, c.carrier, body)
    };

    let proofs = [p_respects, p_mem_e, p_closed_op, p_closed_inv];
    let body = intro_and(k, lg, &props, &proofs);
    let value = lam_over(k, HT_FV, hyp_t, body);
    let value = lam_over(k, HS_FV, hyp_s, value);
    let value = lam_over(k, T_FV, c.sub_ty, value);
    let value = lam_over(k, S_FV, c.sub_ty, value);
    let value = lam_over(k, G_FV, c.group_ty, value);

    let concl = {
        let x = k.const_(is_sub, vec![]);
        app2(k, x, c.g, inter_st)
    };
    let ty = pi_over(k, HT_FV, hyp_t, concl);
    let ty = pi_over(k, HS_FV, hyp_s, ty);
    let ty = pi_over(k, T_FV, c.sub_ty, ty);
    let ty = pi_over(k, S_FV, c.sub_ty, ty);
    let ty = pi_over(k, G_FV, c.group_ty, ty);

    let name = k.name_str(ns, "inter_isSub");
    k.add_declaration(Declaration::Theorem {
        name,
        uparams: vec![],
        ty,
        value,
    })?;
    Ok(name)
}

