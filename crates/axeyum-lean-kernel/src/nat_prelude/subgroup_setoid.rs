struct GCtx {
    g: ExprId,
    group_ty: ExprId,
    carrier: ExprId,
    equiv: ExprId,
    refl: ExprId,
    symm: ExprId,
    trans: ExprId,
    op: ExprId,
    op_congr: ExprId,
    e: ExprId,
    inv: ExprId,
    inv_congr: ExprId,
    ident_l: ExprId,
    ident_r: ExprId,
    inv_l: ExprId,
    /// `G.carrier -> Prop`, the type of a subgroup predicate.
    sub_ty: ExprId,
}

fn gctx(k: &mut Kernel, group: &RecordNames, fv: u64) -> GCtx {
    use idx::group::{
        CARRIER, E, EQUIV, EQUIV_REFL, EQUIV_SYMM, EQUIV_TRANS, IDENT_L, IDENT_R, INV, INV_CONGR,
        INV_L, OP, OP_CONGR,
    };
    let group_ty = k.const_(group.ind, vec![]);
    let g = k.fvar(fv);
    let carrier = sel(k, group, CARRIER, g);
    let l0 = k.level_zero();
    let prop = k.sort(l0);
    let sub_ty = arrow(k, carrier, prop);
    GCtx {
        g,
        group_ty,
        carrier,
        equiv: sel(k, group, EQUIV, g),
        refl: sel(k, group, EQUIV_REFL, g),
        symm: sel(k, group, EQUIV_SYMM, g),
        trans: sel(k, group, EQUIV_TRANS, g),
        op: sel(k, group, OP, g),
        op_congr: sel(k, group, OP_CONGR, g),
        e: sel(k, group, E, g),
        inv: sel(k, group, INV, g),
        inv_congr: sel(k, group, INV_CONGR, g),
        ident_l: sel(k, group, IDENT_L, g),
        ident_r: sel(k, group, IDENT_R, g),
        inv_l: sel(k, group, INV_L, g),
        sub_ty,
    }
}

impl GCtx {
    fn eqv(&self, k: &mut Kernel, a: ExprId, b: ExprId) -> ExprId {
        app2(k, self.equiv, a, b)
    }
    fn tr(
        &self,
        k: &mut Kernel,
        a: ExprId,
        b: ExprId,
        c: ExprId,
        h1: ExprId,
        h2: ExprId,
    ) -> ExprId {
        t_app(k, self.trans, &[a, b, c, h1, h2])
    }
    fn sy(&self, k: &mut Kernel, a: ExprId, b: ExprId, h: ExprId) -> ExprId {
        t_app(k, self.symm, &[a, b, h])
    }
}

