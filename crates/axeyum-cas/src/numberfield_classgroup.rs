//! Composition of binary quadratic forms, and the class group as a **group**.
//!
//! Item 4 of the CAS *Next Ten*, third wave. [`super`] gives the class group of
//! an imaginary quadratic order as a **set** — the list of reduced positive
//! definite primitive forms of discriminant `D < 0`, with a certificate that
//! recounts the region. This module supplies the missing law: Dirichlet
//! composition, the Cayley table it generates, the invariant-factor
//! decomposition of that table, and the correspondence between form classes and
//! ideal classes checked in both directions.
//!
//! Everything is exact `BigInt`; every collection reaching an output is a
//! `Vec` in a producer-fixed order or a [`BTreeMap`]/[`BTreeSet`], so results
//! are deterministic. No `f64`, no new dependency.
//!
//! # What this module computes
//!
//! - [`reduce_form`] — the unique reduced form of a class, with a
//!   [`FormReductionCertificate`] carrying every `SL₂(ℤ)` step.
//! - [`compose`] — Dirichlet composition (in the *Cohen* Algorithm 5.4.7
//!   presentation, **not** Shanks's NUCOMP: NUCOMP's whole point is to keep
//!   intermediate coefficients small, which is a performance property, and the
//!   sizes here are bounded by the class-group order bound anyway) followed by
//!   reduction, with a [`CompositionCertificate`].
//! - [`class_group`] — the whole group: the Cayley table over the reduced
//!   forms, the identity, the inverses, the element orders and the
//!   invariant-factor decomposition, with a [`ClassGroupCertificate`].
//! - [`class_of_ideal`] — the reduced form of an ideal's class, with a
//!   [`FormIdealCertificate`] that checks the correspondence **both ways**.
//! - [`is_principal`] — principality decided by that reduced form, with a
//!   [`PrincipalityCertificate`]. This closes the `uncertified` item wave two
//!   named explicitly ("Non-principality is not certified").
//!
//! # The correspondence, and the normalization every certificate uses
//!
//! Write `ω = (t + √D)/2`, which is exactly the `ω` [`QuadraticOrder`] already
//! carries (`t = 1, n = (d−1)/4` for `d ≡ 1 (mod 4)`; `t = 0, n = d`
//! otherwise), so `√D = 2ω − t`. A form `(a, b, c)` of discriminant `D` maps to
//!
//! ```text
//!     I_f = ℤ·a + ℤ·(−b + √D)/2 = ℤ·a + ℤ·(B + ω),   B = −(b + t)/2 mod a
//! ```
//!
//! which is a [`super::Ideal`] Hermite triple `(a, B, 1)` of norm `a`. `b + t`
//! is even because `b ≡ D ≡ t (mod 2)`. Backwards, a primitive ideal
//! `(a, B, 1)` maps to `(a, −2B − t, N(B + ω)/a)`; the two maps are mutually
//! inverse on **normalized** forms (`−a < b ≤ a`), and a reduced form is
//! normalized. [`FormIdealCertificate`] runs both directions, so neither map is
//! trusted from the other.
//!
//! **The composition identity is checked on the ideal side, over ℤ.** With
//! `d₁ = gcd(a₁, a₂, (b₁+b₂)/2)` and `h₀` the unreduced composite,
//!
//! ```text
//!     I_f · I_g  =  d₁ · I_{h₀}                                       (U)
//!     λ_den · (I_f · I_g)  =  λ_num · I_h,   λ = λ_num/λ_den           (R)
//! ```
//!
//! `(U)` scales by a positive **rational integer**, so both sides are Hermite
//! triples and the comparison is exact. `(R)` is the identity the reduced form
//! `h` satisfies; `λ` is genuinely a fraction of an algebraic integer, so it is
//! recorded as a numerator in `O_K` and a positive integer denominator and the
//! guard compares `λ_den·(I_f·I_g)` (an integer scaling) against `λ_num·I_h`
//! (the ideal generated by `λ_num` times a basis) — never a division. Where
//! `λ` comes from: reduction is `h = h₀ ∘ M` for `M = (p q; r s) ∈ SL₂(ℤ)`, and
//! `I_{h₀} = (A₀·(p − r·τ₀)/A)·I_h` with `τ₀ = (−B₀+√D)/(2A₀)`, so
//!
//! ```text
//!     λ = d₁ · ((2·A₀·p + r·B₀ + r·t) − 2r·ω) / (2·A).
//! ```
//!
//! # What is certified, and what is `uncertified`
//!
//! | producer | certificate | guards |
//! |---|---|---|
//! | [`reduce_form`] | [`FormReductionCertificate`] | the start form has the recorded `D`, is primitive and positive definite; every intermediate form is re-derived by the **general** `SL₂(ℤ)` substitution `f∘M`, not by the step's shortcut; the chain length matches; the last intermediate is the recorded reduced form and passes [`super::BinaryQuadraticForm::is_reduced`]; and the recorded total transform has determinant `1`, is the product of the step matrices, *and* carries the start to the reduced form on its own |
//! | [`compose`] | [`CompositionCertificate`] | order parameters match the radicand and `D`; both factors have discriminant `D`, are primitive and positive definite; `2s = b₁+b₂`, `y₁a₂ + v a₁ = d = gcd(a₁,a₂)`, `x₂s − y₂d = d₁ = gcd(d, s) = gcd(a₁,a₂,s)`; the composite has discriminant `D`, is primitive, positive definite, and `a₃·d₁² = a₁a₂`; the reduction certificate verifies and runs from the composite to the composed form; each of the four recorded ideals is the image of its form under the map above, recomputed; the ideal product certificate verifies and is about the recorded operands; identity `(U)`; identity `(R)`, with `λ_den > 0` and `λ_num ≠ 0` |
//! | [`class_of_ideal`] | [`FormIdealCertificate`] | order parameters; the ideal is admissible; the content is its `ω`-denominator and is positive; the primitive part is the ideal scaled down by it; the raw form has discriminant `D`, is primitive and positive definite; **forwards** `I_form(raw) = primitive part`; **backwards** `form_of(primitive part) = raw`; the reduction certificate verifies from `raw` to the recorded reduced form |
//! | [`is_principal`] | [`PrincipalityCertificate`] | the correspondence certificate verifies; the recorded principal form is the one `D` determines (`(1,0,−D/4)` or `(1,1,(1−D)/4)`), is reduced and has discriminant `D`; and the recorded verdict is exactly `reduced == principal form` — a forged `true` and a forged `false` are separate refusals |
//! | [`class_group`] | [`ClassGroupCertificate`] | the wave-two [`super::ClassNumberCertificate`] verifies and its `D` and form list are the recorded ones; `1 ≤ h ≤` [`CLASS_GROUP_ORDER_BOUND`]; the table is `h × h` with every entry in range; **every cell is re-derived by running [`compose`] and verifying its certificate**; the identity index carries the principal form and its row and column are the identity permutation; every inverse is the reduced opposite form `(a, −b, c)` and the table sends the pair to the identity; associativity over all `h³` triples; commutativity; every recorded element order is the least `k ≥ 1` with `gᵏ = e` recomputed from the table; and the invariant factors are each `> 1`, divide in a chain, multiply to `h`, and **predict the recorded multiset of element orders** |
//!
//! **Why the order multiset settles the decomposition.** For a finite abelian
//! group the counting function `k ↦ #{x : xᵏ = e}` determines the isomorphism
//! type, and that function is a re-encoding of the multiset of element orders.
//! So `verify` never has to trust the producer's search: it enumerates the
//! `∏ nᵢ ≤ h` tuples of `ℤ/n₁ × … × ℤ/n_k`, takes each tuple's order as the
//! `lcm` of `nᵢ/gcd(xᵢ,nᵢ)`, and compares multisets against the table's own
//! orders. The producer's route is different and deliberately naive — take an
//! element of maximal order (which in a finite abelian group generates a direct
//! factor), quotient by the cyclic subgroup it generates, recurse — so a bug in
//! the search cannot be a bug in the check.
//! [`crate::normalforms::smith_normal_form`] was **not** reused: it wants a
//! relation matrix, and a Cayley table does not hand one over without first
//! choosing generators and finding their relations, which is strictly more work
//! than the greedy quotient plus a check that does not depend on either.
//!
//! **`uncertified`, and why.** The [`ClassGroupCertificate`] accessors are
//! reads of recorded data. Nothing else here is uncertified.
//!
//! # What this module reuses
//!
//! - [`super::class_number`] and [`super::ClassNumberCertificate`] — the whole
//!   reduced-form enumeration and its independent recount, unchanged. This
//!   module adds a law on that set, it does not re-enumerate it.
//! - [`super::QuadraticOrder`], [`super::Ideal`] and its canonical Hermite
//!   triple, [`super::QuadraticOrder::multiply_ideals`] with its
//!   [`super::IdealProductCertificate`], and
//!   [`super::QuadraticOrder::ideal_from_generators`] — the entire ideal side
//!   of every composition guard is wave two's, called and verified, not
//!   reimplemented.
//! - [`super::BinaryQuadraticForm`] and its `is_reduced`, `is_primitive`,
//!   `is_positive_definite`, `discriminant`.
//! - `super`'s private `big_gcd`, `big_ext_gcd`, `big_mod_positive`.
//! - [`super::QuadraticOrder::split_prime`] in the tests, for the prime ideals
//!   whose classes the correspondence is exercised on.
//!
//! # Out of scope, deliberately
//!
//! - **Real quadratic class groups.** `D > 0` needs the cycle of reduced
//!   indefinite forms and the regulator; [`class_group`] declines with
//!   [`ClassGroupDecline::DiscriminantNotNegative`].
//! - **Non-maximal orders.** [`compose`] takes a [`super::QuadraticOrder`],
//!   which is always maximal, and declines with
//!   [`ClassGroupDecline::OrderDiscriminantMismatch`] when the form's
//!   discriminant is not the order's — so the class group of the order of
//!   conductor `f > 1` is not reachable here even though
//!   [`super::class_number`] will happily count its forms.
//! - **Genus theory.** The principal genus, the genus characters, and the fact
//!   that `D = −84` splits into four genera of one class each are visible in
//!   the `ℤ/2 × ℤ/2` answer but are not computed as genera.
//! - **Class groups past degree 2**, ray class groups, class field theory,
//!   and `L`-functions.
//! - **A subexponential class-group algorithm.** The route here is the full
//!   `Θ(|D|)` reduced-form enumeration plus an `h²` table, so it is bounded by
//!   [`CLASS_GROUP_ORDER_BOUND`] rather than by `|D|`.
//!
//! # Cost profile
//!
//! **ADVISORY**, measured `--release` on a shared host; the numbers and the
//! load are in the lane report. The shape, independent of any clock: the
//! enumeration inherited from wave two is `Θ(|D|)` bignum operations, the table
//! is `h²` compositions each of which is a constant number of `BigInt`
//! extended-gcd and Hermite steps, `verify` re-runs every one of those `h²`
//! compositions, and the associativity guard is `h³` index lookups with no
//! arithmetic at all. So `verify` costs about what production costs plus the
//! `Θ(|D|)` recount, and the practical ceiling is `h`, not `|D|` — which is why
//! [`CLASS_GROUP_ORDER_BOUND`] exists.

