/// Why a class-group certificate was refused.
///
/// Each variant names a distinct, independently reachable guard.
#[derive(Clone, Debug, PartialEq, Eq)]
pub enum ClassGroupCertificateError {
    /// The certificate's recorded order parameters are not the ones its
    /// squarefree radicand determines.
    OrderParametersMismatch,
    /// The recorded discriminant is not the order's.
    DiscriminantMismatch,
    /// A reduction chain starts from a form that does not have the recorded
    /// discriminant, or is imprimitive, or is not positive definite.
    ReductionStartNotAdmissible,
    /// Applying a recorded step's matrix to the previous form does not give
    /// the recorded intermediate form.
    ReductionStepMismatch {
        /// Index into the step list.
        index: usize,
    },
    /// The step list and the intermediate list have different lengths.
    ReductionChainLengthMismatch,
    /// The last intermediate form is not the recorded reduced form.
    ReductionResultMismatch,
    /// The recorded reduced form is not reduced.
    ReductionResultNotReduced,
    /// The recorded total transform is not the product of the step matrices,
    /// or does not carry the start form to the reduced form.
    ReductionTransformMismatch,
    /// The recorded total transform has determinant other than `1`.
    ReductionTransformDeterminantNotOne,
    /// A composition factor does not have the certificate's discriminant, or
    /// is imprimitive, or is not positive definite.
    CompositionFactorNotAdmissible {
        /// `0` for the left factor, `1` for the right.
        index: usize,
    },
    /// `2·s ≠ b₁ + b₂`, so the recorded half-trace is not one.
    BezoutHalfTraceMismatch,
    /// `y₁·a₂ + v·a₁ ≠ d`.
    BezoutFirstIdentityFails,
    /// The recorded `d` is not `gcd(a₁, a₂)`, or is not positive.
    BezoutFirstGcdMismatch,
    /// `x₂·s − y₂·d ≠ d₁`.
    BezoutContentIdentityFails,
    /// The recorded `d₁` is not `gcd(a₁, a₂, s)`, or is not positive.
    BezoutContentMismatch,
    /// The unreduced composite does not have the certificate's discriminant,
    /// or is imprimitive, or is not positive definite.
    CompositeNotAdmissible,
    /// `a₃ · d₁² ≠ a₁ · a₂`.
    CompositeLeadingMismatch,
    /// The composition's reduction certificate does not run from the recorded
    /// composite to the recorded composed form.
    CompositionReductionMismatch,
    /// A recorded ideal is not the image of its form under the form-to-ideal
    /// map.
    IdealCorrespondenceMismatch {
        /// `0` left, `1` right, `2` unreduced composite, `3` composed.
        index: usize,
    },
    /// The recorded ideal product certificate is not about the recorded left
    /// and right ideals, or not about the recorded product.
    IdealProductOperandMismatch,
    /// The unreduced identity `I_f·I_g = d₁·I_{h₀}` fails.
    UnreducedIdealIdentityFails,
    /// The reduced identity `λ_den·(I_f·I_g) = λ_num·I_h` fails.
    ReducedIdealIdentityFails,
    /// The recorded `λ` denominator is not positive.
    LambdaDenominatorNotPositive,
    /// The recorded `λ` numerator is zero, for which the identity is vacuous.
    LambdaNumeratorZero,
    /// The recorded content of an ideal is not positive.
    ContentNotPositive,
    /// The recorded content is not the ideal's `ω`-denominator.
    ContentMismatch,
    /// The recorded primitive part is not the ideal scaled down by the
    /// content.
    PrimitivePartMismatch,
    /// The form-to-ideal map applied to the recorded form is not the recorded
    /// primitive part.
    ForwardMapMismatch,
    /// The ideal-to-form map applied to the recorded primitive part is not the
    /// recorded form.
    BackwardMapMismatch,
    /// The recorded principal form is not the one the discriminant determines.
    PrincipalFormMismatch,
    /// The recorded principality verdict is not `reduced == principal form`.
    PrincipalityVerdictMismatch,
    /// The embedded class-number certificate is about a different discriminant
    /// or a different list of forms.
    ClassNumberCertificateMismatch,
    /// The class number is zero, or exceeds [`CLASS_GROUP_ORDER_BOUND`].
    ClassNumberOutOfRange {
        /// The bound that was exceeded.
        bound: usize,
    },
    /// The Cayley table is not `h × h`, or a companion list is not length `h`.
    TableShapeMismatch,
    /// A table entry is not a valid form index.
    TableEntryOutOfRange {
        /// Row index.
        row: usize,
        /// Column index.
        column: usize,
    },
    /// A table entry is not the class the re-run composition produces.
    TableEntryMismatch {
        /// Row index.
        row: usize,
        /// Column index.
        column: usize,
    },
    /// The recorded identity index does not carry the principal form.
    IdentityNotPrincipalForm,
    /// The identity's row or column is not the identity permutation.
    IdentityRowMismatch {
        /// The index whose product with the identity was wrong.
        index: usize,
    },
    /// The recorded inverse of a class is not the reduced opposite form.
    InverseFormMismatch {
        /// Index into the form list.
        index: usize,
    },
    /// A class times its recorded inverse is not the identity.
    InverseProductNotIdentity {
        /// Index into the form list.
        index: usize,
    },
    /// `(i·j)·k ≠ i·(j·k)` for a recorded triple.
    NotAssociative {
        /// First index.
        left: usize,
        /// Second index.
        middle: usize,
        /// Third index.
        right: usize,
    },
    /// `i·j ≠ j·i`, so the table is not the table of an abelian group and the
    /// invariant-factor claim is meaningless.
    NotCommutative {
        /// Row index.
        row: usize,
        /// Column index.
        column: usize,
    },
    /// A recorded element order is not the least `k ≥ 1` with `gᵏ = e`.
    ElementOrderMismatch {
        /// Index into the form list.
        index: usize,
    },
    /// An invariant factor is `≤ 1`, which names no cyclic factor.
    InvariantFactorNotProper {
        /// Index into the invariant-factor list.
        index: usize,
    },
    /// The invariant factors do not form a divisibility chain `n₁ | n₂ | …`.
    InvariantFactorChainBroken {
        /// Index of the factor that does not divide its successor.
        index: usize,
    },
    /// The invariant factors do not multiply to the class number.
    InvariantFactorProductMismatch,
    /// The multiset of element orders `ℤ/n₁ × … × ℤ/n_k` predicts is not the
    /// table's.
    ElementOrderMultisetMismatch,
    /// A reused wave-two certificate refused.
    Ideal(IdealCertificateError),
    /// A re-run composition's own certificate refused.
    Composition(Box<ClassGroupCertificateError>),
}

impl fmt::Display for ClassGroupCertificateError {
    fn fmt(&self, f: &mut fmt::Formatter<'_>) -> fmt::Result {
        write!(f, "{self:?}")
    }
}

impl From<IdealCertificateError> for ClassGroupCertificateError {
    fn from(error: IdealCertificateError) -> ClassGroupCertificateError {
        ClassGroupCertificateError::Ideal(error)
    }
}

/// Why a producer in this module declined to answer.
///
/// A decline is an honest "did not run", never a claim about the input.
#[derive(Clone, Debug, PartialEq, Eq)]
pub enum ClassGroupDecline {
    /// The discriminant is non-negative; only the imaginary quadratic case is
    /// in scope.
    DiscriminantNotNegative,
    /// The order's discriminant is not the form's, so the form belongs to a
    /// non-maximal order this module cannot present.
    OrderDiscriminantMismatch,
    /// A form does not have the working discriminant.
    FormDiscriminantMismatch,
    /// A form is imprimitive, so it is not in the class group.
    FormNotPrimitive,
    /// A form has `a ≤ 0`, so it is not positive definite.
    FormNotPositiveDefinite,
    /// An ideal is not an ideal of the order it was offered with.
    IdealNotAdmissible(IdealCertificateError),
    /// A reused wave-two producer declined.
    Ideal(IdealDecline),
    /// The class number exceeds [`CLASS_GROUP_ORDER_BOUND`].
    ClassNumberTooLarge {
        /// The bound that was exceeded.
        bound: usize,
    },
    /// Reduction did not finish within [`REDUCTION_STEP_BOUND`] steps.
    ReductionDidNotTerminate {
        /// The bound that was reached.
        bound: usize,
    },
    /// The composed form is not in the reduced-form list. Reachable only if
    /// the enumeration or the composition is wrong; declining beats shipping a
    /// table with a hole.
    ComposedFormNotInList,
    /// The Cayley table the compositions produced does not behave like a
    /// finite abelian group, so no element order or invariant-factor
    /// decomposition could be read off it. Reachable only if the composition
    /// is wrong; the certificate would refuse it anyway, and declining says so
    /// earlier.
    TableNotAGroup,
    /// A division that composition theory makes exact was not. Reachable only
    /// if a reused routine is wrong, or the discriminant is `≢ 0, 1 (mod 4)`.
    NonExactDivision,
}

impl fmt::Display for ClassGroupDecline {
    fn fmt(&self, f: &mut fmt::Formatter<'_>) -> fmt::Result {
        write!(f, "{self:?}")
    }
}

impl From<IdealDecline> for ClassGroupDecline {
    fn from(decline: IdealDecline) -> ClassGroupDecline {
        ClassGroupDecline::Ideal(decline)
    }
}

