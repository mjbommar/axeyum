/// The two extended-Euclid results Dirichlet composition runs on.
///
/// Recorded so `verify` can check the identities *as identities* rather than
/// re-running the search that produced them.
#[derive(Clone, Debug, PartialEq, Eq)]
pub struct BezoutData {
    /// Whether the producer exchanged the two forms. Cohen's presentation
    /// assumes `a₁ ≤ a₂`; composition is commutative, so the exchange changes
    /// nothing about the answer, but the two identities below are stated about
    /// the exchanged order and `verify` has to know.
    pub swapped: bool,
    /// `s = (b₁ + b₂)/2`, symmetric in the two forms.
    pub half_trace: BigInt,
    /// `d = gcd(a₁, a₂)`.
    pub first_gcd: BigInt,
    /// `y₁` in `y₁·a₂ + v·a₁ = d`.
    pub first_multiplier: BigInt,
    /// `v` in that same identity.
    pub first_cofactor: BigInt,
    /// `d₁ = gcd(d, s) = gcd(a₁, a₂, s)`, the `λ` of identity `(U)`.
    pub content: BigInt,
    /// `x₂` in `x₂·s − y₂·d = d₁`.
    pub second_x: BigInt,
    /// `y₂` in that same identity.
    pub second_y: BigInt,
}

/// The composite of two primitive positive definite forms of one discriminant,
/// reduced, with the whole composition checked on the **ideal** side.
///
/// See the module documentation for the two identities `(U)` and `(R)` and for
/// where `λ` comes from.
#[derive(Clone, Debug, PartialEq, Eq)]
pub struct CompositionCertificate {
    /// The squarefree radicand `d` of the field.
    pub radicand: BigInt,
    /// `t` in `ω² = t·ω + n`.
    pub omega_trace: BigInt,
    /// `n` in `ω² = t·ω + n`.
    pub omega_constant: BigInt,
    /// The common discriminant `D`.
    pub discriminant: BigInt,
    /// The left factor.
    pub left: BinaryQuadraticForm,
    /// The right factor.
    pub right: BinaryQuadraticForm,
    /// The extended-Euclid data the composition used.
    pub bezout: BezoutData,
    /// The composite before reduction, `h₀`.
    pub composite: BinaryQuadraticForm,
    /// The chain from `h₀` to the reduced composite.
    pub reduction: FormReductionCertificate,
    /// The reduced composite, `h`.
    pub composed: BinaryQuadraticForm,
    /// `I_f`.
    pub left_ideal: Ideal,
    /// `I_g`.
    pub right_ideal: Ideal,
    /// `I_{h₀}`.
    pub composite_ideal: Ideal,
    /// `I_h`.
    pub composed_ideal: Ideal,
    /// The wave-two certificate for `I_f · I_g`.
    pub product_certificate: IdealProductCertificate,
    /// The numerator of `λ`, an algebraic integer.
    pub lambda_numerator: OrderElement,
    /// The positive rational denominator of `λ`.
    pub lambda_denominator: BigInt,
}

impl CompositionCertificate {
    /// Re-derive the composition from the recorded forms and Bézout data.
    ///
    /// # Errors
    ///
    /// One [`ClassGroupCertificateError`] variant per guard; see the table in
    /// the module documentation. The two that carry the mathematics are
    /// [`ClassGroupCertificateError::UnreducedIdealIdentityFails`] and
    /// [`ClassGroupCertificateError::ReducedIdealIdentityFails`], which are
    /// the composition law itself, on ideals, over `ℤ`.
    #[allow(clippy::too_many_lines)]
    pub fn verify(&self) -> Result<(), ClassGroupCertificateError> {
        // K1: the order really is the one the radicand determines, and D is
        // its discriminant.
        let order = recover_order(
            &self.radicand,
            &self.omega_trace,
            &self.omega_constant,
            &self.discriminant,
        )?;
        // K2: both factors are positive definite primitive forms of D.
        for (index, form) in [&self.left, &self.right].into_iter().enumerate() {
            if form.discriminant() != self.discriminant
                || !form.is_primitive()
                || !form.is_positive_definite()
            {
                return Err(ClassGroupCertificateError::CompositionFactorNotAdmissible { index });
            }
        }
        let (first, second) = if self.bezout.swapped {
            (&self.right, &self.left)
        } else {
            (&self.left, &self.right)
        };
        let (first_leading, first_middle, _) = first.coefficients();
        let (second_leading, second_middle, _) = second.coefficients();
        // K3: the half-trace really is one.
        if 2u32 * &self.bezout.half_trace != first_middle + second_middle {
            return Err(ClassGroupCertificateError::BezoutHalfTraceMismatch);
        }
        // K4: d = gcd(a1, a2), positive.
        if !self.bezout.first_gcd.is_positive()
            || self.bezout.first_gcd != big_gcd(first_leading, second_leading)
        {
            return Err(ClassGroupCertificateError::BezoutFirstGcdMismatch);
        }
        // K5: the first Bezout identity, as an identity.
        if &self.bezout.first_multiplier * second_leading
            + &self.bezout.first_cofactor * first_leading
            != self.bezout.first_gcd
        {
            return Err(ClassGroupCertificateError::BezoutFirstIdentityFails);
        }
        // K6: d1 = gcd(d, s) = gcd(a1, a2, s), positive.
        if !self.bezout.content.is_positive()
            || self.bezout.content != big_gcd(&self.bezout.first_gcd, &self.bezout.half_trace)
        {
            return Err(ClassGroupCertificateError::BezoutContentMismatch);
        }
        // K7: the second Bezout identity.
        if &self.bezout.second_x * &self.bezout.half_trace
            - &self.bezout.second_y * &self.bezout.first_gcd
            != self.bezout.content
        {
            return Err(ClassGroupCertificateError::BezoutContentIdentityFails);
        }
        // K8: the unreduced composite is a positive definite primitive form of D.
        if self.composite.discriminant() != self.discriminant
            || !self.composite.is_primitive()
            || !self.composite.is_positive_definite()
        {
            return Err(ClassGroupCertificateError::CompositeNotAdmissible);
        }
        // K9: a3 * d1^2 = a1 * a2, the norm bookkeeping of composition.
        let (composite_leading, _, _) = self.composite.coefficients();
        if composite_leading * &self.bezout.content * &self.bezout.content
            != first_leading * second_leading
        {
            return Err(ClassGroupCertificateError::CompositeLeadingMismatch);
        }
        // K10: the reduction chain runs from h0 to h.
        if self.reduction.start != self.composite
            || self.reduction.reduced != self.composed
            || self.reduction.discriminant != self.discriminant
        {
            return Err(ClassGroupCertificateError::CompositionReductionMismatch);
        }
        self.reduction.verify()?;
        // K11: each recorded ideal is the image of its form.
        let pairs = [
            (&self.left, &self.left_ideal),
            (&self.right, &self.right_ideal),
            (&self.composite, &self.composite_ideal),
            (&self.composed, &self.composed_ideal),
        ];
        for (index, (form, ideal)) in pairs.into_iter().enumerate() {
            let expected = ideal_of_form(&order, form)
                .map_err(|_| ClassGroupCertificateError::IdealCorrespondenceMismatch { index })?;
            if &expected != ideal {
                return Err(ClassGroupCertificateError::IdealCorrespondenceMismatch { index });
            }
        }
        // K12: the reused product certificate is about the recorded operands.
        if self.product_certificate.left != self.left_ideal
            || self.product_certificate.right != self.right_ideal
        {
            return Err(ClassGroupCertificateError::IdealProductOperandMismatch);
        }
        // K13: and it holds. This is wave two's checker, not a new one.
        self.product_certificate.verify()?;
        let product = &self.product_certificate.product;
        // K14: identity (U), an exact comparison of Hermite triples.
        if product != &scale_ideal(&self.composite_ideal, &self.bezout.content) {
            return Err(ClassGroupCertificateError::UnreducedIdealIdentityFails);
        }
        // K15: lambda is a usable fraction. Both halves checked before K16,
        // where a zero numerator would make the identity vacuously true on the
        // zero module and a non-positive denominator would break the Hermite
        // conventions rather than fail loudly.
        if !self.lambda_denominator.is_positive() {
            return Err(ClassGroupCertificateError::LambdaDenominatorNotPositive);
        }
        if self.lambda_numerator.is_zero() {
            return Err(ClassGroupCertificateError::LambdaNumeratorZero);
        }
        // K16: identity (R). Never a division: the left side is an integer
        // scaling, the right the module generated by lambda times a basis.
        let left_side = scale_ideal(product, &self.lambda_denominator);
        let right_side =
            scale_ideal_by_element(&order, &self.composed_ideal, &self.lambda_numerator)
                .map_err(|_| ClassGroupCertificateError::ReducedIdealIdentityFails)?;
        if left_side != right_side {
            return Err(ClassGroupCertificateError::ReducedIdealIdentityFails);
        }
        Ok(())
    }
}

/// Dirichlet composition of two primitive positive definite forms of the
/// order's discriminant, followed by reduction.
///
/// The presentation is **Cohen's Algorithm 5.4.7**, not Shanks's NUCOMP.
/// NUCOMP exists to keep the intermediate coefficients from growing to
/// `O(√|D|)` before reduction pulls them back; at the sizes
/// [`CLASS_GROUP_ORDER_BOUND`] admits that is not the bottleneck, and the
/// plain algorithm has fewer moving parts to certify.
///
/// # Errors
///
/// [`ClassGroupDecline::DiscriminantNotNegative`] for a real quadratic order;
/// [`ClassGroupDecline::FormDiscriminantMismatch`],
/// [`ClassGroupDecline::FormNotPrimitive`] and
/// [`ClassGroupDecline::FormNotPositiveDefinite`] for a factor outside the
/// class group; [`ClassGroupDecline::NonExactDivision`] when a division
/// composition theory makes exact is not; and the [`reduce_form`] and
/// [`super::QuadraticOrder::multiply_ideals`] declines.
pub fn compose(
    order: &QuadraticOrder,
    left: &BinaryQuadraticForm,
    right: &BinaryQuadraticForm,
) -> Result<(BinaryQuadraticForm, CompositionCertificate), ClassGroupDecline> {
    let discriminant = order.discriminant().clone();
    if !discriminant.is_negative() {
        return Err(ClassGroupDecline::DiscriminantNotNegative);
    }
    for form in [left, right] {
        if form.discriminant() != discriminant {
            return Err(ClassGroupDecline::FormDiscriminantMismatch);
        }
        if !form.is_positive_definite() {
            return Err(ClassGroupDecline::FormNotPositiveDefinite);
        }
        if !form.is_primitive() {
            return Err(ClassGroupDecline::FormNotPrimitive);
        }
    }
    let swapped = left.coefficients().0 > right.coefficients().0;
    let (first, second) = if swapped { (right, left) } else { (left, right) };
    let (first_leading, first_middle, _) = first.coefficients();
    let (second_leading, second_middle, second_trailing) = second.coefficients();
    // s = (b1 + b2)/2 and n = b2 - s, Cohen's initialization.
    let half_trace = exact_div(&(first_middle + second_middle), &BigInt::from(2))?;
    let offset = second_middle - &half_trace;
    // First Euclidean step: y1*a2 + v*a1 = d = gcd(a2, a1).
    let (first_gcd, first_multiplier, first_cofactor) =
        big_ext_gcd(second_leading, first_leading);
    // Second Euclidean step: x2*s - y2*d = d1 = gcd(s, d).
    let (content, second_x, second_y) = if (&half_trace % &first_gcd).is_zero() {
        (first_gcd.clone(), big_zero(), -big_one())
    } else {
        let (gcd, coefficient, cofactor) = big_ext_gcd(&half_trace, &first_gcd);
        (gcd, coefficient, -cofactor)
    };
    let first_quotient = exact_div(first_leading, &content)?;
    let second_quotient = exact_div(second_leading, &content)?;
    let residue = big_mod_positive(
        &(&first_multiplier * &second_y * &offset - &second_x * second_trailing),
        &first_quotient,
    );
    let composite_middle = second_middle + 2u32 * &second_quotient * &residue;
    let composite_leading = &first_quotient * &second_quotient;
    let composite_trailing = exact_div(
        &(&composite_middle * &composite_middle - &discriminant),
        &(4u32 * &composite_leading),
    )?;
    let composite = BinaryQuadraticForm::new(
        composite_leading.clone(),
        composite_middle.clone(),
        composite_trailing,
    );
    let (composed, reduction) = reduce_form(&discriminant, &composite)?;
    let left_ideal = ideal_of_form(order, left)?;
    let right_ideal = ideal_of_form(order, right)?;
    let composite_ideal = ideal_of_form(order, &composite)?;
    let composed_ideal = ideal_of_form(order, &composed)?;
    let (_, product_certificate) = order.multiply_ideals(&left_ideal, &right_ideal)?;
    // lambda = d1 * ((2*A0*p + r*B0 + r*t) - 2r*omega) / (2*A). See the module
    // documentation for the derivation from I_{h0} = (A0*(p - r*tau0)/A)*I_h.
    let transform_p = &reduction.transform[0];
    let transform_r = &reduction.transform[2];
    let lambda_numerator = OrderElement::new(
        &content
            * (2u32 * &composite_leading * transform_p
                + transform_r * &composite_middle
                + transform_r * order.omega_trace()),
        &content * -(2u32 * transform_r),
    );
    let lambda_denominator = 2u32 * composed.coefficients().0;
    let certificate = CompositionCertificate {
        radicand: order.radicand().clone(),
        omega_trace: order.omega_trace().clone(),
        omega_constant: order.omega_constant().clone(),
        discriminant,
        left: left.clone(),
        right: right.clone(),
        bezout: BezoutData {
            swapped,
            half_trace,
            first_gcd,
            first_multiplier,
            first_cofactor,
            content,
            second_x,
            second_y,
        },
        composite,
        reduction,
        composed: composed.clone(),
        left_ideal,
        right_ideal,
        composite_ideal,
        composed_ideal,
        product_certificate,
        lambda_numerator,
        lambda_denominator,
    };
    Ok((composed, certificate))
}

