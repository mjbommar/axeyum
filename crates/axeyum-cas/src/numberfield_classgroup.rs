    // G17, and why it needs h = 8 to be reachable at all.
    //
    // Every guard above is about the table as an abstract table. G17 is the one
    // that says the table IS the composition table, and a forgery that reaches
    // it has to survive all of them: same identity, same inverse map, same
    // element orders, same invariant factors, still abelian and associative --
    // in other words a group law on the SAME labels, isomorphic to the real
    // one by a permutation that is NOT an automorphism. No such permutation
    // exists for h <= 4, which is why every earlier forgery test stops at an
    // axiom. It does exist for Z/8: fixing e, g^2, g^4, g^6 and swapping
    // g <-> g^3 (and g^5 <-> g^7, so it commutes with inversion) preserves
    // every order and the whole inverse map, but g |-> g^3 with g^2 fixed is
    // not an automorphism of Z/8. h(-95) = 8, cyclic (genus theory: -95 has two
    // prime discriminant factors, so the 2-rank is 1).
    #[test]
    fn the_class_group_refuses_a_relabelled_group_law_only_the_recomposition_can_see() {
        let mut certificate = class_group(&order(-95)).expect("class group");
        certificate.verify().expect("verify");
        assert_eq!(certificate.class_number(), 8);
        assert_eq!(factor_list(&certificate), vec![8]);
        let generator = certificate
            .orders
            .iter()
            .position(|&order| order == 8)
            .expect("a generator");
        let mut powers = vec![certificate.identity];
        for step in 0..7usize {
            powers.push(certificate.table[powers[step]][generator]);
        }
        let mut permuted: Vec<usize> = (0..8).collect();
        permuted[powers[1]] = powers[3];
        permuted[powers[3]] = powers[1];
        permuted[powers[5]] = powers[7];
        permuted[powers[7]] = powers[5];
        let original = certificate.table.clone();
        for row in 0..8usize {
            for column in 0..8usize {
                certificate.table[row][column] =
                    permuted[original[permuted[row]][permuted[column]]];
            }
        }
        assert_ne!(certificate.table, original);
        assert!(matches!(
            certificate.verify(),
            Err(ClassGroupCertificateError::TableEntryMismatch { .. })
        ));
    }

