fn gcd_usize(left: usize, right: usize) -> usize {
    let (mut a, mut b) = (left, right);
    while b != 0 {
        let remainder = a % b;
        a = b;
        b = remainder;
    }
    a
}

fn lcm_usize(left: usize, right: usize) -> Option<usize> {
    if left == 0 || right == 0 {
        return Some(0);
    }
    (left / gcd_usize(left, right)).checked_mul(right)
}

/// The order of every element, read off the Cayley table by repeated
/// multiplication. `None` when the table does not close on the identity within
/// its own size, which is what a non-group table does.
fn element_orders_from_table(table: &[Vec<usize>], identity: usize) -> Option<Vec<usize>> {
    let size = table.len();
    let mut orders = Vec::with_capacity(size);
    for index in 0..size {
        let mut current = index;
        let mut order = 1usize;
        while current != identity {
            current = *table.get(current)?.get(index)?;
            order += 1;
            if order > size {
                return None;
            }
        }
        orders.push(order);
    }
    Some(orders)
}

/// The invariant factors of an abelian Cayley table, by the greedy route: take
/// an element of maximal order (in a finite abelian group a cyclic subgroup of
/// maximal order is a direct factor), quotient by the cyclic subgroup it
/// generates, recurse. The chain comes out descending, so it is reversed.
///
/// `verify` does **not** re-run this; it checks the answer against the multiset
/// of element orders, which determines a finite abelian group up to
/// isomorphism.
fn invariant_factors_from_table(table: &[Vec<usize>], identity: usize) -> Option<Vec<BigInt>> {
    let mut factors: Vec<usize> = Vec::new();
    let mut current: Vec<Vec<usize>> = table.to_vec();
    let mut current_identity = identity;
    while current.len() > 1 {
        let orders = element_orders_from_table(&current, current_identity)?;
        let mut best = 0usize;
        for (index, &order) in orders.iter().enumerate() {
            if order > orders[best] {
                best = index;
            }
        }
        factors.push(orders[best]);
        let mut subgroup: BTreeSet<usize> = BTreeSet::new();
        let mut walker = current_identity;
        loop {
            subgroup.insert(walker);
            walker = *current.get(walker)?.get(best)?;
            if walker == current_identity {
                break;
            }
        }
        let mut representative: Vec<usize> = Vec::with_capacity(current.len());
        for row in &current {
            let coset: BTreeSet<usize> = subgroup
                .iter()
                .map(|&element| row.get(element).copied())
                .collect::<Option<BTreeSet<usize>>>()?;
            representative.push(*coset.iter().next()?);
        }
        let representatives: Vec<usize> = representative
            .iter()
            .copied()
            .collect::<BTreeSet<usize>>()
            .into_iter()
            .collect();
        let mut position: BTreeMap<usize, usize> = BTreeMap::new();
        for (index, &rep) in representatives.iter().enumerate() {
            position.insert(rep, index);
        }
        let mut next: Vec<Vec<usize>> = Vec::with_capacity(representatives.len());
        for &row in &representatives {
            let mut new_row = Vec::with_capacity(representatives.len());
            for &column in &representatives {
                let cell = *current.get(row)?.get(column)?;
                new_row.push(*position.get(representative.get(cell)?)?);
            }
            next.push(new_row);
        }
        current_identity = *position.get(representative.get(current_identity)?)?;
        current = next;
    }
    factors.reverse();
    Some(factors.into_iter().map(BigInt::from).collect())
}

/// The multiset of element orders of `ℤ/n₁ × … × ℤ/n_k`, enumerated over all
/// `∏ nᵢ` tuples. An empty factor list is the trivial group, whose one element
/// has order `1`.
fn predicted_order_multiset(factors: &[BigInt]) -> Option<BTreeMap<usize, usize>> {
    let mut moduli: Vec<usize> = Vec::with_capacity(factors.len());
    for factor in factors {
        moduli.push(usize::try_from(factor).ok()?);
    }
    let mut total = 1usize;
    for &modulus in &moduli {
        total = total.checked_mul(modulus)?;
    }
    let mut counts: BTreeMap<usize, usize> = BTreeMap::new();
    for index in 0..total {
        let mut rest = index;
        let mut order = 1usize;
        for &modulus in &moduli {
            let coordinate = rest % modulus;
            rest /= modulus;
            order = lcm_usize(order, modulus / gcd_usize(coordinate, modulus))?;
        }
        *counts.entry(order).or_insert(0usize) += 1;
    }
    Some(counts)
}

fn order_multiset(orders: &[usize]) -> BTreeMap<usize, usize> {
    let mut counts: BTreeMap<usize, usize> = BTreeMap::new();
    for &order in orders {
        *counts.entry(order).or_insert(0usize) += 1;
    }
    counts
}

/// The ideal class group of an imaginary quadratic order, as a **group**: the
/// reduced forms, the Cayley table composition puts on them, the identity, the
/// inverses, the element orders, and the invariant-factor decomposition.
///
/// The set and its cardinality come from wave two unchanged — the embedded
/// [`ClassNumberCertificate`] is the one [`super::class_number`] produces, and
/// `verify` re-runs its own independent recount of the reduced region.
#[derive(Clone, Debug, PartialEq, Eq)]
pub struct ClassGroupCertificate {
    /// The squarefree radicand `d` of the field.
    pub radicand: BigInt,
    /// `t` in `ω² = t·ω + n`.
    pub omega_trace: BigInt,
    /// `n` in `ω² = t·ω + n`.
    pub omega_constant: BigInt,
    /// The discriminant `D < 0`.
    pub discriminant: BigInt,
    /// Wave two's class-number certificate, embedded and re-verified.
    pub class_number_certificate: ClassNumberCertificate,
    /// The reduced forms, in the enumeration's order; the group's elements.
    pub forms: Vec<BinaryQuadraticForm>,
    /// The index of the principal form.
    pub identity: usize,
    /// `table[i][j]` is the index of the class of `forms[i] ∘ forms[j]`.
    pub table: Vec<Vec<usize>>,
    /// `inverses[i]` is the index of the class of `(a, −b, c)`.
    pub inverses: Vec<usize>,
    /// The order of each element in the table.
    pub orders: Vec<usize>,
    /// `n₁ | n₂ | … | n_k` with `∏ nᵢ = h`; empty for the trivial group.
    pub invariant_factors: Vec<BigInt>,
}

impl ClassGroupCertificate {
    /// The class number `h(D)`.
    #[must_use]
    pub fn class_number(&self) -> usize {
        self.forms.len()
    }

    /// The group's exponent, the largest element order, or `1` when trivial.
    #[must_use]
    pub fn exponent(&self) -> usize {
        self.orders.iter().copied().max().unwrap_or(1)
    }

    /// Whether the group is cyclic: at most one invariant factor.
    #[must_use]
    pub fn is_cyclic(&self) -> bool {
        self.invariant_factors.len() <= 1
    }

    /// Re-derive the whole group structure from `D` alone.
    ///
    /// # Errors
    ///
    /// One [`ClassGroupCertificateError`] variant per guard; see the table in
    /// the module documentation.
    #[allow(clippy::too_many_lines)]
    pub fn verify(&self) -> Result<(), ClassGroupCertificateError> {
        // G1: the order, and D.
        let order = recover_order(
            &self.radicand,
            &self.omega_trace,
            &self.omega_constant,
            &self.discriminant,
        )?;
        // G2: the set is wave two's, and wave two's checker still accepts it.
        if self.class_number_certificate.discriminant != self.discriminant
            || self.class_number_certificate.forms != self.forms
        {
            return Err(ClassGroupCertificateError::ClassNumberCertificateMismatch);
        }
        self.class_number_certificate.verify()?;
        let size = self.forms.len();
        // G3: the class number is in range.
        if size == 0 || size > CLASS_GROUP_ORDER_BOUND {
            return Err(ClassGroupCertificateError::ClassNumberOutOfRange {
                bound: CLASS_GROUP_ORDER_BOUND,
            });
        }
        // G4: the table and its companions have the right shape.
        if self.table.len() != size
            || self.inverses.len() != size
            || self.orders.len() != size
            || self.identity >= size
            || self.table.iter().any(|row| row.len() != size)
        {
            return Err(ClassGroupCertificateError::TableShapeMismatch);
        }
        // G5: every entry is a valid index -- closure, and what makes every
        // lookup below total.
        for (row, entries) in self.table.iter().enumerate() {
            for (column, &entry) in entries.iter().enumerate() {
                if entry >= size {
                    return Err(ClassGroupCertificateError::TableEntryOutOfRange { row, column });
                }
            }
        }
        // The group axioms run BEFORE the recomposition (G17), deliberately.
        // The recomposition pins every cell exactly, so anything checked after
        // it is a guard no forgery can reach; running the axioms first makes
        // each of them the guard that a table forgery actually hits. The cost
        // ordering agrees: these are index lookups, G17 is h^2 verified
        // compositions.
        //
        // G6: the identity index carries the principal form.
        let expected_identity = principal_form(&self.discriminant)
            .map_err(|_| ClassGroupCertificateError::IdentityNotPrincipalForm)?;
        if self.forms[self.identity] != expected_identity {
            return Err(ClassGroupCertificateError::IdentityNotPrincipalForm);
        }
        // G7: and its row and column are the identity permutation.
        for index in 0..size {
            if self.table[self.identity][index] != index
                || self.table[index][self.identity] != index
            {
                return Err(ClassGroupCertificateError::IdentityRowMismatch { index });
            }
        }
        // G8: the inverses are the reduced opposite forms.
        for index in 0..size {
            let (opposite, _) = reduce_form(&self.discriminant, &opposite_form(&self.forms[index]))
                .map_err(|_| ClassGroupCertificateError::InverseFormMismatch { index })?;
            if self.forms[self.inverses[index]] != opposite {
                return Err(ClassGroupCertificateError::InverseFormMismatch { index });
            }
            // G9: and they really invert.
            if self.table[index][self.inverses[index]] != self.identity {
                return Err(ClassGroupCertificateError::InverseProductNotIdentity { index });
            }
        }
        // G10: commutativity, without which the invariant-factor claim below is
        // not even a statement about this table. Before associativity, because
        // a one-cell forgery breaks commutativity and associativity at once and
        // only the guard that runs first is reachable.
        for row in 0..size {
            for column in 0..size {
                if self.table[row][column] != self.table[column][row] {
                    return Err(ClassGroupCertificateError::NotCommutative { row, column });
                }
            }
        }
        // G11: associativity, over every triple.
        for left in 0..size {
            for middle in 0..size {
                let left_middle = self.table[left][middle];
                for right in 0..size {
                    if self.table[left_middle][right]
                        != self.table[left][self.table[middle][right]]
                    {
                        return Err(ClassGroupCertificateError::NotAssociative {
                            left,
                            middle,
                            right,
                        });
                    }
                }
            }
        }
        // G13: every recorded element order is the least k >= 1 with g^k = e.
        let recomputed = element_orders_from_table(&self.table, self.identity)
            .ok_or(ClassGroupCertificateError::ElementOrderMismatch { index: 0 })?;
        for index in 0..size {
            if recomputed[index] != self.orders[index] {
                return Err(ClassGroupCertificateError::ElementOrderMismatch { index });
            }
        }
        // G14: the invariant factors are proper and form a divisibility chain.
        for (index, factor) in self.invariant_factors.iter().enumerate() {
            if factor <= &big_one() {
                return Err(ClassGroupCertificateError::InvariantFactorNotProper { index });
            }
            if index + 1 < self.invariant_factors.len()
                && !(&self.invariant_factors[index + 1] % factor).is_zero()
            {
                return Err(ClassGroupCertificateError::InvariantFactorChainBroken { index });
            }
        }
        // G15: and multiply to h.
        let mut product = big_one();
        for factor in &self.invariant_factors {
            product *= factor;
        }
        if product != BigInt::from(size) {
            return Err(ClassGroupCertificateError::InvariantFactorProductMismatch);
        }
        // G16: and predict the table's own multiset of element orders, which
        // determines a finite abelian group up to isomorphism.
        let predicted = predicted_order_multiset(&self.invariant_factors)
            .ok_or(ClassGroupCertificateError::ElementOrderMultisetMismatch)?;
        if predicted != order_multiset(&self.orders) {
            return Err(ClassGroupCertificateError::ElementOrderMultisetMismatch);
        }
        // G17: and the abstract group above really is the composition table --
        // every cell re-derived by running the composition and verifying its
        // own certificate. This is the guard that ties the group to the
        // arithmetic; everything before it is about the table as a table.
        for (row, entries) in self.table.iter().enumerate() {
            for (column, &entry) in entries.iter().enumerate() {
                let (composed, certificate) =
                    compose(&order, &self.forms[row], &self.forms[column]).map_err(|_| {
                        ClassGroupCertificateError::TableEntryMismatch { row, column }
                    })?;
                certificate
                    .verify()
                    .map_err(|error| ClassGroupCertificateError::Composition(Box::new(error)))?;
                if composed != self.forms[entry] {
                    return Err(ClassGroupCertificateError::TableEntryMismatch { row, column });
                }
            }
        }
        Ok(())
    }
}

/// The ideal class group of an imaginary quadratic order, with a certificate.
///
/// # Errors
///
/// [`ClassGroupDecline::DiscriminantNotNegative`] for a real quadratic order;
/// the [`super::class_number`] declines;
/// [`ClassGroupDecline::ClassNumberTooLarge`] above
/// [`CLASS_GROUP_ORDER_BOUND`]; and
/// [`ClassGroupDecline::ComposedFormNotInList`] /
/// [`ClassGroupDecline::TableNotAGroup`], which are reachable only if the
/// enumeration or the composition is wrong.
pub fn class_group(order: &QuadraticOrder) -> Result<ClassGroupCertificate, ClassGroupDecline> {
    let discriminant = order.discriminant().clone();
    if !discriminant.is_negative() {
        return Err(ClassGroupDecline::DiscriminantNotNegative);
    }
    let (size, class_number_certificate) = class_number(&discriminant)?;
    if size > CLASS_GROUP_ORDER_BOUND {
        return Err(ClassGroupDecline::ClassNumberTooLarge {
            bound: CLASS_GROUP_ORDER_BOUND,
        });
    }
    let forms = class_number_certificate.forms.clone();
    let mut position: BTreeMap<BinaryQuadraticForm, usize> = BTreeMap::new();
    for (index, form) in forms.iter().enumerate() {
        position.insert(form.clone(), index);
    }
    let mut table: Vec<Vec<usize>> = Vec::with_capacity(size);
    for left in &forms {
        let mut row: Vec<usize> = Vec::with_capacity(size);
        for right in &forms {
            let (composed, _) = compose(order, left, right)?;
            row.push(
                *position
                    .get(&composed)
                    .ok_or(ClassGroupDecline::ComposedFormNotInList)?,
            );
        }
        table.push(row);
    }
    let identity = *position
        .get(&principal_form(&discriminant)?)
        .ok_or(ClassGroupDecline::ComposedFormNotInList)?;
    let mut inverses: Vec<usize> = Vec::with_capacity(size);
    for form in &forms {
        let (opposite, _) = reduce_form(&discriminant, &opposite_form(form))?;
        inverses.push(
            *position
                .get(&opposite)
                .ok_or(ClassGroupDecline::ComposedFormNotInList)?,
        );
    }
    let orders =
        element_orders_from_table(&table, identity).ok_or(ClassGroupDecline::TableNotAGroup)?;
    let invariant_factors =
        invariant_factors_from_table(&table, identity).ok_or(ClassGroupDecline::TableNotAGroup)?;
    Ok(ClassGroupCertificate {
        radicand: order.radicand().clone(),
        omega_trace: order.omega_trace().clone(),
        omega_constant: order.omega_constant().clone(),
        discriminant,
        class_number_certificate,
        forms,
        identity,
        table,
        inverses,
        orders,
        invariant_factors,
    })
}

impl QuadraticOrder {
    /// This order's ideal class group as a group, with a certificate.
    ///
    /// # Errors
    ///
    /// The [`class_group`] declines.
    pub fn class_group(&self) -> Result<ClassGroupCertificate, ClassGroupDecline> {
        class_group(self)
    }
}

