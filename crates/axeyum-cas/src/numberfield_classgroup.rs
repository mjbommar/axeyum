/// Largest class number for which [`class_group`] builds its Cayley table.
///
/// The table is `h²` verified compositions and the associativity guard is `h³`
/// lookups, so a large class group would hang a gate rather than answer. Above
/// this the producer declines with [`ClassGroupDecline::ClassNumberTooLarge`].
pub const CLASS_GROUP_ORDER_BOUND: usize = 200;

/// Largest number of `SL₂(ℤ)` steps [`reduce_form`] will take.
///
/// Reduction terminates because every swap strictly decreases the leading
/// coefficient, so this bound is never reached for a genuine form of negative
/// discriminant; it exists so a malformed input declines instead of looping.
pub const REDUCTION_STEP_BOUND: usize = 4096;

