/// Floor division by a **positive** divisor. `BigInt`'s `/` truncates toward
/// zero, which is the wrong rounding for putting `b` into `(−a, a]`.
fn floor_div(numerator: &BigInt, divisor: &BigInt) -> BigInt {
    let quotient = numerator / divisor;
    let remainder = numerator - &quotient * divisor;
    if remainder.is_negative() {
        quotient - 1u32
    } else {
        quotient
    }
}

/// `left / right` when the division is exact, else a decline.
fn exact_div(left: &BigInt, right: &BigInt) -> Result<BigInt, ClassGroupDecline> {
    if right.is_zero() || !(left % right).is_zero() {
        return Err(ClassGroupDecline::NonExactDivision);
    }
    Ok(left / right)
}

