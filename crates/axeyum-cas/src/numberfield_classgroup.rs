/// One `SL₂(ℤ)` step of a form reduction.
///
/// Only two are needed, and each carries its own matrix so `verify` can apply
/// the **general** substitution rather than the step's shortcut.
#[derive(Clone, Debug, PartialEq, Eq)]
pub enum ReductionStep {
    /// `(x, y) ↦ (x + k·y, y)`, matrix `(1 k; 0 1)`, which sends
    /// `b ↦ b + 2·a·k`.
    Translate {
        /// The shift `k`.
        shift: BigInt,
    },
    /// `(x, y) ↦ (−y, x)`, matrix `(0 −1; 1 0)`, which sends
    /// `(a, b, c) ↦ (c, −b, a)`.
    Swap,
}

impl ReductionStep {
    /// The step's matrix, row-major `(p, q, r, s)`.
    #[must_use]
    pub fn matrix(&self) -> [BigInt; 4] {
        match self {
            ReductionStep::Translate { shift } => [big_one(), shift.clone(), big_zero(), big_one()],
            ReductionStep::Swap => [big_zero(), -big_one(), big_one(), big_zero()],
        }
    }
}

impl fmt::Display for ReductionStep {
    fn fmt(&self, f: &mut fmt::Formatter<'_>) -> fmt::Result {
        match self {
            ReductionStep::Translate { shift } => write!(f, "T({shift})"),
            ReductionStep::Swap => write!(f, "S"),
        }
    }
}

/// `f ∘ M` for `M = (p q; r s)`: the form `f(p·x + q·y, r·x + s·y)`.
fn apply_matrix(form: &BinaryQuadraticForm, matrix: &[BigInt; 4]) -> BinaryQuadraticForm {
    let (a, b, c) = form.coefficients();
    let [p, q, r, s] = matrix;
    let leading = a * p * p + b * p * r + c * r * r;
    let middle = 2u32 * a * p * q + b * (p * s + q * r) + 2u32 * c * r * s;
    let trailing = a * q * q + b * q * s + c * s * s;
    BinaryQuadraticForm::new(leading, middle, trailing)
}

/// The 2×2 determinant of a row-major matrix.
fn matrix_det(matrix: &[BigInt; 4]) -> BigInt {
    &matrix[0] * &matrix[3] - &matrix[1] * &matrix[2]
}

/// The row-major product `left · right`.
fn matrix_mul(left: &[BigInt; 4], right: &[BigInt; 4]) -> [BigInt; 4] {
    [
        &left[0] * &right[0] + &left[1] * &right[2],
        &left[0] * &right[1] + &left[1] * &right[3],
        &left[2] * &right[0] + &left[3] * &right[2],
        &left[2] * &right[1] + &left[3] * &right[3],
    ]
}

fn identity_matrix() -> [BigInt; 4] {
    [big_one(), big_zero(), big_zero(), big_one()]
}

/// A chain of `SL₂(ℤ)` steps carrying a form to the unique reduced form of its
/// class.
///
/// `verify` never consults the reduction algorithm: it applies each recorded
/// step's **matrix** through the general substitution `f ∘ M`, checks each
/// determinant is `1`, and finally checks that the recorded total transform is
/// both the product of the steps and, on its own, a map from the start form to
/// the reduced one.
#[derive(Clone, Debug, PartialEq, Eq)]
pub struct FormReductionCertificate {
    /// The discriminant every form in the chain has.
    pub discriminant: BigInt,
    /// The form the chain starts from.
    pub start: BinaryQuadraticForm,
    /// The steps, in order.
    pub steps: Vec<ReductionStep>,
    /// The form after each step; the last is
    /// [`FormReductionCertificate::reduced`].
    pub intermediates: Vec<BinaryQuadraticForm>,
    /// The reduced form of the class.
    pub reduced: BinaryQuadraticForm,
    /// The product of the step matrices, row-major `(p, q, r, s)`.
    pub transform: [BigInt; 4],
}

impl FormReductionCertificate {
    /// Re-derive the whole chain from the start form and the recorded steps.
    ///
    /// # Errors
    ///
    /// [`ClassGroupCertificateError::ReductionStartNotAdmissible`] for a start
    /// form outside the theorem's hypothesis;
    /// [`ClassGroupCertificateError::ReductionChainLengthMismatch`] for a
    /// truncated chain;
    /// [`ClassGroupCertificateError::ReductionStepMismatch`] naming the
    /// offending step; [`ClassGroupCertificateError::ReductionResultMismatch`]
    /// and [`ClassGroupCertificateError::ReductionResultNotReduced`] for the
    /// end of the chain; and
    /// [`ClassGroupCertificateError::ReductionTransformMismatch`] /
    /// [`ClassGroupCertificateError::ReductionTransformDeterminantNotOne`] for
    /// the recorded total transform.
    pub fn verify(&self) -> Result<(), ClassGroupCertificateError> {
        // D1: the start form is a positive definite primitive form of D.
        if self.start.discriminant() != self.discriminant
            || !self.start.is_primitive()
            || !self.start.is_positive_definite()
        {
            return Err(ClassGroupCertificateError::ReductionStartNotAdmissible);
        }
        // D2: one intermediate per step.
        if self.steps.len() != self.intermediates.len() {
            return Err(ClassGroupCertificateError::ReductionChainLengthMismatch);
        }
        let mut current = self.start.clone();
        let mut total = identity_matrix();
        // A per-step determinant check was written here and then removed: both
        // step matrices are computed by `ReductionStep::matrix` from recorded
        // data that cannot make the determinant anything but 1, so no forgery
        // could reach it and no test could kill it. The determinant guard that
        // IS reachable is D7, on the recorded total transform.
        for (index, step) in self.steps.iter().enumerate() {
            let matrix = step.matrix();
            // D4: the intermediate is what the general substitution gives.
            let next = apply_matrix(&current, &matrix);
            if self.intermediates[index] != next {
                return Err(ClassGroupCertificateError::ReductionStepMismatch { index });
            }
            total = matrix_mul(&total, &matrix);
            current = next;
        }
        // D5: the chain lands on the recorded reduced form.
        if current != self.reduced {
            return Err(ClassGroupCertificateError::ReductionResultMismatch);
        }
        // D6: and that form really is reduced.
        if !self.reduced.is_reduced() {
            return Err(ClassGroupCertificateError::ReductionResultNotReduced);
        }
        // D7: the recorded transform is in SL2(Z). Checked before D8 on
        // purpose: D8 pins `transform` exactly, so a determinant forgery could
        // never reach this guard if it ran second, and a guard no forgery can
        // reach is not a guard.
        if !matrix_det(&self.transform).is_one() {
            return Err(ClassGroupCertificateError::ReductionTransformDeterminantNotOne);
        }
        // D8: and it is both the product of the steps and a map start -> reduced.
        if self.transform != total || apply_matrix(&self.start, &self.transform) != self.reduced {
            return Err(ClassGroupCertificateError::ReductionTransformMismatch);
        }
        Ok(())
    }
}

/// The unique reduced form `SL₂(ℤ)`-equivalent to `form`, with the chain of
/// steps that gets there.
///
/// The route is the classical one: put `b` into `(−a, a]` by a translation,
/// swap when `a > c`, repeat; then, when `a = c` and `b < 0`, one final swap
/// fixes the boundary sign convention. Every swap strictly decreases `a`, so
/// the loop terminates.
///
/// # Errors
///
/// [`ClassGroupDecline::DiscriminantNotNegative`] for `D ≥ 0`,
/// [`ClassGroupDecline::FormDiscriminantMismatch`] when `form` does not have
/// discriminant `discriminant`, [`ClassGroupDecline::FormNotPositiveDefinite`],
/// [`ClassGroupDecline::FormNotPrimitive`], and
/// [`ClassGroupDecline::ReductionDidNotTerminate`] at
/// [`REDUCTION_STEP_BOUND`].
pub fn reduce_form(
    discriminant: &BigInt,
    form: &BinaryQuadraticForm,
) -> Result<(BinaryQuadraticForm, FormReductionCertificate), ClassGroupDecline> {
    if !discriminant.is_negative() {
        return Err(ClassGroupDecline::DiscriminantNotNegative);
    }
    if &form.discriminant() != discriminant {
        return Err(ClassGroupDecline::FormDiscriminantMismatch);
    }
    if !form.is_positive_definite() {
        return Err(ClassGroupDecline::FormNotPositiveDefinite);
    }
    if !form.is_primitive() {
        return Err(ClassGroupDecline::FormNotPrimitive);
    }
    let mut steps: Vec<ReductionStep> = Vec::new();
    let mut intermediates: Vec<BinaryQuadraticForm> = Vec::new();
    let mut current = form.clone();
    let mut transform = identity_matrix();
    let mut budget = REDUCTION_STEP_BOUND;
    loop {
        let shift = {
            let (a, b, _) = current.coefficients();
            floor_div(&(a - b), &(2u32 * a))
        };
        if !shift.is_zero() {
            if budget == 0 {
                return Err(ClassGroupDecline::ReductionDidNotTerminate {
                    bound: REDUCTION_STEP_BOUND,
                });
            }
            budget -= 1;
            let step = ReductionStep::Translate { shift };
            let matrix = step.matrix();
            current = apply_matrix(&current, &matrix);
            transform = matrix_mul(&transform, &matrix);
            steps.push(step);
            intermediates.push(current.clone());
        }
        let swap_needed = {
            let (a, _, c) = current.coefficients();
            a > c
        };
        if !swap_needed {
            break;
        }
        if budget == 0 {
            return Err(ClassGroupDecline::ReductionDidNotTerminate {
                bound: REDUCTION_STEP_BOUND,
            });
        }
        budget -= 1;
        let step = ReductionStep::Swap;
        let matrix = step.matrix();
        current = apply_matrix(&current, &matrix);
        transform = matrix_mul(&transform, &matrix);
        steps.push(step);
        intermediates.push(current.clone());
    }
    let boundary_fix = {
        let (a, b, c) = current.coefficients();
        a == c && b.is_negative()
    };
    if boundary_fix {
        let step = ReductionStep::Swap;
        let matrix = step.matrix();
        current = apply_matrix(&current, &matrix);
        transform = matrix_mul(&transform, &matrix);
        steps.push(step);
        intermediates.push(current.clone());
    }
    let certificate = FormReductionCertificate {
        discriminant: discriminant.clone(),
        start: form.clone(),
        steps,
        intermediates,
        reduced: current.clone(),
        transform,
    };
    Ok((current, certificate))
}

/// The principal form of a negative discriminant: the identity of the class
/// group.
///
/// `(1, 0, −D/4)` when `D ≡ 0 (mod 4)`, `(1, 1, (1−D)/4)` when `D ≡ 1`.
///
/// # Errors
///
/// [`ClassGroupDecline::DiscriminantNotNegative`] for `D ≥ 0` and
/// [`ClassGroupDecline::NonExactDivision`] for `D ≢ 0, 1 (mod 4)`, for which
/// no integral form has this discriminant.
pub fn principal_form(discriminant: &BigInt) -> Result<BinaryQuadraticForm, ClassGroupDecline> {
    if !discriminant.is_negative() {
        return Err(ClassGroupDecline::DiscriminantNotNegative);
    }
    let residue = big_mod_positive(discriminant, &BigInt::from(2));
    let trailing = exact_div(&(&residue * &residue - discriminant), &BigInt::from(4))?;
    Ok(BinaryQuadraticForm::new(big_one(), residue, trailing))
}

/// The opposite form `(a, −b, c)`, whose class is the inverse class.
#[must_use]
pub fn opposite_form(form: &BinaryQuadraticForm) -> BinaryQuadraticForm {
    let (a, b, c) = form.coefficients();
    BinaryQuadraticForm::new(a.clone(), -b, c.clone())
}

