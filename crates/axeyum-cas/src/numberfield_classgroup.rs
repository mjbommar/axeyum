/// Whether an ideal is principal, decided by comparing the reduced form of its
/// class to the principal form.
///
/// This is the certificate wave two named as missing: "Non-principality is not
/// certified... A `Principality` certificate would need either a class-group
/// *law* or a general norm-equation solver". The law is now here, so the
/// decision is a form reduction and a comparison, and the recorded *reduction
/// steps* are what makes it checkable.
#[derive(Clone, Debug, PartialEq, Eq)]
pub struct PrincipalityCertificate {
    /// The class of the ideal, with the correspondence checked both ways.
    pub correspondence: FormIdealCertificate,
    /// The identity of the class group for this discriminant.
    pub principal_form: BinaryQuadraticForm,
    /// The verdict.
    pub principal: bool,
}

impl PrincipalityCertificate {
    /// Re-derive the verdict from the recorded ideal alone.
    ///
    /// # Errors
    ///
    /// Everything [`FormIdealCertificate::verify`] refuses, plus
    /// [`ClassGroupCertificateError::PrincipalFormMismatch`] when the recorded
    /// identity is not the one the discriminant determines, and
    /// [`ClassGroupCertificateError::PrincipalityVerdictMismatch`] when the
    /// recorded boolean is not `reduced == principal form` — which refuses a
    /// forged `true` and a forged `false` alike.
    pub fn verify(&self) -> Result<(), ClassGroupCertificateError> {
        // N1: the class is what it says it is.
        self.correspondence.verify()?;
        // N2: the identity element is the principal form of D, recomputed, and
        // really is reduced.
        let expected = principal_form(&self.correspondence.discriminant)
            .map_err(|_| ClassGroupCertificateError::PrincipalFormMismatch)?;
        if expected != self.principal_form
            || !self.principal_form.is_reduced()
            || self.principal_form.discriminant() != self.correspondence.discriminant
        {
            return Err(ClassGroupCertificateError::PrincipalFormMismatch);
        }
        // N3: the verdict is the comparison, in both directions.
        if self.principal != (self.correspondence.reduced == self.principal_form) {
            return Err(ClassGroupCertificateError::PrincipalityVerdictMismatch);
        }
        Ok(())
    }
}

/// Whether `ideal` is principal, with a certificate.
///
/// # Errors
///
/// The [`class_of_ideal`] declines, and
/// [`ClassGroupDecline::NonExactDivision`] when the order's discriminant is
/// `≢ 0, 1 (mod 4)`, which cannot happen for a maximal order and is reported
/// rather than assumed away.
pub fn is_principal(
    order: &QuadraticOrder,
    ideal: &Ideal,
) -> Result<(bool, PrincipalityCertificate), ClassGroupDecline> {
    let (reduced, correspondence) = class_of_ideal(order, ideal)?;
    let identity = principal_form(order.discriminant())?;
    let principal = reduced == identity;
    let certificate = PrincipalityCertificate {
        correspondence,
        principal_form: identity,
        principal,
    };
    Ok((principal, certificate))
}

