//! Real quadratic fields: the regulator, the cycles of reduced indefinite
//! forms, and the narrow and ordinary class numbers.
//!
//! Item 4 of the CAS *Next Ten*, fourth wave. [`super`] gives the class group
//! of an **imaginary** quadratic order as a set, and
//! [`super::numberfield_classgroup`] gives it as a group; both stop at `D < 0`
//! and say so. This module is the `D > 0` half.
//!
//! Everything is exact [`BigInt`]. The one transcendental quantity — the
//! regulator `R = ln ε` — is carried as a **rational enclosure** produced and
//! checked by [`crate::enclosure`], never as a float. No `f64` appears in any
//! certified path here, and no new dependency is introduced.
//!
//! # What this module computes
//!
//! - [`reduced_indefinite_forms`] — every reduced primitive form of a positive
//!   non-square discriminant `D`, by the Gauss/Lagrange condition
//!   `|√D − 2|a|| < b < √D`.
//! - [`rho`] — the reduction step `ρ` on reduced indefinite forms, whose orbits
//!   are the *cycles*.
//! - [`form_cycles`] — the partition of the reduced forms into cycles, with a
//!   [`FormCycleCertificate`]. The number of cycles is the **narrow** class
//!   number `h⁺(D)`.
//! - [`real_class_number`] — the narrow class number, the ordinary class number
//!   `h(D)`, and the two independent cross-checks that pin the relation between
//!   them, as a [`RealClassNumberCertificate`].
//! - [`regulator`] — `R = ln ε` for the certified fundamental unit, as a
//!   [`RegulatorCertificate`] carrying an [`Enclosure`] of stated precision.
//!
//! # Which reduction, and why the cycles are the classes
//!
//! **Gauss (equivalently Lagrange) reduction, not Zagier reduction.** A form
//! `(a, b, c)` of positive non-square discriminant `D = b² − 4ac` is *reduced*
//! when
//!
//! ```text
//!     |√D − 2|a||  <  b  <  √D.
//! ```
//!
//! Zagier's alternative convention (`a > 0`, `c > 0`, `b > a + c`) picks a
//! different set of representatives and a different `ρ`; the two give the same
//! cycle count but not the same forms, so mixing them silently would be a
//! defect. This module is Gauss's throughout, and [`is_reduced_indefinite`] is
//! the only place the condition is written.
//!
//! Every inequality above is tested over ℤ, never over the reals: `b < √D` is
//! `b² < D`, `√D < 2|a| + b` is `D < (2|a| + b)²`, and `2|a| − b < √D` is
//! `2|a| − b ≤ 0` or `(2|a| − b)² < D`. `D` is not a square, so no comparison
//! can land on equality and no tie-breaking convention is needed.
//!
//! The step is
//!
//! ```text
//!     ρ(a, b, c) = (c, b', (b'² − D)/(4c)),
//!     b' ≡ −b (mod 2c),   √D − 2|c| < b' < √D.
//! ```
//!
//! A reduced form always has `|c| < √D`, so that window has length exactly
//! `2|c|` and contains exactly one member of the residue class; with
//! `r = ⌊√D⌋` the representative is `b' = r − ((r + b) mod 2|c|)`, which is
//! integer arithmetic only. `ρ` is a bijection of the reduced forms of `D`, so
//! the reduced forms fall into disjoint cycles, and the classical theorem is
//! that **two reduced forms are properly equivalent exactly when they lie in
//! the same cycle**. The classes of primitive forms of `D > 0` under `SL₂(ℤ)`
//! are the **narrow** class group `Cl⁺(D)`, so
//!
//! ```text
//!     h⁺(D) = the number of cycles.
//! ```
//!
//! # Narrow versus ordinary, and the two cross-checks
//!
//! `Cl⁺(D) → Cl(D)` is surjective with kernel generated by `g`, the class of
//! the negative `(−1, b*, −c*)` of the principal form, and `g² = 1`. So
//! `h(D) = h⁺(D)` when `g` is trivial and `h(D) = h⁺(D)/2` otherwise. Two
//! statements of *when*, computed by disjoint routes, are both recorded and
//! required to agree:
//!
//! 1. **The cycle route (certified).** Any form `(1, b, c)` is properly
//!    equivalent to `(1, b', c')` for every `b' ≡ b (mod 2)`, because the
//!    translation `(x, y) ↦ (x + k·y, y)` sends `b ↦ b + 2k` when `a = 1`.
//!    There is exactly one integer `b*` of the parity of `D` in
//!    `(√D − 2, √D)`, and `(1, b*, c*)` and `(−1, b*, −c*)` are both reduced.
//!    So the principal class is the cycle of `(1, b*, c*)`, `g` is the class of
//!    `(−1, b*, −c*)`, and `g` is trivial exactly when those two forms lie in
//!    the **same cycle** — a lookup in data the certificate already carries,
//!    needing no reduction algorithm and no unit.
//! 2. **The unit route (cross-check).** `g` is trivial exactly when the
//!    fundamental unit has norm `−1`. The certificate carries a
//!    [`FundamentalUnitCertificate`] from
//!    [`QuadraticField::fundamental_unit`], re-verifies it, and refuses when
//!    its norm disagrees with route 1.
//!
//! A note on which order that unit belongs to, because it matters and is easy
//! to get wrong: [`QuadraticField::fundamental_unit`] certifies the fundamental
//! unit of `ℤ[√d]`, which for `d ≡ 1 (mod 4)` is a *proper* suborder of
//! `O_K = ℤ[(1+√d)/2]`. The index of the unit groups for that conductor-2 order
//! is `1` or `3` — never even — so the **norm sign** is the same for both,
//! which is all route 2 uses. The *value* is not: see the regulator section.
//!
//! # The third route: reduction of ideals
//!
//! The certificate also carries an ideal-side count that uses neither route
//! above. Each reduced form `(a, b, c)` is mapped to the [`super::Ideal`]
//! Hermite triple
//!
//! ```text
//!     I = ℤ·|a| + ℤ·(B + ω),    B = −(b + t)/2  mod |a|,
//! ```
//!
//! with `ω = (t + √D)/2` the generator [`super::QuadraticOrder`] already
//! carries. This is [`super::numberfield_classgroup::ideal_of_form`]'s
//! correspondence with `|a|` in place of `a`, which is exactly right: the
//! ℤ-module `ℤ·a + ℤ·(−b + √D)/2` does not see the sign of `a`, and *forgetting
//! that sign is precisely the map `Cl⁺ → Cl`*. So the set of ideals attached to
//! a cycle depends only on the cycle's **ordinary** class, and
//!
//! ```text
//!     h(D) = the number of distinct ideal sets the cycles produce.
//! ```
//!
//! Every ideal is run through [`super::Ideal::admissible_in`] and its norm
//! recomputed, so a triple that is not an ideal of the order cannot pass. This
//! count is compared against route 1's answer; disagreement is a refusal.
//!
//! # The regulator
//!
//! `R = ln ε`. [`regulator`] builds the [`CasExpr`] `ln(a + b·√d)` from the
//! certificate's own `(d, a, b)` — the radical is enclosed first, then the sum,
//! then the logarithm — and hands it to [`crate::enclosure::enclose`] at the
//! requested precision, so the result is an interval of rational endpoints with
//! width at most `2^(−precision)` plus the per-step evidence
//! [`Enclosure::verify`] re-derives. [`RegulatorCertificate::verify`] rebuilds
//! the expression from `(d, a, b)` rather than trusting a stored one, which is
//! what stops a valid enclosure of a *different* number being pasted in.
//!
//! **Whose regulator.** It is the regulator of `ℤ[√d]`, the order whose unit
//! [`QuadraticField::fundamental_unit`] certifies. For `d ≡ 2, 3 (mod 4)` that
//! is the maximal order and this is `R_K`. For `d ≡ 1 (mod 4)` it is `m · R_K`
//! with `m ∈ {1, 3}` the unit index above — `d = 5` gives
//! `ln(2 + √5) = 3 · ln((1+√5)/2)`. Computing `m` is not done here; the
//! certificate reports the unit it used and nothing more.
//!
//! # What is NOT certified here
//!
//! - **Non-fundamental discriminants.** [`form_cycles`] is happy with any
//!   non-square `D ≡ 0, 1 (mod 4)` and counts `h⁺` of the order of that
//!   discriminant. [`real_class_number`] takes a [`super::QuadraticOrder`],
//!   which is always maximal, so the ideal cross-check is available only there.
//! - **The analytic class number formula.** `h·R = (√D/2)·L(1, χ_D)` is not
//!   exactly computable — `L(1, χ_D)` is a transcendental limit with no finite
//!   exact form — so it is not used as a check anywhere in this module. The
//!   ideal-side recount is the cross-check that replaces it.
//! - **The class group as a group** in the real case. Composition of the cycle
//!   representatives is Dirichlet's same formula, and
//!   [`super::numberfield_classgroup::compose`] declines on `D > 0` only
//!   because it reduces through the definite algorithm. Wiring that to the
//!   indefinite reduction is the next slice; this wave ships the counts and the
//!   regulator, not the Cayley table.
//! - **Degree > 2**, ray class groups, and the unit index `m` above.
//!
//! # Cost profile
//!
//! **ADVISORY.** The enumeration is `Θ(D)` outer steps each doing a `Θ(√D)`
//! divisor scan, so it is `Θ(D^{3/2})` bignum operations; the cycle walk is one
//! [`rho`] per reduced form; `verify` re-runs the enumeration, so checking
//! costs about what producing does. The regulator's cost is the enclosure's,
//! which grows quickly in the requested precision. Measured numbers, the host
//! and the load are in the lane report that landed this module.

