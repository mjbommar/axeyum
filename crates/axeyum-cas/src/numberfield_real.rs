/// The unique integer `b*` of the parity of `D` with `√D − 2 < b* < √D`, and
/// the `c*` that makes `(1, b*, c*)` a form of discriminant `D`.
fn principal_reduced_pair(
    discriminant: &BigInt,
    root: &BigInt,
) -> Result<(BigInt, BigInt), RealDecline> {
    // The window `(√D − 2, √D)` is open, of length 2, with irrational
    // endpoints, so it holds exactly one integer of each parity. `r = ⌊√D⌋` is
    // the larger of the two; step down by one when its parity is wrong.
    let parity = big_mod_positive(discriminant, &BigInt::from(2));
    let mut b = root.clone();
    if big_mod_positive(&b, &BigInt::from(2)) != parity {
        b -= big_one();
    }
    let c = exact_div(&(&b * &b - discriminant), &BigInt::from(4))?;
    Ok((b, c))
}

/// `I = ℤ·|a| + ℤ·(B + ω)` with `B = −(b + t)/2 mod |a|`, the ideal of a
/// reduced indefinite form.
///
/// The sign of `a` is dropped on purpose: the ℤ-module does not see it, and
/// forgetting it is exactly the map `Cl⁺(D) → Cl(D)`.
fn ideal_of_indefinite_form(
    order: &QuadraticOrder,
    form: &BinaryQuadraticForm,
) -> Result<Ideal, RealDecline> {
    let (a, b, _) = form.coefficients();
    let leading = a.abs();
    if leading.is_zero() {
        return Err(RealDecline::NonExactDivision);
    }
    let half = exact_div(&(b + order.omega_trace()), &BigInt::from(2))?;
    let offset = big_mod_positive(&(-half), &leading);
    Ok(Ideal::from_hermite(leading, offset, big_one()))
}

/// The distinct ideal sets a cycle partition produces, ascending, together with
/// the per-cycle index into them.
fn ideal_sides(
    order: &QuadraticOrder,
    cycles: &[Vec<BinaryQuadraticForm>],
) -> Result<(Vec<BTreeSet<Ideal>>, Vec<usize>), RealDecline> {
    let mut sets: Vec<BTreeSet<Ideal>> = Vec::with_capacity(cycles.len());
    for cycle in cycles {
        let mut set: BTreeSet<Ideal> = BTreeSet::new();
        for form in cycle {
            set.insert(ideal_of_indefinite_form(order, form)?);
        }
        sets.push(set);
    }
    let mut ordered = sets.clone();
    ordered.sort();
    ordered.dedup();
    let mut map: Vec<usize> = Vec::with_capacity(sets.len());
    for set in &sets {
        let index = ordered
            .iter()
            .position(|other| other == set)
            .ok_or(RealDecline::NonExactDivision)?;
        map.push(index);
    }
    Ok((ordered, map))
}

/// The narrow and ordinary class numbers of a real quadratic order, with all
/// three routes recorded.
///
/// See the module documentation for what the three routes are and why they are
/// independent. `verify` re-derives every one of them and refuses on any
/// disagreement.
#[derive(Clone, Debug, PartialEq, Eq)]
pub struct RealClassNumberCertificate {
    /// The squarefree `d` of `K = ℚ(√d)`.
    pub radicand: BigInt,
    /// `D = disc(O_K)`.
    pub discriminant: BigInt,
    /// The cycle partition, with its own certificate.
    pub cycles: FormCycleCertificate,
    /// The fundamental unit of `ℤ[√d]`, with its own certificate.
    pub unit: FundamentalUnitCertificate,
    /// Index into `cycles.cycles` of the cycle containing `(1, b*, c*)`.
    pub principal_cycle: usize,
    /// Index into `cycles.cycles` of the cycle containing `(−1, b*, −c*)`.
    pub negative_principal_cycle: usize,
    /// The distinct sets of primitive ideals the cycles produce, each sorted,
    /// the outer list sorted.
    pub ideal_classes: Vec<Vec<Ideal>>,
    /// For each cycle, the index into `ideal_classes` of its ideal set.
    pub cycle_ideal_class: Vec<usize>,
    /// `h⁺(D)`.
    pub narrow_class_number: usize,
    /// `h(D)`.
    pub class_number: usize,
}

impl RealClassNumberCertificate {
    /// `h(D)`.
    #[must_use]
    pub fn class_number(&self) -> usize {
        self.class_number
    }

    /// `h⁺(D)`.
    #[must_use]
    pub fn narrow_class_number(&self) -> usize {
        self.narrow_class_number
    }

    /// Whether the fundamental unit has norm `−1`, which is equivalent to
    /// `h = h⁺`.
    #[must_use]
    pub fn unit_norm_is_negative(&self) -> bool {
        self.unit.norm.is_negative()
    }

    /// Re-derive everything from `d` alone.
    ///
    /// # Errors
    ///
    /// Everything [`FormCycleCertificate::verify`] can refuse, plus
    /// [`RealCertificateError::OrderParametersMismatch`],
    /// [`RealCertificateError::DiscriminantMismatch`],
    /// [`RealCertificateError::UnitCertificate`],
    /// [`RealCertificateError::UnitRadicandMismatch`],
    /// [`RealCertificateError::PrincipalCycleMismatch`],
    /// [`RealCertificateError::OrdinaryClassNumberMismatch`],
    /// [`RealCertificateError::UnitNormDisagreesWithCycles`],
    /// [`RealCertificateError::IdealNotAdmissible`],
    /// [`RealCertificateError::IdealNormMismatch`],
    /// [`RealCertificateError::IdealClassesMismatch`],
    /// [`RealCertificateError::IdealClassMapMismatch`] and
    /// [`RealCertificateError::IdealClassCountMismatch`].
    #[allow(clippy::too_many_lines)]
    pub fn verify(&self) -> Result<(), RealCertificateError> {
        // N1: the cycles stand on their own.
        self.cycles.verify()?;
        // N2: the order is the one the radicand determines, and D is its
        // discriminant.
        let order = QuadraticOrder::new(&self.radicand)
            .map_err(|_| RealCertificateError::OrderParametersMismatch)?;
        if order.discriminant() != &self.discriminant
            || self.cycles.discriminant != self.discriminant
        {
            return Err(RealCertificateError::DiscriminantMismatch);
        }
        // N3: the unit certificate stands on its own, and is for this field.
        self.unit.verify()?;
        if self.unit.radicand != self.radicand {
            return Err(RealCertificateError::UnitRadicandMismatch);
        }
        // N4: locate the principal form and its negative, both recomputed from
        // D rather than read from the certificate.
        let root = admissible_discriminant_checked(&self.discriminant)?;
        let (star_b, star_c) = principal_reduced_pair(&self.discriminant, &root)
            .map_err(|_| RealCertificateError::PrincipalCycleMismatch)?;
        let principal = BinaryQuadraticForm::new(big_one(), star_b.clone(), star_c.clone());
        let negative = BinaryQuadraticForm::new(-big_one(), star_b, -star_c);
        let locate = |target: &BinaryQuadraticForm| -> Option<usize> {
            self.cycles
                .cycles
                .iter()
                .position(|cycle| cycle.contains(target))
        };
        let found_principal =
            locate(&principal).ok_or(RealCertificateError::PrincipalCycleMismatch)?;
        let found_negative =
            locate(&negative).ok_or(RealCertificateError::PrincipalCycleMismatch)?;
        if found_principal != self.principal_cycle
            || found_negative != self.negative_principal_cycle
        {
            return Err(RealCertificateError::PrincipalCycleMismatch);
        }
        // N5: h+ is the cycle count and matches the top-level field.
        if self.narrow_class_number != self.cycles.cycles.len() {
            return Err(RealCertificateError::NarrowClassNumberMismatch {
                claimed: self.narrow_class_number,
                cycles: self.cycles.cycles.len(),
            });
        }
        // N6: h follows from the criterion. `h⁺ = h·|⟨g⟩|` with `|⟨g⟩| ∈ {1, 2}`,
        // so `h⁺` is even whenever the two forms lie in different cycles — and a
        // guard on that parity would be unreachable, because N1's recount plus
        // N4's recomputation pin BOTH the cycle partition and which cycles the
        // two forms land in to functions of `D` alone. No forged field can make
        // the branch disagree with the arithmetic, so no guard is written for
        // it; the integer division is exact on every input that gets here.
        let shares_cycle = found_principal == found_negative;
        let derived = if shares_cycle {
            self.narrow_class_number
        } else {
            self.narrow_class_number / 2
        };
        if derived != self.class_number {
            return Err(RealCertificateError::OrdinaryClassNumberMismatch {
                claimed: self.class_number,
                derived,
            });
        }
        // N7: cross-check one — the unit's norm must agree with the criterion.
        if self.unit.norm.is_negative() != shares_cycle {
            return Err(RealCertificateError::UnitNormDisagreesWithCycles {
                norm: self.unit.norm.clone(),
                shares_cycle,
            });
        }
        // N8: cross-check two — the ideal side, recomputed from the cycles.
        let (ordered, expected_map) = ideal_sides(&order, &self.cycles.cycles)
            .map_err(|_| RealCertificateError::IdealClassesMismatch)?;
        // N9: every ideal the certificate LISTS really is an ideal of the order,
        // with the norm its leading coefficient says. Run against the listed
        // triples, not the recomputed ones, so a forged triple is reachable.
        for (class, listed) in self.ideal_classes.iter().enumerate() {
            for ideal in listed {
                ideal
                    .admissible_in(&order)
                    .map_err(|reason| RealCertificateError::IdealNotAdmissible { class, reason })?;
                if ideal.norm() != *ideal.leading() {
                    return Err(RealCertificateError::IdealNormMismatch { class });
                }
            }
        }
        // N10: THE CROSS-CHECK. The ideal side counts the ordinary classes by a
        // route that uses neither the unit nor the principal-cycle criterion,
        // and that count must be the criterion's `h`.
        if self.ideal_classes.len() != derived {
            return Err(RealCertificateError::IdealClassCountMismatch {
                ideal_side: self.ideal_classes.len(),
                cycle_side: derived,
            });
        }
        // N11: and the listed classes are exactly the recomputed sets, so N10
        // counted the right things.
        let recorded: Vec<BTreeSet<Ideal>> = self
            .ideal_classes
            .iter()
            .map(|class| class.iter().cloned().collect())
            .collect();
        if recorded != ordered {
            return Err(RealCertificateError::IdealClassesMismatch);
        }
        // N12: and the recorded map is the one the ideals give.
        if expected_map != self.cycle_ideal_class {
            return Err(RealCertificateError::IdealClassMapMismatch);
        }
        Ok(())
    }
}

/// `h⁺(D)` and `h(D)` for the maximal order of a real quadratic field.
///
/// # Errors
///
/// The declines of [`form_cycles`] and of
/// [`QuadraticField::fundamental_unit`], plus
/// [`RealDecline::DiscriminantNotPositive`] when the order is imaginary and
/// [`RealDecline::FormNotReduced`] if the principal form is somehow not among
/// the reduced ones.
pub fn real_class_number(
    order: &QuadraticOrder,
) -> Result<RealClassNumberCertificate, RealDecline> {
    let discriminant = order.discriminant().clone();
    let root = admissible_discriminant(&discriminant)?;
    let cycles = form_cycles(&discriminant)?;
    let field =
        QuadraticField::new(order.radicand()).map_err(|_| RealDecline::MagnitudeOutOfRange)?;
    let unit = field.fundamental_unit()?;
    let (star_b, star_c) = principal_reduced_pair(&discriminant, &root)?;
    let principal = BinaryQuadraticForm::new(big_one(), star_b.clone(), star_c.clone());
    let negative = BinaryQuadraticForm::new(-big_one(), star_b, -star_c);
    let locate = |target: &BinaryQuadraticForm| {
        cycles
            .cycles
            .iter()
            .position(|cycle| cycle.contains(target))
            .ok_or(RealDecline::FormNotReduced)
    };
    let principal_cycle = locate(&principal)?;
    let negative_principal_cycle = locate(&negative)?;
    let (ordered, cycle_ideal_class) = ideal_sides(order, &cycles.cycles)?;
    let narrow_class_number = cycles.narrow_class_number;
    let class_number = if principal_cycle == negative_principal_cycle {
        narrow_class_number
    } else {
        narrow_class_number / 2
    };
    Ok(RealClassNumberCertificate {
        radicand: order.radicand().clone(),
        discriminant,
        cycles,
        unit,
        principal_cycle,
        negative_principal_cycle,
        ideal_classes: ordered
            .into_iter()
            .map(|set| set.into_iter().collect())
            .collect(),
        cycle_ideal_class,
        narrow_class_number,
        class_number,
    })
}

impl QuadraticOrder {
    /// [`real_class_number`] on this order.
    ///
    /// # Errors
    ///
    /// See [`real_class_number`].
    pub fn real_class_number(&self) -> Result<RealClassNumberCertificate, RealDecline> {
        real_class_number(self)
    }
}

