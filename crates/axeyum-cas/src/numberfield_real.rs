/// `left / right`, refusing a non-exact division.
fn exact_div(left: &BigInt, right: &BigInt) -> Result<BigInt, RealDecline> {
    if right.is_zero() || !(left % right).is_zero() {
        return Err(RealDecline::NonExactDivision);
    }
    Ok(left / right)
}

/// `D > 0`, `D ≡ 0, 1 (mod 4)`, `D` not a square — the standing hypothesis of
/// everything in this module, as a producer-side check. Returns `⌊√D⌋`.
fn admissible_discriminant(discriminant: &BigInt) -> Result<BigInt, RealDecline> {
    if !discriminant.is_positive() {
        return Err(RealDecline::DiscriminantNotPositive);
    }
    let residue = big_mod_positive(discriminant, &BigInt::from(4));
    if !(residue.is_zero() || residue.is_one()) {
        return Err(RealDecline::DiscriminantNotAdmissible);
    }
    let root = big_isqrt(discriminant);
    if &root * &root == *discriminant {
        return Err(RealDecline::DiscriminantIsSquare);
    }
    Ok(root)
}

/// The same hypothesis, as a checker-side refusal.
fn admissible_discriminant_checked(discriminant: &BigInt) -> Result<BigInt, RealCertificateError> {
    // A1: D > 0.
    if !discriminant.is_positive() {
        return Err(RealCertificateError::DiscriminantNotPositive);
    }
    // A2: D ≡ 0 or 1 (mod 4).
    let residue = big_mod_positive(discriminant, &BigInt::from(4));
    if !(residue.is_zero() || residue.is_one()) {
        return Err(RealCertificateError::DiscriminantNotAdmissible);
    }
    // A3: D is not a square.
    let root = big_isqrt(discriminant);
    if &root * &root == *discriminant {
        return Err(RealCertificateError::DiscriminantIsSquare);
    }
    Ok(root)
}

