/// Why a real-quadratic certificate was refused.
///
/// Each variant names a distinct, independently reachable guard.
#[derive(Clone, Debug, PartialEq, Eq)]
pub enum RealCertificateError {
    /// `D ≤ 0`, so there are no indefinite forms of this discriminant.
    DiscriminantNotPositive,
    /// `D ≢ 0, 1 (mod 4)`, so no integral form has this discriminant.
    DiscriminantNotAdmissible,
    /// `D` is a perfect square: the forms factor over ℚ and the theory does not
    /// apply.
    DiscriminantIsSquare,
    /// A listed form does not have the recorded discriminant.
    FormDiscriminantMismatch {
        /// Index of the cycle.
        cycle: usize,
        /// Index within the cycle.
        index: usize,
    },
    /// A listed form is imprimitive, so it is a multiple of a form of smaller
    /// discriminant and does not count towards `h⁺(D)`.
    FormNotPrimitive {
        /// Index of the cycle.
        cycle: usize,
        /// Index within the cycle.
        index: usize,
    },
    /// A listed form is not reduced.
    FormNotReduced {
        /// Index of the cycle.
        cycle: usize,
        /// Index within the cycle.
        index: usize,
    },
    /// The same form appears twice, so the cycles are not disjoint (or one
    /// cycle repeats itself).
    FormListedTwice {
        /// Index of the cycle the repeat was found in.
        cycle: usize,
        /// Index within that cycle.
        index: usize,
    },
    /// A cycle carries no forms.
    CycleEmpty {
        /// Index of the cycle.
        cycle: usize,
    },
    /// `ρ` applied to a cycle member is not the next member (cyclically), so
    /// the cycle is not closed under the reduction step.
    CycleNotClosed {
        /// Index of the cycle.
        cycle: usize,
        /// Index within the cycle whose successor is wrong.
        index: usize,
    },
    /// The checker's own enumeration of the reduced forms of `D` disagrees with
    /// the union of the listed cycles.
    CycleRecountMismatch {
        /// How many distinct forms the cycles carry.
        listed: usize,
        /// How many the checker found.
        recounted: usize,
    },
    /// The recorded narrow class number is not the number of cycles.
    NarrowClassNumberMismatch {
        /// What the certificate claims.
        claimed: usize,
        /// The number of cycles.
        cycles: usize,
    },
    /// The recorded order parameters are not the ones the radicand determines.
    OrderParametersMismatch,
    /// The recorded discriminant is not the order's.
    DiscriminantMismatch,
    /// The recorded index of the principal cycle, or of the cycle of the
    /// negative principal form, is not where the checker finds it.
    PrincipalCycleMismatch,
    /// The recorded ordinary class number does not follow from the narrow one
    /// and the principal-cycle criterion.
    OrdinaryClassNumberMismatch {
        /// What the certificate claims.
        claimed: usize,
        /// What the criterion gives.
        derived: usize,
    },
    /// `h⁺` is odd but the criterion says `h = h⁺/2`, which is impossible.
    NarrowClassNumberNotEven {
        /// The narrow class number.
        narrow: usize,
    },
    /// The fundamental unit's norm disagrees with the cycle criterion: norm
    /// `−1` must hold exactly when the principal form and its negative share a
    /// cycle.
    UnitNormDisagreesWithCycles {
        /// The unit's norm.
        norm: BigInt,
        /// Whether the two forms share a cycle.
        shares_cycle: bool,
    },
    /// The unit certificate did not verify.
    UnitCertificate(CertificateError),
    /// The unit certificate is for a different radicand.
    UnitRadicandMismatch,
    /// An ideal attached to a cycle is not an ideal of the order.
    IdealNotAdmissible {
        /// Index of the ideal class.
        class: usize,
        /// Why the Hermite triple was refused.
        reason: IdealCertificateError,
    },
    /// An ideal's norm is not the `|a|` of the form it came from.
    IdealNormMismatch {
        /// Index of the ideal class.
        class: usize,
    },
    /// The recorded ideal classes are not the distinct ideal sets the cycles
    /// produce.
    IdealClassesMismatch,
    /// The recorded cycle-to-ideal-class map is not the one the ideals give.
    IdealClassMapMismatch,
    /// The ideal-side count of ordinary classes disagrees with the
    /// principal-cycle criterion.
    IdealClassCountMismatch {
        /// The ideal-side count.
        ideal_side: usize,
        /// The cycle-side count.
        cycle_side: usize,
    },
    /// The regulator's `(d, a, b)` could not be lifted into a [`CasExpr`],
    /// whose integer constructor is `i128`.
    RegulatorMagnitudeOutOfRange,
    /// The recorded precision is not the enclosure's own.
    RegulatorPrecisionMismatch {
        /// What the certificate claims.
        claimed: u32,
        /// What the enclosure carries.
        enclosure: u32,
    },
    /// [`Enclosure::verify`] rejected the evidence against the expression
    /// rebuilt from `(d, a, b)`.
    RegulatorEnclosureRejected(String),
    /// The certificate's `fundamental_certified` label does not match whether
    /// the unit's minimality was actually proved.
    RegulatorMinimalityLabelMismatch {
        /// What the certificate claims.
        claimed: bool,
        /// What the unit certificate supports.
        supported: bool,
    },
}

