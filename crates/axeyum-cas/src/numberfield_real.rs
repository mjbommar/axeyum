/// Largest discriminant [`reduced_indefinite_forms`] will enumerate.
///
/// The enumeration is `Θ(D^{3/2})`, so a large `D` would hang a gate rather
/// than answer. Above this the producer declines with
/// [`RealDecline::DiscriminantTooLarge`].
pub const REAL_DISCRIMINANT_BOUND: i64 = 100_000;

/// Largest number of `ρ` steps [`form_cycles`] will take before giving up on a
/// cycle closing.
///
/// `ρ` is a bijection of a finite set, so every orbit closes and this bound is
/// never reached for a genuine discriminant; it exists so a malformed input
/// declines instead of looping.
pub const CYCLE_STEP_BOUND: usize = 1_000_000;

/// Largest precision [`regulator`] will ask [`crate::enclosure::enclose`] for.
///
/// The enclosure cost grows quickly in the denominator sizes of the rational
/// series kernels; this keeps a mistyped precision from becoming a hang.
pub const REGULATOR_PRECISION_BOUND: u32 = 512;

