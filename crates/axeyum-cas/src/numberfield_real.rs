/// Whether `form` is **Gauss-reduced** for the positive non-square
/// discriminant `discriminant`: `|√D − 2|a|| < b < √D`.
///
/// Every comparison is done over ℤ; see the module documentation for the
/// translation. This does **not** check that the form's own discriminant is
/// `discriminant` — callers that need that check it separately, so the two
/// failures stay distinguishable.
#[must_use]
pub fn is_reduced_indefinite(discriminant: &BigInt, form: &BinaryQuadraticForm) -> bool {
    let (a, b, c) = form.coefficients();
    if a.is_zero() || c.is_zero() || !b.is_positive() {
        return false;
    }
    // b < √D.
    if &(b * b) >= discriminant {
        return false;
    }
    let twice = 2u32 * a.abs();
    // √D < 2|a| + b.
    let upper = &twice + b;
    if discriminant >= &(&upper * &upper) {
        return false;
    }
    // 2|a| − b < √D.
    let lower = &twice - b;
    if lower.is_positive() && &(&lower * &lower) >= discriminant {
        return false;
    }
    true
}

/// The positive divisors of `value > 0`, ascending.
fn positive_divisors(value: i128) -> Vec<i128> {
    let mut small: Vec<i128> = Vec::new();
    let mut large: Vec<i128> = Vec::new();
    let mut step = 1i128;
    while step * step <= value {
        if value % step == 0 {
            small.push(step);
            let other = value / step;
            if other != step {
                large.push(other);
            }
        }
        step += 1;
    }
    large.reverse();
    small.extend(large);
    small
}

/// Every reduced primitive form of the positive non-square discriminant `D`,
/// in ascending `(a, b, c)` order.
///
/// The enumeration walks `b` of the parity of `D` with `b² < D`, sets
/// `m = (D − b²)/4 > 0`, and takes `a = ±e` for each positive divisor `e` of
/// `m` with `c = −m/a`, keeping the primitive ones that pass
/// [`is_reduced_indefinite`]. `a·c = −m` is exactly the discriminant condition,
/// so nothing reduced is missed.
///
/// # Errors
///
/// [`RealDecline::DiscriminantNotPositive`],
/// [`RealDecline::DiscriminantNotAdmissible`],
/// [`RealDecline::DiscriminantIsSquare`] for a `D` outside the hypothesis;
/// [`RealDecline::DiscriminantTooLarge`] past [`REAL_DISCRIMINANT_BOUND`]; and
/// [`RealDecline::MagnitudeOutOfRange`] if `D` will not fit `i128`.
pub fn reduced_indefinite_forms(
    discriminant: &BigInt,
) -> Result<Vec<BinaryQuadraticForm>, RealDecline> {
    admissible_discriminant(discriminant)?;
    if discriminant > &BigInt::from(REAL_DISCRIMINANT_BOUND) {
        return Err(RealDecline::DiscriminantTooLarge {
            bound: REAL_DISCRIMINANT_BOUND,
        });
    }
    let small = to_i128(discriminant).ok_or(RealDecline::MagnitudeOutOfRange)?;
    let mut forms: Vec<BinaryQuadraticForm> = Vec::new();
    let mut b = if small % 2 == 0 { 2i128 } else { 1i128 };
    while b * b < small {
        let numerator = small - b * b;
        if numerator % 4 != 0 {
            b += 2;
            continue;
        }
        let m = numerator / 4;
        for divisor in positive_divisors(m) {
            for sign in [1i128, -1i128] {
                let a = sign * divisor;
                let c = -m / a;
                let form =
                    BinaryQuadraticForm::new(BigInt::from(a), BigInt::from(b), BigInt::from(c));
                if !is_reduced_indefinite(discriminant, &form) {
                    continue;
                }
                if !form.is_primitive() {
                    continue;
                }
                forms.push(form);
            }
        }
        b += 2;
    }
    forms.sort();
    Ok(forms)
}

/// The reduction step `ρ(a, b, c) = (c, b', (b'² − D)/(4c))`.
///
/// `b'` is the unique integer congruent to `−b` modulo `2c` with
/// `√D − 2|c| < b' < √D`; with `r = ⌊√D⌋` that is `r − ((r + b) mod 2|c|)`.
/// `ρ` maps reduced forms to reduced forms and is a bijection on them.
///
/// # Errors
///
/// The discriminant declines of [`reduced_indefinite_forms`] (without the size
/// bound — `ρ` is `O(1)`), [`RealDecline::FormNotReduced`] when `form` is not
/// reduced for `discriminant` or does not have that discriminant, and
/// [`RealDecline::NonExactDivision`] if `4c` does not divide `b'² − D`.
pub fn rho(
    discriminant: &BigInt,
    form: &BinaryQuadraticForm,
) -> Result<BinaryQuadraticForm, RealDecline> {
    let root = admissible_discriminant(discriminant)?;
    if &form.discriminant() != discriminant || !is_reduced_indefinite(discriminant, form) {
        return Err(RealDecline::FormNotReduced);
    }
    let (_, b, c) = form.coefficients();
    let modulus = 2u32 * c.abs();
    let next_b = &root - big_mod_positive(&(&root + b), &modulus);
    let next_c = exact_div(&(&next_b * &next_b - discriminant), &(4u32 * c))?;
    Ok(BinaryQuadraticForm::new(c.clone(), next_b, next_c))
}

/// The cycles of reduced forms of a positive non-square discriminant.
///
/// Each cycle is one orbit of [`rho`], rotated so its `(a, b, c)`-least form is
/// first; the cycles are listed in ascending order of that first form. Both
/// choices are producer-fixed, so the output is deterministic.
///
/// `verify` re-derives everything: each form's discriminant, primitivity and
/// reducedness; that no form is listed twice; that `ρ` of each member is the
/// next member; and — with a traversal the producer never runs — that the union
/// of the cycles is exactly the reduced forms of `D`.
#[derive(Clone, Debug, PartialEq, Eq)]
pub struct FormCycleCertificate {
    /// The discriminant `D > 0`, non-square, `≡ 0` or `1 (mod 4)`.
    pub discriminant: BigInt,
    /// One entry per cycle.
    pub cycles: Vec<Vec<BinaryQuadraticForm>>,
    /// The narrow class number `h⁺(D)`, which is the number of cycles.
    pub narrow_class_number: usize,
}

impl FormCycleCertificate {
    /// `h⁺(D)`.
    #[must_use]
    pub fn narrow_class_number(&self) -> usize {
        self.narrow_class_number
    }

    /// The total number of reduced forms across all cycles.
    #[must_use]
    pub fn form_count(&self) -> usize {
        self.cycles.iter().map(Vec::len).sum()
    }

    /// Re-derive the whole partition from `D` alone.
    ///
    /// # Errors
    ///
    /// [`RealCertificateError::DiscriminantNotPositive`],
    /// [`RealCertificateError::DiscriminantNotAdmissible`] and
    /// [`RealCertificateError::DiscriminantIsSquare`] for a `D` outside the
    /// hypothesis; [`RealCertificateError::CycleEmpty`],
    /// [`RealCertificateError::FormDiscriminantMismatch`],
    /// [`RealCertificateError::FormNotPrimitive`],
    /// [`RealCertificateError::FormNotReduced`] and
    /// [`RealCertificateError::FormListedTwice`] naming the offending form;
    /// [`RealCertificateError::CycleNotClosed`] when `ρ` disagrees;
    /// [`RealCertificateError::CycleRecountMismatch`] when the independent
    /// enumeration disagrees; and
    /// [`RealCertificateError::NarrowClassNumberMismatch`].
    pub fn verify(&self) -> Result<(), RealCertificateError> {
        admissible_discriminant_checked(&self.discriminant)?;
        let mut seen: BTreeSet<BinaryQuadraticForm> = BTreeSet::new();
        for (cycle, forms) in self.cycles.iter().enumerate() {
            // F1: a cycle is an orbit, so it has at least one member.
            if forms.is_empty() {
                return Err(RealCertificateError::CycleEmpty { cycle });
            }
            for (index, form) in forms.iter().enumerate() {
                // F2: the form has the recorded discriminant.
                if form.discriminant() != self.discriminant {
                    return Err(RealCertificateError::FormDiscriminantMismatch { cycle, index });
                }
                // F3: primitive, or it is not a class of this discriminant.
                if !form.is_primitive() {
                    return Err(RealCertificateError::FormNotPrimitive { cycle, index });
                }
                // F4: reduced.
                if !is_reduced_indefinite(&self.discriminant, form) {
                    return Err(RealCertificateError::FormNotReduced { cycle, index });
                }
                // F5: no repeats anywhere, which is disjointness of the cycles
                // and non-repetition within one.
                if !seen.insert(form.clone()) {
                    return Err(RealCertificateError::FormListedTwice { cycle, index });
                }
            }
            // F6: closed under rho, recomputed here and compared cyclically.
            for index in 0..forms.len() {
                let next = rho(&self.discriminant, &forms[index])
                    .map_err(|_| RealCertificateError::CycleNotClosed { cycle, index })?;
                if next != forms[(index + 1) % forms.len()] {
                    return Err(RealCertificateError::CycleNotClosed { cycle, index });
                }
            }
        }
        // F7: the union is ALL of the reduced forms, by an enumeration the
        // producer's cycle walk never performs.
        let recount = reduced_indefinite_forms(&self.discriminant).map_err(|_| {
            RealCertificateError::CycleRecountMismatch {
                listed: seen.len(),
                recounted: 0,
            }
        })?;
        let recounted: BTreeSet<BinaryQuadraticForm> = recount.into_iter().collect();
        if recounted != seen {
            return Err(RealCertificateError::CycleRecountMismatch {
                listed: seen.len(),
                recounted: recounted.len(),
            });
        }
        // F8: the headline number is the cycle count.
        if self.narrow_class_number != self.cycles.len() {
            return Err(RealCertificateError::NarrowClassNumberMismatch {
                claimed: self.narrow_class_number,
                cycles: self.cycles.len(),
            });
        }
        Ok(())
    }
}

/// Partition the reduced forms of `D` into `ρ`-cycles.
///
/// # Errors
///
/// The declines of [`reduced_indefinite_forms`] and [`rho`], plus
/// [`RealDecline::CycleDidNotClose`] at [`CYCLE_STEP_BOUND`].
pub fn form_cycles(discriminant: &BigInt) -> Result<FormCycleCertificate, RealDecline> {
    let forms = reduced_indefinite_forms(discriminant)?;
    let all: BTreeSet<BinaryQuadraticForm> = forms.iter().cloned().collect();
    let mut seen: BTreeSet<BinaryQuadraticForm> = BTreeSet::new();
    let mut cycles: Vec<Vec<BinaryQuadraticForm>> = Vec::new();
    for start in &forms {
        if seen.contains(start) {
            continue;
        }
        let mut orbit: Vec<BinaryQuadraticForm> = Vec::new();
        let mut current = start.clone();
        let mut budget = CYCLE_STEP_BOUND;
        loop {
            if !all.contains(&current) || !seen.insert(current.clone()) {
                break;
            }
            orbit.push(current.clone());
            if budget == 0 {
                return Err(RealDecline::CycleDidNotClose {
                    bound: CYCLE_STEP_BOUND,
                });
            }
            budget -= 1;
            current = rho(discriminant, &current)?;
        }
        if &current != start {
            // rho is a bijection of the reduced forms, so an orbit that walks
            // into an already-seen form other than its own start is impossible;
            // refuse rather than emit a partition that is not one.
            return Err(RealDecline::CycleDidNotClose {
                bound: CYCLE_STEP_BOUND,
            });
        }
        // Rotate so the least form leads, so the output does not depend on
        // which member the outer loop reached first.
        if let Some(pivot) = orbit
            .iter()
            .enumerate()
            .min_by(|left, right| left.1.cmp(right.1))
            .map(|(index, _)| index)
        {
            orbit.rotate_left(pivot);
        }
        cycles.push(orbit);
    }
    cycles.sort();
    let narrow_class_number = cycles.len();
    Ok(FormCycleCertificate {
        discriminant: discriminant.clone(),
        cycles,
        narrow_class_number,
    })
}

