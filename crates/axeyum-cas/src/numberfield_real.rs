/// Why a real-quadratic producer declined.
#[derive(Clone, Debug, PartialEq, Eq)]
pub enum RealDecline {
    /// `D ≤ 0`.
    DiscriminantNotPositive,
    /// `D ≢ 0, 1 (mod 4)`.
    DiscriminantNotAdmissible,
    /// `D` is a perfect square.
    DiscriminantIsSquare,
    /// `D` is past [`REAL_DISCRIMINANT_BOUND`].
    DiscriminantTooLarge {
        /// The bound.
        bound: i64,
    },
    /// A value did not fit the `i128` range a reused routine needs.
    MagnitudeOutOfRange,
    /// The form handed to [`rho`] is not reduced, so `ρ` is not defined on it.
    FormNotReduced,
    /// A division that the theory says is exact was not.
    NonExactDivision,
    /// A cycle did not close within [`CYCLE_STEP_BOUND`] steps.
    CycleDidNotClose {
        /// The bound.
        bound: usize,
    },
    /// The fundamental-unit producer declined.
    Unit(UnitDecline),
    /// The requested precision is past [`REGULATOR_PRECISION_BOUND`].
    PrecisionTooLarge {
        /// The bound.
        bound: u32,
    },
    /// [`crate::enclosure::enclose`] declined.
    Enclosure(EncloseDecline),
}

impl fmt::Display for RealDecline {
    fn fmt(&self, f: &mut fmt::Formatter<'_>) -> fmt::Result {
        match self {
            RealDecline::DiscriminantNotPositive => write!(f, "discriminant is not positive"),
            RealDecline::DiscriminantNotAdmissible => {
                write!(f, "discriminant is not 0 or 1 mod 4")
            }
            RealDecline::DiscriminantIsSquare => write!(f, "discriminant is a square"),
            RealDecline::DiscriminantTooLarge { bound } => {
                write!(f, "discriminant is past the enumeration bound {bound}")
            }
            RealDecline::MagnitudeOutOfRange => write!(f, "value is past the i128 range"),
            RealDecline::FormNotReduced => write!(f, "rho needs a reduced form"),
            RealDecline::NonExactDivision => write!(f, "a division that must be exact was not"),
            RealDecline::CycleDidNotClose { bound } => {
                write!(f, "a cycle did not close within {bound} steps")
            }
            RealDecline::Unit(inner) => write!(f, "fundamental unit: {inner}"),
            RealDecline::PrecisionTooLarge { bound } => {
                write!(f, "precision is past the bound {bound}")
            }
            RealDecline::Enclosure(inner) => write!(f, "enclosure: {inner}"),
        }
    }
}

impl From<UnitDecline> for RealDecline {
    fn from(value: UnitDecline) -> RealDecline {
        RealDecline::Unit(value)
    }
}

impl From<EncloseDecline> for RealDecline {
    fn from(value: EncloseDecline) -> RealDecline {
        RealDecline::Enclosure(value)
    }
}

