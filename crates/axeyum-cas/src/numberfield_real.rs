/// `ln(a + b·√d)` as a [`CasExpr`], or `None` when a coefficient is past the
/// `i128` range of [`CasExpr::int`].
fn regulator_expression(radicand: &BigInt, a: &BigInt, b: &BigInt) -> Option<CasExpr> {
    let d = to_i128(radicand)?;
    let a = to_i128(a)?;
    let b = to_i128(b)?;
    let root = CasExpr::int(d).sqrt();
    let scaled = CasExpr::Mul(vec![CasExpr::int(b), root]);
    Some(CasExpr::Add(vec![CasExpr::int(a), scaled]).ln())
}

/// `R = ln ε` for a certified fundamental unit, as a rational enclosure.
///
/// The certificate carries no float and no decimal rendering: the answer is the
/// [`Enclosure`]'s interval of exact rational endpoints, of width at most
/// `2^(−precision)`.
#[derive(Clone, Debug, PartialEq, Eq)]
pub struct RegulatorCertificate {
    /// The squarefree `d`.
    pub radicand: BigInt,
    /// The unit whose logarithm this is.
    pub unit: FundamentalUnitCertificate,
    /// The requested precision: the width bound is `2^(−precision)`.
    pub precision: u32,
    /// The enclosure of `ln(a + b√d)` with its per-step evidence.
    pub enclosure: Enclosure,
    /// Whether the unit's *fundamental* claim was proved (not merely labelled),
    /// and hence whether this is `R` rather than `k·R` for an unknown `k ≥ 1`.
    pub fundamental_certified: bool,
}

impl RegulatorCertificate {
    /// The enclosing interval.
    #[must_use]
    pub fn interval(&self) -> &BigInterval {
        &self.enclosure.interval
    }

    /// The expression `ln(a + b√d)` this certificate is about, rebuilt from
    /// `(d, a, b)`. `None` when a coefficient is past `i128`.
    #[must_use]
    pub fn expression(&self) -> Option<CasExpr> {
        regulator_expression(&self.radicand, &self.unit.a, &self.unit.b)
    }

    /// Re-derive the unit, rebuild the expression from `(d, a, b)`, and re-run
    /// the enclosure's evidence against it.
    ///
    /// # Errors
    ///
    /// [`RealCertificateError::UnitCertificate`] when the unit does not stand
    /// up; [`RealCertificateError::UnitRadicandMismatch`] when the unit is for
    /// a different field;
    /// [`RealCertificateError::RegulatorMagnitudeOutOfRange`];
    /// [`RealCertificateError::RegulatorPrecisionMismatch`];
    /// [`RealCertificateError::RegulatorEnclosureRejected`]; and
    /// [`RealCertificateError::RegulatorMinimalityLabelMismatch`].
    pub fn verify(&self) -> Result<(), RealCertificateError> {
        // G1: the unit stands on its own — the norm is recomputed and, when the
        // certificate claims one, the minimality search is re-run.
        self.unit.verify()?;
        // G2: and it is a unit of THIS field.
        if self.unit.radicand != self.radicand {
            return Err(RealCertificateError::UnitRadicandMismatch);
        }
        // G3: the subject is rebuilt from (d, a, b), never read from the
        // certificate, so an enclosure of some other number cannot be pasted
        // in.
        let expr = self
            .expression()
            .ok_or(RealCertificateError::RegulatorMagnitudeOutOfRange)?;
        // G4: the claimed precision is the enclosure's own, so the width bound
        // the verifier enforces is the one the certificate advertises.
        if self.precision != self.enclosure.precision {
            return Err(RealCertificateError::RegulatorPrecisionMismatch {
                claimed: self.precision,
                enclosure: self.enclosure.precision,
            });
        }
        self.enclosure
            .verify(&expr, &[])
            .map_err(RealCertificateError::RegulatorEnclosureRejected)?;
        // G5: "this is THE regulator" is only true when the unit's minimality
        // was proved; the label may not outrun the unit certificate.
        let supported = matches!(self.unit.minimality, Minimality::ExhaustiveBelow { .. });
        if self.fundamental_certified != supported {
            return Err(RealCertificateError::RegulatorMinimalityLabelMismatch {
                claimed: self.fundamental_certified,
                supported,
            });
        }
        Ok(())
    }
}

/// `R = ln ε` for an already-certified unit.
///
/// # Errors
///
/// [`RealDecline::PrecisionTooLarge`] past [`REGULATOR_PRECISION_BOUND`],
/// [`RealDecline::MagnitudeOutOfRange`] when the unit is past the `i128` range
/// of [`CasExpr::int`], and [`RealDecline::Enclosure`] when
/// [`crate::enclosure::enclose`] declines.
pub fn regulator_of_unit(
    unit: &FundamentalUnitCertificate,
    precision: u32,
) -> Result<RegulatorCertificate, RealDecline> {
    if precision > REGULATOR_PRECISION_BOUND {
        return Err(RealDecline::PrecisionTooLarge {
            bound: REGULATOR_PRECISION_BOUND,
        });
    }
    let expr = regulator_expression(&unit.radicand, &unit.a, &unit.b)
        .ok_or(RealDecline::MagnitudeOutOfRange)?;
    let enclosure = enclose_with_reason(&expr, &[], precision)?;
    Ok(RegulatorCertificate {
        radicand: unit.radicand.clone(),
        unit: unit.clone(),
        precision,
        enclosure,
        fundamental_certified: matches!(unit.minimality, Minimality::ExhaustiveBelow { .. }),
    })
}

/// `R = ln ε` for the fundamental unit of `ℤ[√d]`.
///
/// # Errors
///
/// The declines of [`QuadraticField::fundamental_unit`] and of
/// [`regulator_of_unit`].
pub fn regulator(
    field: &QuadraticField,
    precision: u32,
) -> Result<RegulatorCertificate, RealDecline> {
    let unit = field.fundamental_unit()?;
    regulator_of_unit(&unit, precision)
}

/// `ln` of the fundamental solution of `x² − d·y² = 1`, which is `R` when the
/// fundamental unit has norm `+1` and `2R` when it has norm `−1`.
///
/// The `fundamental_certified` flag on the result is always `false`: see
/// [`QuadraticField::pell_unit`] for why minimality is not certified there.
///
/// # Errors
///
/// The declines of [`QuadraticField::pell_unit`] and of
/// [`regulator_of_unit`].
pub fn pell_regulator(
    field: &QuadraticField,
    precision: u32,
) -> Result<RegulatorCertificate, RealDecline> {
    let unit = field.pell_unit()?;
    regulator_of_unit(&unit, precision)
}
