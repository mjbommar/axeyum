//! Coordinatised Euclidean geometry: theorems as ideal-membership questions,
//! settled by a **Nullstellensatz cofactor certificate**.
//!
//! [`crate::geometry`] decides positional predicates at *concrete* rational
//! coordinates. This module states them at **symbolic** coordinates: every point
//! is a pair of indeterminates, every predicate is a polynomial in
//! [`crate::mvpoly::MvPoly`] that vanishes exactly on the configurations
//! satisfying it. A theorem
//!
//! ```text
//! h₁ = 0, …, hₙ = 0   (hypotheses)      ⟹   c = 0   (conclusion)
//! ```
//!
//! then becomes the question "does `c` lie in the ideal generated by the `hᵢ`?",
//! and [`crate::groebner_cert`] answers it with an **identity**
//!
//! ```text
//! c = Σᵢ uᵢ · hᵢ
//! ```
//!
//! that a checker re-derives with polynomial addition and multiplication alone.
//! At any common zero of the hypotheses the right-hand side is `0`, so `c` is
//! `0` — regardless of how the `uᵢ` were found, and simultaneously for **every**
//! configuration. That is the whole proof.
//!
//! # Non-degeneracy is explicit, or the theorem is false
//!
//! Mechanised geometry's characteristic failure is a proof that silently holds
//! only away from degenerate configurations — the collinear "triangle", the
//! coincident vertices. Many classical theorems' conclusions are not in the plain
//! hypothesis ideal at all; they are in the **saturation** of that ideal by the
//! non-degeneracy conditions. So a condition `d ≠ 0` is admitted here only by
//! being *named* and turned into a generator via the Rabinowitsch trick: a fresh
//! variable `z` and the generator `d·z − 1`. The certificate then reads
//!
//! ```text
//! c = Σᵢ uᵢ · hᵢ + w · (d·z − 1)
//! ```
//!
//! and specialising `z := 1/d` — legitimate exactly when `d ≠ 0` — kills the last
//! term. The condition is therefore visible in the artifact rather than assumed
//! in prose, and [`certify`] reports the **smallest** set of conditions that makes
//! the reduction succeed, so a theorem that needs none says so.
//!
//! # What a certificate does and does not establish
//!
//! The identity is an identity in `ℚ[coordinates, z…]`, hence valid over every
//! field of characteristic zero. Two things it does **not** do:
//!
//! - It says nothing about configurations where a saturating `d` vanishes. Those
//!   are exactly where these theorems can be false, which is why
//!   [`DegenerateWitness`] exists and is checked.
//! - It does not certify that a polynomial *means* the geometric predicate it is
//!   named after. That link is the coordinatisation, and it is an assumption.

